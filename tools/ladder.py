#!/usr/bin/env python3
"""ladder.py: maintainer-eligibility report (spec node ECO.COMM.LADDER).

    python tools/ladder.py --log <git-log.txt> --reviews <reviews.json> --now <ISO8601>
                           [--config <json>] [--json | --md]

Standard library only, fully offline and deterministic. It runs no subprocess (not even `git`)
and opens no network connection. Both inputs are recorded files:

  --log      the output of
             git log --format=%H%x00%an%x00%ae%x00%cI%x00%s
             run on the main branch (one commit per line, five NUL-separated fields);
  --reviews  a JSON list exported from the forge:
             [{pr, reviewer, state, body, inline_comments, at, node_ids[]}].

The current time is always given with --now; commits and reviews after it are ignored. Output is
sorted and byte-identical for the same inputs.

The report lists, per domain, the contributors who meet the GOVERNANCE.md nomination thresholds,
with the commits and reviews each count is based on. It is information for people: it nominates
no one and grants no role, permission or access.

Exit codes: 0 success; 1 an input error, printed to stderr as `LADDER-<CODE>: <message>`
(LADDER-GIT for the recorded log, LADDER-INPUT for the review export and options, LADDER-CONFIG,
LADDER-OUTPUT when the report cannot be written, e.g. a closed pipe);
2 a command-line usage error.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(Path(__file__).resolve().parent))

from claims import ClaimsError, fmt_time  # noqa: E402  (ECO.COMM.CLAIM's time helpers)
from claims import parse_time as _claims_parse_time  # noqa: E402
from rfc import RfcError, decode, read_bounded  # noqa: E402  (ECO.COMM.RFC's bounded readers)
from scope import ID_RE as NODE_ID_RE  # noqa: E402  (ECO.COMM.SCOPE's node ID rule)

DEFAULT_CONFIG = ROOT / "tools" / "ladder_config.json"
TOOL = "tools/ladder.py"
HEADER = "Generated by tools/ladder.py. Do not edit."
NOTICE = ("This report lists eligibility only. It is not a nomination and grants no role, "
          "permission or access; nominations are made by people as GOVERNANCE.md describes.")

MAX_LOG_BYTES = 64 << 20  # 64 MiB, about 400 000 commits
MAX_REVIEWS_BYTES = 16 << 20  # 16 MiB
MAX_CONFIG_BYTES = 64 << 10  # 64 KiB
MAX_THRESHOLD = 10000
MAX_WINDOW_DAYS = 3660

EXPANSION_RE = re.compile(r"^spec\(([A-Z0-9.]+)\): (split into \d+ children|leaf|blocked on D-\d+)")
REVERT_RE = re.compile(r'^Revert "spec\(([A-Z0-9.]+)\): split')
PR_SUFFIX_RE = re.compile(r" \(#[0-9]+\)$")  # what a squash merge appends to a subject
EXPLICIT_ZONE_RE = re.compile(r"T.*(?:[Zz]|[+-][0-9]{2}:?[0-9]{2})$")
SHA_RE = re.compile(r"^(?:[0-9a-f]{40}|[0-9a-f]{64})$")
NOREPLY_RE = re.compile(r"^(?:[0-9]+\+)?([a-z0-9](?:[a-z0-9-]*[a-z0-9])?)@users\.noreply\.github\.com$")
CONTROL_RE = re.compile(r"[\x00-\x1f\x7f]")

CONFIG_KEYS = {"min_expansions", "alt_min_expansions", "alt_min_reviews", "revert_window_days",
               "substantive_states", "substantive_requires_content", "aliases"}
REQUIRED_CONFIG_KEYS = {"min_expansions", "alt_min_expansions", "alt_min_reviews", "revert_window_days"}
DEFAULT_SUBSTANTIVE_STATES = ["approved", "changes requested"]


class LadderError(Exception):
    def __init__(self, code: str, message: str) -> None:
        super().__init__(message)
        self.code = code
        self.message = message


# ---------------------------------------------------------------- small helpers


def parse_time(value, what: str, code: str = "LADDER-INPUT") -> datetime:
    """An ISO 8601 time as aware UTC (claims.parse_time), with every failure as a LadderError."""
    if not isinstance(value, str) or not value.strip():
        raise LadderError(code, f"{what} must be an ISO 8601 time string")
    if not EXPLICIT_ZONE_RE.search(value.strip()):
        raise LadderError(code, f"{what} must be a date and time with an explicit Z or UTC offset, "
                                f"got {value!r}")
    try:
        return _claims_parse_time(value)
    except (ClaimsError, ValueError, OverflowError):
        raise LadderError(code, f"{what} is not a valid ISO 8601 time: {value!r}") from None


def read_input(path: str, limit: int, code: str, what: str) -> str:
    """Bounded, symlink-refusing UTF-8 read via rfc.read_bounded / rfc.decode."""
    try:
        return decode(read_bounded(Path(path), limit, code, what), code, f"{what} {path}")
    except RfcError as e:
        raise LadderError(code, e.message) from None


def load_json(path: str, limit: int, code: str, what: str):
    text = read_input(path, limit, code, what)

    def no_duplicates(pairs):
        obj = {}
        for k, v in pairs:
            if k in obj:
                raise LadderError(code, f"{what} {path} repeats the key {k!r} in one object")
            obj[k] = v
        return obj

    try:
        return json.loads(text, object_pairs_hook=no_duplicates)
    except json.JSONDecodeError as e:
        raise LadderError(code, f"{what} {path} is not valid JSON: {e.msg} at line {e.lineno}") from None
    except (ValueError, RecursionError):
        raise LadderError(code, f"{what} {path} is not valid JSON or is nested too deeply") from None


def domain_of(node_id: str):
    """The domain (first ID segment) of a well-formed node ID, else None."""
    return node_id.split(".", 1)[0] if NODE_ID_RE.match(node_id) else None


def is_int(v) -> bool:
    return isinstance(v, int) and not isinstance(v, bool)


# ---------------------------------------------------------------- config


def load_config(path: str) -> dict:
    cfg = load_json(path, MAX_CONFIG_BYTES, "LADDER-CONFIG", "config")
    if not isinstance(cfg, dict):
        raise LadderError("LADDER-CONFIG", f"config {path} must be a JSON object")
    unknown = sorted(set(cfg) - CONFIG_KEYS)
    if unknown:
        raise LadderError("LADDER-CONFIG", f"config {path} has unknown keys: {', '.join(unknown)}")
    missing = sorted(REQUIRED_CONFIG_KEYS - set(cfg))
    if missing:
        raise LadderError("LADDER-CONFIG", f"config {path} lacks keys: {', '.join(missing)}")
    out = {}
    for key in sorted(REQUIRED_CONFIG_KEYS):
        top = MAX_WINDOW_DAYS if key == "revert_window_days" else MAX_THRESHOLD
        v = cfg[key]
        if not is_int(v) or not 1 <= v <= top:
            raise LadderError("LADDER-CONFIG", f"config key {key} must be an integer from 1 to {top}")
        out[key] = v
    states = cfg.get("substantive_states", DEFAULT_SUBSTANTIVE_STATES)
    if not isinstance(states, list) or not states or not all(isinstance(s, str) and s.strip() for s in states):
        raise LadderError("LADDER-CONFIG", "config key substantive_states must be a non-empty list of strings")
    out["substantive_states"] = sorted({norm_state(s) for s in states})
    content = cfg.get("substantive_requires_content", True)
    if not isinstance(content, bool):
        raise LadderError("LADDER-CONFIG", "config key substantive_requires_content must be true or false")
    out["substantive_requires_content"] = content
    aliases = cfg.get("aliases", {})
    if not isinstance(aliases, dict):
        raise LadderError("LADDER-CONFIG", "config key aliases must map an email or forge login to a person")
    out["aliases"] = {}
    for key, person in aliases.items():
        k = key.strip().casefold()
        if not k or CONTROL_RE.search(k):
            raise LadderError("LADDER-CONFIG", f"aliases key {key!r} must be a non-empty email or login")
        if k in out["aliases"]:
            raise LadderError("LADDER-CONFIG", f"aliases keys collide when case and spaces are ignored: {key!r}")
        if not isinstance(person, str) or not person.strip() or CONTROL_RE.search(person):
            raise LadderError("LADDER-CONFIG", f"aliases entry {key!r} must name a person (non-empty string)")
        out["aliases"][k] = person.strip().casefold()
    return out


def norm_state(state: str) -> str:
    """`APPROVED`, `CHANGES_REQUESTED` (GitHub) and `changes requested` (spec) compare equal."""
    return " ".join(state.replace("_", " ").split()).casefold()


# ---------------------------------------------------------------- identities


def person_for_email(email: str, aliases: dict) -> str:
    """Normalise a commit email: alias table first, then a GitHub noreply address's login,
    then that login's alias, else the lower-cased email itself."""
    e = email.strip().casefold()
    if e in aliases:
        return aliases[e]
    m = NOREPLY_RE.match(e)
    if m:
        return aliases.get(m.group(1), m.group(1))
    return e


def person_for_login(login: str, aliases: dict) -> str:
    k = login.strip().casefold()
    return aliases.get(k, k)


# ---------------------------------------------------------------- history


def parse_log(text: str, aliases: dict) -> list:
    """Commits from the recorded `git log --format=%H%x00%an%x00%ae%x00%cI%x00%s` output."""
    commits, seen = [], set()
    for n, line in enumerate(text.split("\n"), 1):
        if line.endswith("\r"):
            line = line[:-1]
        if not line:
            continue
        fields = line.split("\x00")
        if len(fields) != 5:
            raise LadderError("LADDER-GIT", f"log line {n}: expected 5 NUL-separated fields "
                                            f"(%H %an %ae %cI %s), found {len(fields)}")
        sha, _name, email, when, subject = fields
        if not SHA_RE.match(sha):
            raise LadderError("LADDER-GIT", f"log line {n}: {sha[:80]!r} is not a commit hash")
        if sha in seen:
            raise LadderError("LADDER-GIT", f"log line {n}: commit {sha} appears twice")
        seen.add(sha)
        if not email.strip() or CONTROL_RE.search(email):
            raise LadderError("LADDER-GIT", f"log line {n}: commit {sha} has an empty or malformed author email")
        commits.append({
            "sha": sha,
            "person": person_for_email(email, aliases),
            "at": parse_time(when, f"log line {n} commit date", "LADDER-GIT"),
            "subject": subject,
        })
    return commits


# ---------------------------------------------------------------- reviews


def parse_reviews(data, cfg: dict) -> list:
    if not isinstance(data, list):
        raise LadderError("LADDER-INPUT", "review export must be a JSON list of review objects")
    out = []
    for i, r in enumerate(data):
        where = f"review entry {i}"
        if not isinstance(r, dict):
            raise LadderError("LADDER-INPUT", f"{where} is not an object")
        pr = r.get("pr")
        if not is_int(pr) or pr < 1:
            raise LadderError("LADDER-INPUT", f"{where}: pr must be a positive integer")
        reviewer, state = r.get("reviewer"), r.get("state")
        if not isinstance(reviewer, str) or not reviewer.strip() or CONTROL_RE.search(reviewer):
            raise LadderError("LADDER-INPUT", f"{where}: reviewer must be a non-empty login")
        if not isinstance(state, str):
            raise LadderError("LADDER-INPUT", f"{where}: state must be a string")
        body = r.get("body")
        if body is None:
            body = ""
        if not isinstance(body, str):
            raise LadderError("LADDER-INPUT", f"{where}: body must be a string or null")
        inline = r.get("inline_comments", 0)
        if isinstance(inline, list):
            inline = len(inline)
        if inline is None:
            inline = 0
        if not is_int(inline) or inline < 0:
            raise LadderError("LADDER-INPUT", f"{where}: inline_comments must be a count or a list")
        node_ids = r.get("node_ids")
        if not isinstance(node_ids, list) or not all(isinstance(x, str) for x in node_ids):
            raise LadderError("LADDER-INPUT", f"{where}: node_ids must be a list of node ID strings")
        domains = sorted({d for d in map(domain_of, node_ids) if d})
        substantive = norm_state(state) in cfg["substantive_states"] and (
            not cfg["substantive_requires_content"] or bool(body.strip()) or inline > 0)
        out.append({
            "pr": pr,
            "person": person_for_login(reviewer, cfg["aliases"]),
            "at": parse_time(r.get("at"), f"{where} at"),
            "domains": domains,
            "substantive": substantive,
        })
    return out


# ---------------------------------------------------------------- report


def build_report(commits: list, reviews: list, cfg: dict, now: datetime) -> dict:
    try:
        window_start = now - timedelta(days=cfg["revert_window_days"])
    except OverflowError:
        raise LadderError("LADDER-INPUT", f"--now {fmt_time(now)} minus the revert window is before year 1") from None
    warnings = []
    expansions: dict = {}  # (domain, person) -> list of commit refs
    splits_by_subject: dict = {}  # subject without a squash-merge " (#N)" -> [(at, sha, domain, person)]
    splits_by_node: dict = {}  # node ID -> [(at, sha, domain, person)]
    others_by_node: dict = {}  # node ID -> [(at, sha)] for leaf and blocked expansions
    past = sorted((c for c in commits if c["at"] <= now), key=lambda c: (c["at"], c["sha"]))
    for c in past:
        m = EXPANSION_RE.match(c["subject"])
        if not m:
            continue
        node, kind = m.group(1), m.group(2)
        domain = domain_of(node)
        if domain is None:
            warnings.append(f"commit {c['sha']}: node ID {node!r} is malformed; not counted")
            continue
        expansions.setdefault((domain, c["person"]), []).append(
            {"sha": c["sha"], "node": node, "kind": kind.split(" ", 1)[0], "at": fmt_time(c["at"])})
        if kind.startswith("split"):
            ref = (c["at"], c["sha"], domain, c["person"])
            splits_by_subject.setdefault(PR_SUFFIX_RE.sub("", c["subject"]), []).append(ref)
            splits_by_node.setdefault(node, []).append(ref)
        else:
            others_by_node.setdefault(node, []).append((c["at"], c["sha"]))

    # A revert is matched to the split it reverts by subject (ignoring a squash merge's " (#N)" on
    # either side), else by node ID. One that still matches nothing fails closed: no expansion of
    # that node counts for anyone, and the report says so.
    blocked: dict = {}  # (domain, person) -> list of revert refs inside the window
    uncounted: set = set()  # commit hashes of expansions withdrawn by an unattributed revert
    for c in past:
        m = REVERT_RE.match(c["subject"])
        if not m:
            continue
        node = m.group(1)
        original = PR_SUFFIX_RE.sub("", c["subject"])[len('Revert "'):]
        original = original[:-1] if original.endswith('"') else original
        earlier = [s for s in splits_by_subject.get(PR_SUFFIX_RE.sub("", original), []) if s[0] <= c["at"]]
        if not earlier:
            earlier = [s for s in splits_by_node.get(node, []) if s[0] <= c["at"]]
            if earlier:
                warnings.append(f"revert {c['sha']} of {node} matched split {earlier[-1][1]} by node ID only")
        if not earlier:
            withdrawn = sorted(sha for at, sha in others_by_node.get(node, []) if at <= c["at"])
            uncounted.update(withdrawn)
            warnings.append(f"revert {c['sha']} of {node} matches no split in the log; not attributed, "
                            f"and {len(withdrawn)} other expansion(s) of {node} are not counted")
            continue
        _, split_sha, domain, person = earlier[-1]
        if c["at"] >= window_start:
            blocked.setdefault((domain, person), []).append(
                {"revert": c["sha"], "split": split_sha, "at": fmt_time(c["at"])})
    if uncounted:
        expansions = {k: [e for e in v if e["sha"] not in uncounted] for k, v in expansions.items()}

    review_refs: dict = {}  # (domain, person) -> {pr: earliest substantive review time}
    for r in reviews:
        if not r["substantive"] or r["at"] > now:
            continue
        for d in r["domains"]:
            prs = review_refs.setdefault((d, r["person"]), {})
            if r["pr"] not in prs or r["at"] < prs[r["pr"]]:
                prs[r["pr"]] = r["at"]

    eligible: dict = {}
    for key in sorted(set(expansions) | set(review_refs)):
        domain, person = key
        exp = expansions.get(key, [])
        revs = review_refs.get(key, {})
        meets = len(exp) >= cfg["min_expansions"] or (
            len(exp) >= cfg["alt_min_expansions"] and len(revs) >= cfg["alt_min_reviews"])
        if not meets or key in blocked:
            continue
        eligible.setdefault(domain, []).append({
            "person": person,
            "expansions": len(exp),
            "substantive_reviews": len(revs),
            "commits": exp,
            "reviews": [{"pr": pr, "at": fmt_time(at)} for pr, at in sorted(revs.items())],
        })
    return {
        "generated_by": TOOL,
        "notice": f"{HEADER} {NOTICE}",
        "now": fmt_time(now),
        "thresholds": {k: cfg[k] for k in sorted(REQUIRED_CONFIG_KEYS)},
        "eligible": eligible,
        "warnings": sorted(warnings),
    }


def render_json(report: dict) -> str:
    return json.dumps(report, sort_keys=True, indent=2, ensure_ascii=False) + "\n"


MD_SPECIAL = re.compile(r"([\\`*_{}\[\]()#+\-.!|<>~])")


def md(text: str) -> str:
    return MD_SPECIAL.sub(r"\\\1", text)


def render_md(report: dict) -> str:
    t = report["thresholds"]
    lines = [
        f"<!-- {HEADER} -->",
        "# Maintainer-eligibility report",
        "",
        HEADER,
        "",
        NOTICE,
        "",
        f"- As of: {report['now']}",
        f"- Thresholds: at least {t['min_expansions']} merged expansions, or at least "
        f"{t['alt_min_expansions']} expansions and {t['alt_min_reviews']} substantive reviews; "
        f"no reverted split in the {t['revert_window_days']} days before the as-of time.",
        "",
    ]
    if not report["eligible"]:
        lines += ["No contributor meets the thresholds in any domain.", ""]
    for domain in sorted(report["eligible"]):
        lines += [f"## {domain}", ""]
        for e in report["eligible"][domain]:
            lines.append(f"- **{md(e['person'])}**: {e['expansions']} expansions, "
                         f"{e['substantive_reviews']} substantive reviews")
            for c in e["commits"]:
                lines.append(f"  - commit `{c['sha'][:12]}` {c['kind']} {c['node']} ({c['at']})")
            for r in e["reviews"]:
                lines.append(f"  - review on PR #{r['pr']} ({r['at']})")
        lines.append("")
    if report["warnings"]:
        lines += ["## Warnings", ""]
        lines += [f"- {md(w)}" for w in report["warnings"]]
        lines.append("")
    return "\n".join(lines)


# ---------------------------------------------------------------- main


class _Parser(argparse.ArgumentParser):
    def error(self, message: str):  # usage errors: exit 2 with a one-line message, no traceback
        self.print_usage(sys.stderr)
        sys.stderr.write(f"ladder.py: error: {message}\n")
        raise SystemExit(2)


def build_parser() -> argparse.ArgumentParser:
    ap = _Parser(prog="ladder.py", description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--log", required=True, help="recorded `git log --format=%%H%%x00%%an%%x00%%ae%%x00%%cI%%x00%%s`")
    ap.add_argument("--reviews", required=True, help="review export JSON")
    ap.add_argument("--now", required=True, help="as-of time, ISO 8601, e.g. 2026-12-01T00:00:00Z")
    ap.add_argument("--config", default=str(DEFAULT_CONFIG), help="thresholds and aliases JSON")
    fmt = ap.add_mutually_exclusive_group()
    fmt.add_argument("--json", action="store_true", help="emit JSON")
    fmt.add_argument("--md", action="store_true", help="emit Markdown (the default)")
    return ap


def run(args) -> str:
    now = parse_time(args.now, "--now")
    cfg = load_config(args.config)
    commits = parse_log(read_input(args.log, MAX_LOG_BYTES, "LADDER-GIT", "log"), cfg["aliases"])
    reviews = parse_reviews(load_json(args.reviews, MAX_REVIEWS_BYTES, "LADDER-INPUT", "review export"), cfg)
    report = build_report(commits, reviews, cfg, now)
    return render_json(report) if args.json else render_md(report)


def main(argv=None, out=None) -> int:
    args = build_parser().parse_args(argv)
    try:
        text = run(args)
    except LadderError as e:
        sys.stderr.write(f"{e.code}: {e.message}\n")
        return 1
    stream = out if out is not None else sys.stdout.buffer
    try:
        stream.write(text.encode("utf-8"))
        stream.flush()
    except OSError as e:  # BrokenPipeError included: a closed pipe is an error, not a traceback
        if out is None:
            _silence_stdout()
        sys.stderr.write(f"LADDER-OUTPUT: cannot write the report: {e.strerror or e}\n")
        return 1
    return 0


def _silence_stdout() -> None:
    """Point stdout at the null device so the interpreter's exit-time flush cannot fail again."""
    try:
        devnull = os.open(os.devnull, os.O_WRONLY)
        os.dup2(devnull, sys.stdout.fileno())
        os.close(devnull)
    except (OSError, ValueError):
        pass


if __name__ == "__main__":
    sys.exit(main())
