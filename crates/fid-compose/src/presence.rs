//! The presence-provider source scan (REQ-AUTO.SURF.COMPOSE-009).
//!
//! [`scan_workspace`] reads the shipped Rust source of every workspace crate (`crates/*` and
//! `vendor/*/crate`; every `.rs` file except under `tests/`, `benches/`, `examples/` and
//! `target/`) and reports each `impl ... HumanPresence for <Type>`, with or without a path
//! prefix or generic arguments, outside items under a `#[cfg(test)]` attribute.
//! [`unlisted`] keeps the findings whose type is not in [`crate::PRESENCE_PROVIDERS`].
//!
//! The scan reads text, not expanded code: comments and string and character literals are
//! blanked first, so a mention in a doc comment or a string never counts. An impl generated by
//! a macro whose source does not contain it cannot be seen, so every `macro_rules!` definition
//! whose body names `HumanPresence` is reported too (as type `macro_rules! <name>`); procedural
//! macros are left to review (leaf Design). An import or re-export that renames the trait
//! (`HumanPresence as <alias>`) would let `impl <alias> for T` pass the impl rule, so every
//! such rename in shipped code is reported too (as type `HumanPresence as <alias>`).

use crate::host::Platform;
use std::fs;
use std::io;
use std::path::{Path, PathBuf};

/// The trait the scan looks for.
pub const TRAIT: &str = "HumanPresence";

/// One implementation (or macro) found.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct Finding {
    /// The implementing type's name (its last path segment, without generic arguments),
    /// `macro_rules! <name>`, or `HumanPresence as <alias>`.
    pub ty: String,
    /// The file it is in.
    pub file: PathBuf,
}

/// Directories of a crate that are never shipped.
const NOT_SHIPPED: [&str; 4] = ["tests", "benches", "examples", "target"];

/// The findings of every workspace crate below `workspace` (`crates/*`, `vendor/*/crate`),
/// sorted.
pub fn scan_workspace(workspace: &Path) -> io::Result<Vec<Finding>> {
    let mut crates = Vec::new();
    for entry in fs::read_dir(workspace.join("crates"))? {
        let path = entry?.path();
        if path.is_dir() {
            crates.push(path);
        }
    }
    if let Ok(vendor) = fs::read_dir(workspace.join("vendor")) {
        for entry in vendor {
            let path = entry?.path().join("crate");
            if path.is_dir() {
                crates.push(path);
            }
        }
    }
    let mut out = Vec::new();
    for dir in crates {
        out.extend(scan_crate(&dir)?);
    }
    out.sort();
    Ok(out)
}

/// The findings of one crate directory: every `.rs` file below `dir`, except under its
/// `tests/`, `benches/`, `examples/` and `target/` folders, sorted.
pub fn scan_crate(dir: &Path) -> io::Result<Vec<Finding>> {
    let mut files = Vec::new();
    collect(dir, true, &mut files)?;
    files.sort();
    let mut out = Vec::new();
    for file in files {
        let text = fs::read_to_string(&file)?;
        for ty in scan_text(&text) {
            out.push(Finding { ty, file: file.clone() });
        }
    }
    out.sort();
    Ok(out)
}

fn collect(dir: &Path, top: bool, out: &mut Vec<PathBuf>) -> io::Result<()> {
    for entry in fs::read_dir(dir)? {
        let entry = entry?;
        let path = entry.path();
        let kind = entry.file_type()?;
        if kind.is_dir() {
            let name = entry.file_name();
            if top && NOT_SHIPPED.iter().any(|n| name.to_str() == Some(n)) {
                continue;
            }
            if !top && name.to_str() == Some("target") {
                continue;
            }
            collect(&path, false, out)?;
        } else if kind.is_file() && path.extension().and_then(|e| e.to_str()) == Some("rs") {
            out.push(path);
        }
    }
    Ok(())
}

/// The findings whose type `allowed` does not list.
pub fn unlisted(findings: &[Finding], allowed: &[(Platform, &str)]) -> Vec<Finding> {
    findings.iter().filter(|f| !allowed.iter().any(|(_, ty)| *ty == f.ty)).cloned().collect()
}

// ------------------------------------------------------------------ lexing

/// `text` with every comment and the inside of every string and character literal replaced
/// by spaces (newlines kept), so only code remains.
pub fn strip(text: &str) -> String {
    let c: Vec<char> = text.chars().collect();
    let mut out = String::with_capacity(text.len());
    let blank = |out: &mut String, ch: char| out.push(if ch == '\n' { '\n' } else { ' ' });
    let mut i = 0;
    while i < c.len() {
        let ch = c[i];
        let next = c.get(i + 1).copied();
        if ch == '/' && next == Some('/') {
            while i < c.len() && c[i] != '\n' {
                blank(&mut out, c[i]);
                i += 1;
            }
        } else if ch == '/' && next == Some('*') {
            let mut depth = 0usize;
            while i < c.len() {
                if c[i] == '/' && c.get(i + 1) == Some(&'*') {
                    depth += 1;
                    out.push_str("  ");
                    i += 2;
                } else if c[i] == '*' && c.get(i + 1) == Some(&'/') {
                    depth = depth.saturating_sub(1);
                    out.push_str("  ");
                    i += 2;
                    if depth == 0 {
                        break;
                    }
                } else {
                    blank(&mut out, c[i]);
                    i += 1;
                }
            }
        } else if ch == 'r' && raw_string_start(&c, i).is_some() && !ident_before(&c, i) {
            let hashes = raw_string_start(&c, i).unwrap_or(0);
            // `r`, the hashes and the opening quote.
            for _ in 0..hashes + 2 {
                out.push(' ');
            }
            i += hashes + 2;
            while i < c.len() {
                if c[i] == '"' && (1..=hashes).all(|k| c.get(i + k) == Some(&'#')) {
                    for _ in 0..hashes + 1 {
                        out.push(' ');
                    }
                    i += hashes + 1;
                    break;
                }
                blank(&mut out, c[i]);
                i += 1;
            }
        } else if ch == '"' {
            out.push(' ');
            i += 1;
            while i < c.len() {
                if c[i] == '\\' {
                    blank(&mut out, c[i]);
                    if let Some(&e) = c.get(i + 1) {
                        blank(&mut out, e);
                    }
                    i += 2;
                    continue;
                }
                if c[i] == '"' {
                    out.push(' ');
                    i += 1;
                    break;
                }
                blank(&mut out, c[i]);
                i += 1;
            }
        } else if ch == '\'' {
            if let Some(len) = char_literal_len(&c, i) {
                for &x in c.get(i..i + len).unwrap_or_default() {
                    blank(&mut out, x);
                }
                i += len;
            } else {
                // A lifetime or label.
                out.push(ch);
                i += 1;
            }
        } else {
            out.push(ch);
            i += 1;
        }
    }
    out
}

/// The number of `#`s of a raw string starting at `i` (`r"`, `r#"`, ...), if one does.
fn raw_string_start(c: &[char], i: usize) -> Option<usize> {
    let mut j = i + 1;
    while c.get(j) == Some(&'#') {
        j += 1;
    }
    (c.get(j) == Some(&'"')).then_some(j - i - 1)
}

/// Whether `c[i]` continues an identifier (so `r` is not a raw-string prefix), allowing the
/// byte-string prefix `b`.
fn ident_before(c: &[char], i: usize) -> bool {
    match i.checked_sub(1).and_then(|p| c.get(p)) {
        Some('b') => i.checked_sub(2).and_then(|p| c.get(p)).is_some_and(|x| x.is_alphanumeric() || *x == '_'),
        Some(x) => x.is_alphanumeric() || *x == '_',
        None => false,
    }
}

/// The length of a character literal starting at `i`, or `None` for a lifetime.
fn char_literal_len(c: &[char], i: usize) -> Option<usize> {
    match c.get(i + 1) {
        Some('\\') => {
            let mut j = i + 2;
            while j < c.len() && j < i + 12 {
                if c[j] == '\'' {
                    return Some(j - i + 1);
                }
                j += 1;
            }
            None
        }
        Some(_) if c.get(i + 2) == Some(&'\'') => Some(3),
        _ => None,
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
enum Tok {
    Ident(String),
    Punct(String),
}

impl Tok {
    fn is(&self, s: &str) -> bool {
        match self {
            Tok::Ident(t) | Tok::Punct(t) => t == s,
        }
    }

    fn ident(&self) -> Option<&str> {
        match self {
            Tok::Ident(t) => Some(t),
            Tok::Punct(_) => None,
        }
    }
}

fn tokens(code: &str) -> Vec<Tok> {
    let c: Vec<char> = code.chars().collect();
    let mut out = Vec::new();
    let mut i = 0;
    while i < c.len() {
        let ch = c[i];
        if ch.is_whitespace() {
            i += 1;
        } else if ch.is_alphanumeric() || ch == '_' {
            let start = i;
            while i < c.len() && (c[i].is_alphanumeric() || c[i] == '_') {
                i += 1;
            }
            out.push(Tok::Ident(c[start..i].iter().collect()));
        } else if (ch == '-' || ch == '=') && c.get(i + 1) == Some(&'>') {
            out.push(Tok::Punct(format!("{ch}>")));
            i += 2;
        } else {
            out.push(Tok::Punct(ch.to_string()));
            i += 1;
        }
    }
    out
}

/// The index just past the delimited group opening at `open` (`(`, `[`, `{` or `<`), or the
/// end of the tokens.
fn close_of(t: &[Tok], open: usize) -> usize {
    let (o, c) = match &t[open] {
        Tok::Punct(p) if p == "(" => ("(", ")"),
        Tok::Punct(p) if p == "[" => ("[", "]"),
        Tok::Punct(p) if p == "<" => ("<", ">"),
        _ => ("{", "}"),
    };
    let mut depth = 0usize;
    let mut i = open;
    while i < t.len() {
        if t[i].is(o) {
            depth += 1;
        } else if t[i].is(c) {
            depth = depth.saturating_sub(1);
            if depth == 0 {
                return i + 1;
            }
        }
        i += 1;
    }
    t.len()
}

/// Whether `#[cfg(test)]` starts at `i`.
fn cfg_test_at(t: &[Tok], i: usize) -> bool {
    let want = ["#", "[", "cfg", "(", "test", ")", "]"];
    want.iter().enumerate().all(|(k, w)| t.get(i + k).is_some_and(|x| x.is(w)))
}

/// The end of the item that starts at `i` (after its attributes): just past its `;` or its
/// `{ ... }` body, whichever comes first at nesting depth 0.
fn item_end(t: &[Tok], mut i: usize) -> usize {
    while i < t.len() && t[i].is("#") && t.get(i + 1).is_some_and(|x| x.is("[")) {
        i = close_of(t, i + 1);
    }
    while i < t.len() {
        if t[i].is(";") {
            return i + 1;
        }
        if t[i].is("{") {
            return close_of(t, i);
        }
        if t[i].is("(") || t[i].is("[") {
            i = close_of(t, i);
            continue;
        }
        i += 1;
    }
    t.len()
}

/// The tokens of `code` with every item under `#[cfg(test)]` removed.
fn shipped(t: Vec<Tok>) -> Vec<Tok> {
    let mut out = Vec::with_capacity(t.len());
    let mut i = 0;
    while i < t.len() {
        if cfg_test_at(&t, i) {
            i = item_end(&t, i + 7);
            continue;
        }
        out.push(t[i].clone());
        i += 1;
    }
    out
}

/// The last identifier of `t` outside `<...>` groups.
fn last_name(t: &[Tok]) -> Option<String> {
    let mut depth = 0usize;
    let mut name = None;
    for tok in t {
        if tok.is("<") {
            depth += 1;
        } else if tok.is(">") {
            depth = depth.saturating_sub(1);
        } else if depth == 0 {
            if let Some(id) = tok.ident() {
                if !matches!(id, "dyn" | "mut" | "const") {
                    name = Some(id.to_string());
                }
            }
        }
    }
    name
}

/// The type names of every `impl HumanPresence for T` in shipped code of one file's text,
/// and `macro_rules! <name>` for every macro definition whose body names `HumanPresence`.
pub fn scan_text(text: &str) -> Vec<String> {
    let t = shipped(tokens(&strip(text)));
    let mut out = Vec::new();
    let mut i = 0;
    while i < t.len() {
        if t[i].is("macro_rules") && t.get(i + 1).is_some_and(|x| x.is("!")) {
            let name = t.get(i + 2).and_then(Tok::ident).unwrap_or("?").to_string();
            let open = i + 3;
            if open < t.len() {
                let end = close_of(&t, open);
                if t[open..end].iter().any(|x| x.is(TRAIT)) {
                    out.push(format!("macro_rules! {name}"));
                }
                i = end;
                continue;
            }
        }
        // A renamed import or re-export hides the trait from the impl rule: report the alias.
        if t[i].is(TRAIT) && t.get(i + 1).is_some_and(|x| x.is("as")) {
            let alias = t.get(i + 2).and_then(Tok::ident).unwrap_or("?");
            out.push(format!("{TRAIT} as {alias}"));
        }
        if t[i].is("impl") {
            let mut j = i + 1;
            if t.get(j).is_some_and(|x| x.is("<")) {
                j = close_of(&t, j);
            }
            // The trait path runs to `for` at angle depth 0; the header ends at `{` or `;`.
            let mut depth = 0usize;
            let mut k = j;
            let mut for_at = None;
            while k < t.len() && !t[k].is("{") && !t[k].is(";") {
                if t[k].is("<") {
                    depth += 1;
                } else if t[k].is(">") {
                    depth = depth.saturating_sub(1);
                } else if depth == 0 && t[k].is("for") {
                    for_at = Some(k);
                    break;
                }
                k += 1;
            }
            if let Some(f) = for_at {
                if last_name(&t[j..f]).as_deref() == Some(TRAIT) {
                    let mut e = f + 1;
                    let mut d = 0usize;
                    while e < t.len() && !t[e].is("{") && !t[e].is(";") && !(d == 0 && t[e].is("where")) {
                        if t[e].is("<") {
                            d += 1;
                        } else if t[e].is(">") {
                            d = d.saturating_sub(1);
                        }
                        e += 1;
                    }
                    out.push(last_name(&t[f + 1..e]).unwrap_or_else(|| "?".to_string()));
                }
            }
        }
        i += 1;
    }
    out
}
