//! Generated support matrix page (spec node `PLAT.MATRIX.PAGE`): renders
//! `platform/support-matrix.toml` to the Markdown page `docs/platform/support-matrix.md`, and
//! the `--check` comparison that fails when the committed page and the file disagree.
//!
//! Determinism D0: the page is a pure function of the matrix file's bytes. Sections follow a
//! fixed OS family order, rows are sorted by (arch, version_min), every table cell is escaped
//! for Markdown and HTML, and lines end in LF on every platform (REQ-PLAT.MATRIX.PAGE-004).

use crate::matrix::{self, Arch, OsFamily, Row, Tier, Validation};
use std::fmt::Write as _;

/// The matrix file read when `--matrix` is not given.
pub const DEFAULT_MATRIX: &str = "platform/support-matrix.toml";
/// Where the project's page is committed.
pub const DEFAULT_PAGE: &str = "docs/platform/support-matrix.md";
/// Largest committed page `--check` reads; a larger file is reported as a mismatch.
pub const MAX_PAGE_BYTES: usize = 64 * 1024 * 1024;
/// Context lines around the changed region of a unified diff.
pub const DIFF_CONTEXT: usize = 3;
/// Above this many line pairs the diff shows the whole changed region as removed then added
/// instead of computing a longest common subsequence.
pub const MAX_LCS_CELLS: usize = 4_000_000;

/// Section order (Build prompt): windows, macos, ubuntu, debian, fedora, rhel.
const FAMILY_ORDER: [OsFamily; 6] =
    [OsFamily::Windows, OsFamily::Macos, OsFamily::Ubuntu, OsFamily::Debian, OsFamily::Fedora, OsFamily::Rhel];

fn family_title(os: OsFamily) -> &'static str {
    match os {
        OsFamily::Windows => "Windows",
        OsFamily::Macos => "macOS",
        OsFamily::Ubuntu => "Ubuntu",
        OsFamily::Debian => "Debian",
        OsFamily::Fedora => "Fedora",
        OsFamily::Rhel => "RHEL",
    }
}

fn tier_title(t: Tier) -> &'static str {
    match t {
        Tier::Tier1 => "Tier 1",
        Tier::Tier2 => "Tier 2",
        Tier::Tier3 => "Tier 3",
    }
}

/// Escapes text for one GFM table cell: control characters (including CR, LF and tab, which
/// would break the row) become a space; `&`, `<` and `>` become HTML entities; and
/// `` \ ` * _ [ ] | ~ $ `` get a backslash so they render literally.
pub fn escape_cell(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        match c {
            '\u{0}'..='\u{1f}' | '\u{7f}' => out.push(' '),
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '\\' | '`' | '*' | '_' | '[' | ']' | '|' | '~' | '$' => {
                out.push('\\');
                out.push(c);
            }
            _ => out.push(c),
        }
    }
    out
}

/// The version bounds of each `[[row]]` as written in the file (so `22.04` is not shown as
/// `22.4`), in file order. Entries are `None` where the text cannot be read back.
fn written_versions(bytes: &[u8]) -> Vec<(Option<String>, Option<String>)> {
    let Some(table) = std::str::from_utf8(bytes).ok().and_then(|t| t.parse::<toml::Table>().ok()) else {
        return Vec::new();
    };
    let Some(toml::Value::Array(rows)) = table.get("row") else {
        return Vec::new();
    };
    let text = |r: &toml::Value, k: &str| r.get(k).and_then(toml::Value::as_str).map(str::to_string);
    rows.iter().map(|r| (text(r, "version_min"), text(r, "version_max"))).collect()
}

fn versions_cell(row: &Row, written: Option<&(Option<String>, Option<String>)>) -> String {
    let min = written.and_then(|w| w.0.clone()).unwrap_or_else(|| row.version_min.to_string());
    match &row.version_max {
        Some(max) => {
            let max = written.and_then(|w| w.1.clone()).unwrap_or_else(|| max.to_string());
            format!("{min} to before {max}")
        }
        None => format!("{min} and later"),
    }
}

fn arch_order(a: Arch) -> usize {
    Arch::ALL.iter().position(|x| *x == a).unwrap_or(usize::MAX)
}

/// Validates the matrix file and renders the page (REQ-PLAT.MATRIX.PAGE-001, -002, -004).
/// Any validation error is returned as the whole [`Validation`] and nothing is rendered.
pub fn render(bytes: &[u8]) -> Result<String, Validation> {
    let v = matrix::validate(bytes);
    let m = match (&v.matrix, v.errors.is_empty()) {
        (Some(m), true) => m,
        _ => return Err(v),
    };
    let written = written_versions(bytes);
    let digest = fid_types::Digest::from_bytes(fid_canon::digest_bytes(bytes).0);

    let mut out = String::new();
    let _ = writeln!(out, "<!-- generated from {DEFAULT_MATRIX} sha256:{}; do not edit -->", digest.hex());
    out.push_str("# Support matrix\n\n");
    out.push_str(
        "This page is generated by `cargo xtask plat-matrix page` from the machine-readable support matrix; \
         do not edit it by hand. Tier definitions: [tiers.md](tiers.md).\n",
    );
    if m.rows.is_empty() {
        out.push_str("\nThe matrix lists no platforms.\n");
    }
    // Families outside the fixed order (a future schema bump) follow it in declaration order.
    let extra = OsFamily::ALL.iter().copied().filter(|f| !FAMILY_ORDER.contains(f));
    for os in FAMILY_ORDER.iter().copied().chain(extra) {
        let mut group: Vec<(usize, &Row)> = m.rows.iter().enumerate().filter(|(_, r)| r.os == os).collect();
        if group.is_empty() {
            continue;
        }
        group.sort_by_key(|(_, r)| (arch_order(r.arch), r.version_min));
        let _ = write!(out, "\n## {}\n\n", family_title(os));
        out.push_str("| Versions | Arch | Tier | Since | Notes |\n|---|---|---|---|---|\n");
        for (i, r) in group {
            let cells = [
                versions_cell(r, written.get(i)),
                r.arch.to_string(),
                tier_title(r.tier).to_string(),
                r.since_phase.to_string(),
                r.notes.clone(),
            ];
            out.push('|');
            for c in &cells {
                out.push(' ');
                out.push_str(&escape_cell(c));
                out.push_str(" |");
            }
            out.push('\n');
        }
    }
    Ok(out)
}

/// Compares a committed page with the generated one (REQ-PLAT.MATRIX.PAGE-003). Returns
/// `None` when they are byte-identical, otherwise a unified diff from `committed` (labelled
/// `path`) to `generated` (labelled `path (generated)`).
pub fn check(committed: &[u8], generated: &str, path: &str) -> Option<String> {
    if committed == generated.as_bytes() {
        return None;
    }
    let old = String::from_utf8_lossy(committed);
    Some(unified_diff(&old, generated, path, &format!("{path} (generated)")))
}

/// A unified diff with one hunk spanning the changed region plus [`DIFF_CONTEXT`] lines on
/// each side. Empty when the texts are equal. Deterministic for equal inputs.
pub fn unified_diff(old: &str, new: &str, old_name: &str, new_name: &str) -> String {
    let a: Vec<&str> = old.split_inclusive('\n').collect();
    let b: Vec<&str> = new.split_inclusive('\n').collect();
    if a == b {
        return String::new();
    }
    let mut pre = 0;
    while pre < a.len() && pre < b.len() && a[pre] == b[pre] {
        pre += 1;
    }
    let mut suf = 0;
    while suf < a.len() - pre && suf < b.len() - pre && a[a.len() - 1 - suf] == b[b.len() - 1 - suf] {
        suf += 1;
    }
    let start = pre - pre.min(DIFF_CONTEXT);
    let mut body: Vec<(char, &str)> = a[start..pre].iter().map(|l| (' ', *l)).collect();
    body.extend(middle_ops(&a[pre..a.len() - suf], &b[pre..b.len() - suf]));
    let tail = a.len() - suf;
    body.extend(a[tail..tail + suf.min(DIFF_CONTEXT)].iter().map(|l| (' ', *l)));

    let old_len = body.iter().filter(|(c, _)| *c != '+').count();
    let new_len = body.iter().filter(|(c, _)| *c != '-').count();
    let first = |len: usize| if len == 0 { start } else { start + 1 };
    let mut out =
        format!("--- {old_name}\n+++ {new_name}\n@@ -{},{old_len} +{},{new_len} @@\n", first(old_len), first(new_len));
    for (c, line) in body {
        out.push(c);
        out.push_str(line);
        if !line.ends_with('\n') {
            out.push_str("\n\\ No newline at end of file\n");
        }
    }
    out
}

/// Edit script of the changed region: a longest common subsequence when it is small enough,
/// otherwise every old line removed and then every new line added.
fn middle_ops<'a>(a: &[&'a str], b: &[&'a str]) -> Vec<(char, &'a str)> {
    let (n, m) = (a.len(), b.len());
    let mut ops = Vec::with_capacity(n + m);
    if n.saturating_mul(m) > MAX_LCS_CELLS {
        ops.extend(a.iter().map(|l| ('-', *l)));
        ops.extend(b.iter().map(|l| ('+', *l)));
        return ops;
    }
    // lcs[i * w + j]: length of the LCS of a[i..] and b[j..].
    let w = m + 1;
    let mut lcs = vec![0u32; (n + 1) * w];
    for i in (0..n).rev() {
        for j in (0..m).rev() {
            lcs[i * w + j] = if a[i] == b[j] {
                lcs[(i + 1) * w + j + 1] + 1
            } else {
                std::cmp::max(lcs[(i + 1) * w + j], lcs[i * w + j + 1])
            };
        }
    }
    let (mut i, mut j) = (0, 0);
    while i < n && j < m {
        if a[i] == b[j] {
            ops.push((' ', a[i]));
            i += 1;
            j += 1;
        } else if lcs[(i + 1) * w + j] >= lcs[i * w + j + 1] {
            ops.push(('-', a[i]));
            i += 1;
        } else {
            ops.push(('+', b[j]));
            j += 1;
        }
    }
    ops.extend(a[i..].iter().map(|l| ('-', *l)));
    ops.extend(b[j..].iter().map(|l| ('+', *l)));
    ops
}
