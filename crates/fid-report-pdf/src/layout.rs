// ------------------------------------------------------------------ greedy UAX #14 wrapping

/// Wraps `text` greedily into lines fitting within `max_width_um` using UAX #14
/// [`break_opportunities`] and integer-µm glyph advances from [`FontSet::shape`].
pub fn wrap_text(
    text: &str,
    font: &FontId,
    font_size_um: i64,
    line_height_um: i64,
    max_width_um: i64,
    fonts: &FontSet,
) -> Result<Vec<ShapedLine>, LayoutError> {
    let effective_w = max_width_um.max(1);
    let mut lines = Vec::new();
    let baseline_in_line = font_size_um.min(line_height_um);

    for raw_para in text.split('\n') {
        let para_lines = wrap_paragraph(raw_para, font, font_size_um, effective_w, fonts)?;
        for line_str in para_lines {
            let has_placeholder = line_str.contains(PLACEHOLDER_PAGE_NUM) || line_str.contains(PLACEHOLDER_PAGE_COUNT);
            let render_str = if has_placeholder {
                line_str.replace([PLACEHOLDER_PAGE_NUM, PLACEHOLDER_PAGE_COUNT], "999")
            } else {
                line_str.clone()
            };
            let shaped = fonts.shape(font, &render_str, font_size_um)?;
            let y_top = (lines.len() as i64) * line_height_um;
            lines.push(ShapedLine {
                baseline_offset_um: y_top + baseline_in_line,
                height_um: line_height_um,
                runs: shaped.runs,
                text: render_str,
                font_id: font.clone(),
                font_size_um,
                placeholder_template: if has_placeholder { Some(line_str) } else { None },
            });
        }
    }
    if lines.is_empty() {
        lines.push(ShapedLine {
            baseline_offset_um: baseline_in_line,
            height_um: line_height_um,
            runs: Vec::new(),
            text: String::new(),
            font_id: font.clone(),
            font_size_um,
            placeholder_template: None,
        });
    }
    Ok(lines)
}

fn wrap_paragraph(
    para: &str,
    font: &FontId,
    font_size_um: i64,
    max_width_um: i64,
    fonts: &FontSet,
) -> Result<Vec<String>, LayoutError> {
    if para.is_empty() {
        return Ok(vec![String::new()]);
    }
    // Replace sentinel placeholders with a 3-digit probe width during line-break measurement
    // while keeping byte mapping clean: if placeholders are present and short, keep as one line
    // unless overflowing.
    let has_ph = para.contains(PLACEHOLDER_PAGE_NUM) || para.contains(PLACEHOLDER_PAGE_COUNT);
    if has_ph {
        return Ok(vec![para.to_string()]);
    }

    let shaped = fonts.shape(font, para, font_size_um)?;
    let breaks = break_opportunities(para)?;

    // Build per-character (byte_start, byte_end, advance_um) table in string order.
    let mut char_adv: Vec<(usize, usize, i64)> = Vec::new();
    let mut flat_glyphs = shaped.runs.iter().flat_map(|r| r.glyphs.iter());
    for (byte_start, ch) in para.char_indices() {
        let adv = flat_glyphs.next().map_or(0, |g| g.advance_um);
        char_adv.push((byte_start, byte_start + ch.len_utf8(), adv));
    }

    let mut out = Vec::new();
    let mut start_idx = 0usize;
    let n = char_adv.len();

    while start_idx < n {
        let start_byte = char_adv[start_idx].0;
        let mut width: i64 = 0;
        let mut fit_end_idx = start_idx;
        let mut overflowed = false;

        for (i, &(_, _, adv)) in char_adv.iter().enumerate().skip(start_idx) {
            let next_w = width.saturating_add(adv);
            if next_w > max_width_um && i > start_idx {
                overflowed = true;
                break;
            }
            width = next_w;
            fit_end_idx = i + 1;
        }

        if !overflowed || fit_end_idx >= n {
            let end_byte = char_adv[n - 1].1;
            out.push(para[start_byte..end_byte].to_string());
            break;
        }

        // Find the latest UAX #14 break opportunity within (start_byte, fit_end_byte].
        let fit_end_byte = char_adv[fit_end_idx - 1].1;
        let best_break_byte = breaks.iter().copied().rfind(|&b| b > start_byte && b <= fit_end_byte);

        let (line_end_byte, next_start_idx) = if let Some(brk) = best_break_byte {
            // Find character index whose byte_start == brk.
            let next_i = char_adv.iter().position(|&(s, _, _)| s == brk).unwrap_or(fit_end_idx);
            (brk, next_i)
        } else {
            // Unbreakable token wider than max_width_um: hard break at fit_end_idx (>= 1 char).
            (fit_end_byte, fit_end_idx)
        };

        let slice = para[start_byte..line_end_byte].trim_end_matches([' ', '\t']);
        out.push(slice.to_string());
        start_idx = next_start_idx.max(start_idx + 1);
    }

    Ok(out)
}

// ------------------------------------------------------------------ text / block extraction

fn extract_text_content(payload: &JsonVal) -> (String, bool) {
    if let Some(o) = payload.as_obj() {
        let is_heading =
            o.get("key").and_then(JsonVal::as_str).is_some_and(|k| k.contains("heading") || k.contains("title"))
                || o.get("style").and_then(JsonVal::as_str) == Some("heading");

        if let Some(runs) = o.get("runs").and_then(JsonVal::as_arr) {
            let mut buf = String::new();
            for r in runs {
                let Some(ro) = r.as_obj() else {
                    continue;
                };
                match ro.get("kind").and_then(JsonVal::as_str) {
                    Some("page_placeholder") => match ro.get("field").and_then(JsonVal::as_str) {
                        Some("page_number") => buf.push(PLACEHOLDER_PAGE_NUM),
                        Some("page_count") => buf.push(PLACEHOLDER_PAGE_COUNT),
                        _ => {}
                    },
                    Some("value") => {
                        if let Some(vt) = ro.get("value").and_then(JsonVal::as_obj) {
                            buf.push_str(&format_value_with_markers(vt));
                        }
                    }
                    Some("outcome") => {
                        if let Some(ot) = ro.get("outcome").and_then(JsonVal::as_obj) {
                            if let Some(t) = ot.get("text").and_then(JsonVal::as_str) {
                                buf.push_str(t);
                            }
                        }
                    }
                    Some("uncertainty") => {
                        if let Some(t) = ro.get("display").and_then(JsonVal::as_str) {
                            buf.push_str(t);
                        } else if let Some(vt) = ro.get("value").and_then(JsonVal::as_obj) {
                            buf.push_str(&format_value_with_markers(vt));
                        }
                    }
                    _ => {
                        if let Some(t) = ro.get("text").and_then(JsonVal::as_str) {
                            buf.push_str(t);
                        }
                    }
                }
            }
            return (buf, is_heading);
        }

        if let Some(t) = o.get("text").and_then(JsonVal::as_str) {
            return (t.to_string(), is_heading);
        }
    }
    (String::new(), false)
}

/// Formats a `ValueText` object verbatim from its `display` field plus any visible markers
/// (`DRAW` REQ-001, REQ-005). Never formats, rounds, or converts numbers.
fn format_value_with_markers(vt: &BTreeMap<String, JsonVal>) -> String {
    let display = vt.get("display").and_then(JsonVal::as_str).unwrap_or("");
    let markers = extract_markers(vt);
    if markers.is_empty() {
        display.to_string()
    } else {
        format!("{display} {}", markers.join(" "))
    }
}

fn extract_markers(vt: &BTreeMap<String, JsonVal>) -> Vec<String> {
    let Some(arr) = vt.get("markers").and_then(JsonVal::as_arr) else {
        return Vec::new();
    };
    let mut out = Vec::new();
    for m in arr {
        match m {
            JsonVal::Str(s) if !s.is_empty() => out.push(s.clone()),
            JsonVal::Obj(mo) => {
                if let Some(sym) = mo
                    .get("glyph")
                    .or_else(|| mo.get("symbol"))
                    .or_else(|| mo.get("label"))
                    .or_else(|| mo.get("code"))
                    .and_then(JsonVal::as_str)
                {
                    if !sym.is_empty() {
                        out.push(sym.to_string());
                    }
                }
            }
            _ => {}
        }
    }
    out
}

// ------------------------------------------------------------------ table model & pagination

#[derive(Debug, Clone)]
struct TableCellData {
    text: String,
    style: CellStyleKind,
    markers: Vec<String>,
}

#[derive(Debug, Clone)]
struct TableRowData {
    is_header: bool,
    cells: Vec<TableCellData>,
}

#[derive(Debug, Clone)]
struct ParsedTableData {
    headers: Vec<TableCellData>,
    rows: Vec<TableRowData>,
    repeat_header_rows: usize,
    continuation_block: Option<String>,
    max_columns_per_group: Option<usize>,
    repeat_columns: Vec<usize>,
}

fn stage_letter_label(index: usize) -> String {
    // Letter labels A..Z, AA.. avoid introducing extra numeric digits in content streams
    // (RPT.OUTPUT.PDF.DRAW AC-1).
    let mut n = index;
    let mut chars = Vec::new();
    loop {
        chars.push(char::from(b'A' + (n % 26) as u8));
        if n < 26 {
            break;
        }
        n = n / 26 - 1;
    }
    chars.into_iter().rev().collect()
}

fn parse_table_data(payload: &JsonVal) -> Result<ParsedTableData, LayoutError> {
    let Some(o) = payload.as_obj() else {
        return Err(LayoutError::ResolvedInvalid("table payload must be an object".to_string()));
    };
    let schema = o.get("schema").and_then(JsonVal::as_str).unwrap_or("");

    // Case 1: `resolved_column_group@1` (stage-header descriptor from bracket_3stage).
    if schema == "resolved_column_group@1" {
        let cols = o.get("columns").and_then(JsonVal::as_arr).unwrap_or(&[]);
        let mut headers = Vec::with_capacity(cols.len().max(1));
        let mut row_cells = Vec::with_capacity(cols.len().max(1));
        if cols.is_empty() {
            headers.push(TableCellData {
                text: "Stages".to_string(),
                style: CellStyleKind::Header,
                markers: Vec::new(),
            });
            row_cells.push(TableCellData { text: "—".to_string(), style: CellStyleKind::Text, markers: Vec::new() });
        } else {
            for (i, c) in cols.iter().enumerate() {
                let kind = c.get("kind").and_then(JsonVal::as_str).unwrap_or("stage");
                let label = stage_letter_label(i);
                headers.push(TableCellData {
                    text: format!("Stage {label}"),
                    style: CellStyleKind::Header,
                    markers: Vec::new(),
                });
                row_cells.push(TableCellData {
                    text: kind.to_string(),
                    style: CellStyleKind::Text,
                    markers: Vec::new(),
                });
            }
        }
        return Ok(ParsedTableData {
            headers,
            rows: vec![TableRowData { is_header: false, cells: row_cells }],
            repeat_header_rows: 1,
            continuation_block: None,
            max_columns_per_group: None,
            repeat_columns: Vec::new(),
        });
    }

    let repeat_header_rows =
        o.get("repeat_header_rows").and_then(JsonVal::as_i64).and_then(|n| usize::try_from(n).ok()).unwrap_or(1);
    let continuation_block = o.get("continuation_block").and_then(JsonVal::as_str).map(ToString::to_string);
    let max_columns_per_group = o
        .get("max_columns_per_group")
        .and_then(JsonVal::as_i64)
        .and_then(|n| usize::try_from(n).ok())
        .filter(|&n| n > 0);
    let repeat_columns: Vec<usize> = o
        .get("repeat_columns")
        .and_then(JsonVal::as_arr)
        .map(|arr| arr.iter().filter_map(|v| v.as_i64().and_then(|n| usize::try_from(n).ok())).collect())
        .unwrap_or_default();

    // Case 2: Multi-stage `resolved_table@1` (e.g. `bracket_3stage.resolved.json`).
    if let Some(stages) = o.get("stages").and_then(JsonVal::as_arr) {
        if !stages.is_empty() {
            return parse_multistage_table(
                o,
                stages.len(),
                repeat_header_rows,
                continuation_block,
                max_columns_per_group,
                repeat_columns,
            );
        }
    }

    // Case 3: General table (`columns` + `rows` array of arrays or objects, e.g. FAI / PPAP).
    let cols_arr = o.get("columns").and_then(JsonVal::as_arr).unwrap_or(&[]);
    let mut headers = Vec::with_capacity(cols_arr.len());
    let mut col_keys = Vec::with_capacity(cols_arr.len());
    for (idx, cv) in cols_arr.iter().enumerate() {
        match cv {
            JsonVal::Str(s) => {
                headers.push(TableCellData { text: s.clone(), style: CellStyleKind::Header, markers: Vec::new() });
                col_keys.push(s.clone());
            }
            JsonVal::Obj(co) => {
                let title = co
                    .get("title")
                    .or_else(|| co.get("label"))
                    .or_else(|| co.get("key"))
                    .and_then(JsonVal::as_str)
                    .unwrap_or("Column")
                    .to_string();
                let key =
                    co.get("key").and_then(JsonVal::as_str).map_or_else(|| format!("col_{idx}"), ToString::to_string);
                headers.push(TableCellData { text: title, style: CellStyleKind::Header, markers: Vec::new() });
                col_keys.push(key);
            }
            _ => {
                headers.push(TableCellData {
                    text: "Column".to_string(),
                    style: CellStyleKind::Header,
                    markers: Vec::new(),
                });
                col_keys.push(format!("col_{idx}"));
            }
        }
    }

    let rows_arr = o.get("rows").and_then(JsonVal::as_arr).unwrap_or(&[]);
    let mut rows = Vec::with_capacity(rows_arr.len());
    for rv in rows_arr {
        let mut cells = Vec::new();
        match rv {
            JsonVal::Arr(arr) => {
                for cell_v in arr {
                    cells.push(parse_general_cell(cell_v));
                }
            }
            JsonVal::Obj(ro) => {
                if let Some(arr) = ro.get("cells").and_then(JsonVal::as_arr) {
                    for cell_v in arr {
                        cells.push(parse_general_cell(cell_v));
                    }
                } else {
                    for key in &col_keys {
                        cells.push(ro.get(key).map_or_else(
                            || TableCellData { text: String::new(), style: CellStyleKind::Text, markers: Vec::new() },
                            parse_general_cell,
                        ));
                    }
                }
            }
            _ => {}
        }
        while cells.len() < headers.len() {
            cells.push(TableCellData { text: String::new(), style: CellStyleKind::Text, markers: Vec::new() });
        }
        rows.push(TableRowData { is_header: false, cells });
    }

    if headers.is_empty() {
        let max_cols = rows.iter().map(|r| r.cells.len()).max().unwrap_or(1);
        for _ in 0..max_cols {
            headers.push(TableCellData { text: String::new(), style: CellStyleKind::Header, markers: Vec::new() });
        }
    }

    Ok(ParsedTableData { headers, rows, repeat_header_rows, continuation_block, max_columns_per_group, repeat_columns })
}

fn parse_multistage_table(
    o: &BTreeMap<String, JsonVal>,
    stage_count: usize,
    repeat_header_rows: usize,
    continuation_block: Option<String>,
    max_columns_per_group: Option<usize>,
    repeat_columns: Vec<usize>,
) -> Result<ParsedTableData, LayoutError> {
    let rows_arr = o.get("rows").and_then(JsonVal::as_arr).unwrap_or(&[]);
    let mut headers = vec![
        TableCellData { text: "Char".to_string(), style: CellStyleKind::Header, markers: Vec::new() },
        TableCellData { text: "Nominal".to_string(), style: CellStyleKind::Header, markers: Vec::new() },
    ];
    for s in 0..stage_count {
        let lbl = stage_letter_label(s);
        headers.push(TableCellData { text: format!("{lbl} Meas"), style: CellStyleKind::Header, markers: Vec::new() });
        headers.push(TableCellData { text: format!("{lbl} Dev"), style: CellStyleKind::Header, markers: Vec::new() });
        headers.push(TableCellData { text: format!("{lbl} Unc"), style: CellStyleKind::Header, markers: Vec::new() });
        headers.push(TableCellData { text: format!("{lbl} Dec"), style: CellStyleKind::Header, markers: Vec::new() });
    }

    let mut rows = Vec::with_capacity(rows_arr.len());
    for rv in rows_arr {
        let Some(ro) = rv.as_obj() else {
            continue;
        };
        let mut cells = Vec::with_capacity(headers.len());
        let name = ro.get("name").and_then(JsonVal::as_str).unwrap_or("").to_string();
        cells.push(TableCellData { text: name, style: CellStyleKind::Text, markers: Vec::new() });
        cells.push(ro.get("nominal").map_or_else(
            || TableCellData { text: String::new(), style: CellStyleKind::Numeric, markers: Vec::new() },
            parse_general_cell,
        ));
        let stage_cells = ro.get("cells").and_then(JsonVal::as_arr).unwrap_or(&[]);
        for s in 0..stage_count {
            if let Some(so) = stage_cells.get(s).and_then(JsonVal::as_obj) {
                cells.push(so.get("measured").map_or_else(
                    || TableCellData { text: String::new(), style: CellStyleKind::Numeric, markers: Vec::new() },
                    parse_general_cell,
                ));
                cells.push(so.get("deviation").map_or_else(
                    || TableCellData { text: String::new(), style: CellStyleKind::Numeric, markers: Vec::new() },
                    parse_general_cell,
                ));
                let unc_cell = so.get("uncertainty").and_then(|u| u.get("value").or(Some(u))).map_or_else(
                    || TableCellData { text: String::new(), style: CellStyleKind::Numeric, markers: Vec::new() },
                    parse_general_cell,
                );
                cells.push(unc_cell);
                cells.push(so.get("decision").map_or_else(
                    || TableCellData { text: String::new(), style: CellStyleKind::Text, markers: Vec::new() },
                    parse_decision_cell,
                ));
            } else {
                for _ in 0..4 {
                    cells.push(TableCellData { text: String::new(), style: CellStyleKind::Text, markers: Vec::new() });
                }
            }
        }
        rows.push(TableRowData { is_header: false, cells });
    }

    Ok(ParsedTableData { headers, rows, repeat_header_rows, continuation_block, max_columns_per_group, repeat_columns })
}

fn parse_general_cell(v: &JsonVal) -> TableCellData {
    match v {
        JsonVal::Null => TableCellData { text: String::new(), style: CellStyleKind::Text, markers: Vec::new() },
        JsonVal::Str(s) => TableCellData { text: s.clone(), style: CellStyleKind::Text, markers: Vec::new() },
        JsonVal::Int(n) => TableCellData { text: n.to_string(), style: CellStyleKind::Numeric, markers: Vec::new() },
        JsonVal::Dec(s) => TableCellData { text: s.clone(), style: CellStyleKind::Numeric, markers: Vec::new() },
        JsonVal::Bool(b) => TableCellData { text: b.to_string(), style: CellStyleKind::Text, markers: Vec::new() },
        JsonVal::Obj(o) => {
            if o.contains_key("display") {
                let markers = extract_markers(o);
                let text = format_value_with_markers(o);
                return TableCellData { text, style: CellStyleKind::Numeric, markers };
            }
            if let Some(vt) = o.get("value").and_then(JsonVal::as_obj) {
                if vt.contains_key("display") {
                    let markers = extract_markers(vt);
                    let text = format_value_with_markers(vt);
                    return TableCellData { text, style: CellStyleKind::Numeric, markers };
                }
            }
            if o.contains_key("rule") || o.get("kind").and_then(JsonVal::as_str) == Some("outcome") {
                return parse_decision_cell(v);
            }
            if let Some(t) = o.get("text").and_then(JsonVal::as_str) {
                return TableCellData { text: t.to_string(), style: CellStyleKind::Text, markers: Vec::new() };
            }
            TableCellData { text: String::new(), style: CellStyleKind::Text, markers: Vec::new() }
        }
        JsonVal::Arr(_) => TableCellData { text: String::new(), style: CellStyleKind::Text, markers: Vec::new() },
    }
}

fn parse_decision_cell(v: &JsonVal) -> TableCellData {
    let text = match v {
        JsonVal::Str(s) => s.clone(),
        JsonVal::Obj(o) => o.get("text").and_then(JsonVal::as_str).unwrap_or("").to_string(),
        _ => String::new(),
    };
    let lower = text.to_ascii_lowercase();
    let style = if lower.contains("nonconform") || lower.contains("fail") || lower.contains("reject") {
        CellStyleKind::OutcomeFail
    } else if lower.contains("conform") || lower.contains("pass") || lower.contains("accept") {
        CellStyleKind::OutcomePass
    } else if lower.contains("not decidable") || lower.contains("indeterminate") || lower.contains("warn") {
        CellStyleKind::OutcomeWarn
    } else {
        CellStyleKind::Text
    };
    TableCellData { text, style, markers: Vec::new() }
}

/// Computes column groups when `max_columns_per_group` is set (`REQ-004`, `AC-3`).
///
/// Each returned `Vec<usize>` lists the column indices (repeat columns first, then the group's
/// variable columns) for one sub-table.
fn compute_column_groups(total_cols: usize, repeat_cols: &[usize], max_per_group: Option<usize>) -> Vec<Vec<usize>> {
    if total_cols == 0 {
        return vec![Vec::new()];
    }
    let Some(max_var) = max_per_group else {
        return vec![(0..total_cols).collect()];
    };
    let mut rep: Vec<usize> = Vec::new();
    for &c in repeat_cols {
        if c < total_cols && !rep.contains(&c) {
            rep.push(c);
        }
    }
    let var_cols: Vec<usize> = (0..total_cols).filter(|c| !rep.contains(c)).collect();
    if var_cols.len() <= max_var {
        return vec![(0..total_cols).collect()];
    }
    let mut groups = Vec::new();
    for chunk in var_cols.chunks(max_var) {
        let mut g = rep.clone();
        g.extend_from_slice(chunk);
        groups.push(g);
    }
    groups
}

/// Splits `total_width_um` evenly across `n_cols` columns in integer µm (remainder `+1 µm` to
/// leftmost columns so the sum equals `total_width_um` exactly).
fn distribute_column_widths(n_cols: usize, total_width_um: i64) -> Vec<i64> {
    if n_cols == 0 {
        return Vec::new();
    }
    let n = n_cols as i64;
    let base = total_width_um / n;
    let rem = total_width_um % n;
    (0..n).map(|i| base + i64::from(i < rem)).collect()
}

#[allow(clippy::too_many_arguments)]
fn measure_table_row(
    cells: &[TableCellData],
    col_indices: &[usize],
    col_widths_um: &[i64],
    is_header: bool,
    fonts: &FontSet,
    body_font: &FontId,
    strong_font: &FontId,
    mono_font: &FontId,
) -> Result<LaidTableRow, LayoutError> {
    let mut laid_cells = Vec::with_capacity(col_indices.len());
    let mut x_off: i64 = 0;
    let mut max_h: i64 = TABLE_LINE_UM + 2 * CELL_PAD_Y_UM;

    for (pos, (&col_idx, &w)) in col_indices.iter().zip(col_widths_um.iter()).enumerate() {
        let cell_data = cells.get(col_idx);
        let text = cell_data.map_or("", |c| c.text.as_str());
        let style = if is_header { CellStyleKind::Header } else { cell_data.map_or(CellStyleKind::Text, |c| c.style) };
        let markers = cell_data.map_or_else(Vec::new, |c| c.markers.clone());
        let font = match style {
            CellStyleKind::Header => strong_font,
            CellStyleKind::Numeric => mono_font,
            _ => body_font,
        };
        let inner_w = (w - 2 * CELL_PAD_X_UM).max(1);
        let lines = wrap_text(text, font, TABLE_FONT_UM, TABLE_LINE_UM, inner_w, fonts)?;
        let cell_h = (lines.len() as i64) * TABLE_LINE_UM + 2 * CELL_PAD_Y_UM;
        if cell_h > max_h {
            max_h = cell_h;
        }
        laid_cells.push(LaidTableCell { col_index: pos, x_offset_um: x_off, width_um: w, style, lines, markers });
        x_off += w;
    }

    Ok(LaidTableRow { y_offset_um: 0, height_um: max_h, is_header, cells: laid_cells })
}

// ------------------------------------------------------------------ core layout engine

struct PageBuilder {
    logical_page_id: String,
    spec: PageSpec,
    body_um: RectUm,
    boxes: Vec<LaidBox>,
    cursor_y_um: i64,
    has_flow_content: bool,
}

impl PageBuilder {
    fn new(logical_page_id: String, spec: PageSpec, body_um: RectUm, chrome_boxes: &[LaidBox]) -> PageBuilder {
        PageBuilder {
            logical_page_id,
            spec,
            body_um,
            boxes: chrome_boxes.to_vec(),
            cursor_y_um: body_um.y_um,
            has_flow_content: false,
        }
    }

    fn remaining_height_um(&self) -> i64 {
        let body_bottom = self.body_um.y_um + self.body_um.height_um;
        let gap = if self.has_flow_content { BLOCK_GAP_UM } else { 0 };
        (body_bottom - self.cursor_y_um - gap).max(0)
    }

    fn next_y_um(&self) -> i64 {
        if self.has_flow_content {
            self.cursor_y_um + BLOCK_GAP_UM
        } else {
            self.cursor_y_um
        }
    }

    fn push_flow_box(&mut self, mut b: LaidBox) {
        let y = self.next_y_um();
        b.rect_um.y_um = y;
        self.cursor_y_um = y + b.rect_um.height_um;
        self.has_flow_content = true;
        self.boxes.push(b);
    }

    fn finish(self, page_index: u32) -> LaidPage {
        LaidPage {
            page_index,
            total_pages: 0,
            logical_page_id: self.logical_page_id,
            size_um: (self.spec.width_um, self.spec.height_um),
            body_um: self.body_um,
            boxes: self.boxes,
        }
    }
}

/// Lays out a parsed [`ResolvedDoc`] into a deterministic integer-µm [`PageLayout`] display list
/// (`REQ-RPT.OUTPUT.PDF.LAYOUT-001`..`006`).
pub fn layout_document(
    doc: &ResolvedDoc,
    fonts: &FontSet,
    measurers: &MeasureRegistry<'_>,
) -> Result<PageLayout, LayoutError> {
    let body_font = fonts
        .default_style(DefaultStyle::Body)
        .ok_or_else(|| LayoutError::ResolvedInvalid("bundled body font missing".to_string()))?
        .clone();
    let strong_font = fonts.default_style(DefaultStyle::Strong).unwrap_or(&body_font).clone();
    let mono_font = fonts.default_style(DefaultStyle::Mono).unwrap_or(&body_font).clone();

    // Index all blocks by ID across the document so `continuation_block` can reference any block.
    let mut blocks_by_id: BTreeMap<String, &ParsedBlock> = BTreeMap::new();
    for page in &doc.pages {
        for block in &page.blocks {
            blocks_by_id.insert(block.id.clone(), block);
        }
    }

    let mut physical_pages: Vec<LaidPage> = Vec::new();
    let mut warnings: Vec<LayoutWarning> = Vec::new();

    for logical_page in &doc.pages {
        let mut spec = doc
            .page_overrides
            .get(&logical_page.id)
            .copied()
            .or(doc.default_page)
            .unwrap_or_else(PageSpec::a4_portrait);

        let has_header = logical_page.blocks.iter().any(|b| b.kind == "header");
        let has_footer = logical_page.blocks.iter().any(|b| b.kind == "footer");
        if has_header && spec.header_um == 0 {
            spec.header_um = DEFAULT_HEADER_UM;
        }
        if has_footer && spec.footer_um == 0 {
            spec.footer_um = DEFAULT_FOOTER_UM;
        }
        let body_um = spec.body_rect()?;
        let header_um = spec.header_rect()?;
        let footer_um = spec.footer_rect()?;

        // Build repeating chrome boxes (`header` and `footer`) for every physical page emitted
        // from this logical page.
        let mut chrome_boxes = Vec::new();
        for b in &logical_page.blocks {
            if b.kind == "header" {
                let rect = match b.frame_01mm {
                    Some(f) => f.to_rect_um()?,
                    None => header_um,
                };
                let (txt, _) = extract_text_content(&b.payload);
                let lines = wrap_text(&txt, &body_font, CHROME_FONT_UM, CHROME_LINE_UM, rect.width_um, fonts)?;
                chrome_boxes.push(LaidBox {
                    block_id: b.id.clone(),
                    kind: b.kind.clone(),
                    rect_um: rect,
                    clipped: false,
                    content: BoxContent::Text(lines),
                });
            } else if b.kind == "footer" {
                let rect = match b.frame_01mm {
                    Some(f) => f.to_rect_um()?,
                    None => footer_um,
                };
                let (txt, _) = extract_text_content(&b.payload);
                let lines = wrap_text(&txt, &body_font, CHROME_FONT_UM, CHROME_LINE_UM, rect.width_um, fonts)?;
                chrome_boxes.push(LaidBox {
                    block_id: b.id.clone(),
                    kind: b.kind.clone(),
                    rect_um: rect,
                    clipped: false,
                    content: BoxContent::Text(lines),
                });
            }
        }

        let mut cur = PageBuilder::new(logical_page.id.clone(), spec, body_um, &chrome_boxes);

        for block in &logical_page.blocks {
            if block.kind == "header" || block.kind == "footer" {
                continue;
            }

            // Framed block placement (`REQ-002`, `AC-5`): exact 0.01 mm -> µm conversion.
            if let Some(frame) = block.frame_01mm {
                let rect = frame.to_rect_um()?;
                let measured = measure_single_block(
                    block,
                    rect.width_um,
                    Some(rect.height_um),
                    fonts,
                    measurers,
                    &body_font,
                    &strong_font,
                    &mono_font,
                )?;
                let clipped = measured.height_um > rect.height_um
                    || rect.x_um < 0
                    || rect.y_um < 0
                    || rect.x_um + rect.width_um > spec.width_um
                    || rect.y_um + rect.height_um > spec.height_um;
                if clipped {
                    warnings.push(LayoutWarning {
                        block_id: block.id.clone(),
                        code: WARN_BLOCK_OVERFLOW.to_string(),
                        detail: Some("framed_block_overflow".to_string()),
                    });
                }
                cur.boxes.push(LaidBox {
                    block_id: block.id.clone(),
                    kind: block.kind.clone(),
                    rect_um: rect,
                    clipped,
                    content: measured.content,
                });
                continue;
            }

            // Flow table with pagination, continuation headers & column groups (`REQ-003`, `REQ-004`).
            if block.kind == "table" {
                layout_flow_table(
                    block,
                    &blocks_by_id,
                    &mut cur,
                    &mut physical_pages,
                    &chrome_boxes,
                    &mut warnings,
                    fonts,
                    measurers,
                    &body_font,
                    &strong_font,
                    &mono_font,
                )?;
                continue;
            }

            // Unframed non-table block in top-to-bottom document flow (`REQ-002`, `REQ-005`).
            let measured = measure_single_block(
                block,
                body_um.width_um,
                None,
                fonts,
                measurers,
                &body_font,
                &strong_font,
                &mono_font,
            )?;

            if measured.height_um > body_um.height_um {
                // REQ-005 / AC-4: oversized unbreakable block goes on its own page, clipped, with warning.
                if cur.has_flow_content {
                    push_physical_page(&mut physical_pages, cur)?;
                    cur = PageBuilder::new(logical_page.id.clone(), spec, body_um, &chrome_boxes);
                }
                warnings.push(LayoutWarning {
                    block_id: block.id.clone(),
                    code: WARN_BLOCK_OVERFLOW.to_string(),
                    detail: Some(format!(
                        "block_height_um={} exceeds body_height_um={}",
                        measured.height_um, body_um.height_um
                    )),
                });
                cur.push_flow_box(LaidBox {
                    block_id: block.id.clone(),
                    kind: block.kind.clone(),
                    rect_um: RectUm::new(
                        body_um.x_um,
                        body_um.y_um,
                        measured.width_um.min(body_um.width_um),
                        body_um.height_um,
                    ),
                    clipped: true,
                    content: measured.content,
                });
                // Own page: any subsequent block starts on a fresh page.
                push_physical_page(&mut physical_pages, cur)?;
                cur = PageBuilder::new(logical_page.id.clone(), spec, body_um, &chrome_boxes);
            } else {
                if cur.has_flow_content && measured.height_um > cur.remaining_height_um() {
                    push_physical_page(&mut physical_pages, cur)?;
                    cur = PageBuilder::new(logical_page.id.clone(), spec, body_um, &chrome_boxes);
                }
                cur.push_flow_box(LaidBox {
                    block_id: block.id.clone(),
                    kind: block.kind.clone(),
                    rect_um: RectUm::new(
                        body_um.x_um,
                        cur.next_y_um(),
                        measured.width_um.min(body_um.width_um),
                        measured.height_um,
                    ),
                    clipped: false,
                    content: measured.content,
                });
            }
        }

        // Flush final physical page of this logical page (unless it's a trailing empty page created
        // right after an oversized own-page block when there were no more blocks).
        let should_flush = cur.has_flow_content
            || cur.boxes.len() > chrome_boxes.len()
            || physical_pages.iter().all(|p| p.logical_page_id != logical_page.id);
        if should_flush {
            push_physical_page(&mut physical_pages, cur)?;
        }
    }

    // REQ-006: fill page number (n) and total page count (m) across every page & re-shape affected lines.
    let total_pages = u32::try_from(physical_pages.len()).unwrap_or(u32::MAX);
    for (idx, page) in physical_pages.iter_mut().enumerate() {
        let page_num = (idx as u32) + 1;
        page.page_index = page_num;
        page.total_pages = total_pages;
        fill_page_placeholders_in_page(page, page_num, total_pages, fonts)?;
    }

    warnings.sort();

    Ok(PageLayout {
        schema: LAYOUT_SCHEMA.to_string(),
        schema_version: LAYOUT_SCHEMA_VERSION,
        resolved_digest: doc.digest,
        pages: physical_pages,
        warnings,
    })
}

/// Convenience entry point: parses `resolved_report@1` JSON bytes and lays out the document.
pub fn layout_resolved_json(
    bytes: &[u8],
    fonts: &FontSet,
    measurers: &MeasureRegistry<'_>,
) -> Result<PageLayout, LayoutError> {
    let doc = ResolvedDoc::from_json_bytes(bytes)?;
    layout_document(&doc, fonts, measurers)
}

fn push_physical_page(pages: &mut Vec<LaidPage>, cur: PageBuilder) -> Result<(), LayoutError> {
    if pages.len() >= MAX_LAYOUT_PAGES {
        return Err(LayoutError::LayoutInvalid { field: "pages", reason: "exceeds_max_layout_pages" });
    }
    let idx = (pages.len() as u32) + 1;
    pages.push(cur.finish(idx));
    Ok(())
}

#[allow(clippy::too_many_arguments)]
fn measure_single_block(
    block: &ParsedBlock,
    width_um: i64,
    frame_height_um: Option<i64>,
    fonts: &FontSet,
    measurers: &MeasureRegistry<'_>,
    body_font: &FontId,
    strong_font: &FontId,
    mono_font: &FontId,
) -> Result<MeasuredBox, LayoutError> {
    if let Some(m) = measurers.get(&block.kind) {
        return m.measure(block, width_um, fonts);
    }
    match block.kind.as_str() {
        "text" | "header" | "footer" => {
            let (txt, is_heading) = extract_text_content(&block.payload);
            let (font, size_um, line_um) = if is_heading {
                (strong_font, HEADING_FONT_UM, HEADING_LINE_UM)
            } else {
                (body_font, BODY_FONT_UM, BODY_LINE_UM)
            };
            let lines = wrap_text(&txt, font, size_um, line_um, width_um, fonts)?;
            let height_um = (lines.len() as i64) * line_um;
            Ok(MeasuredBox { width_um, height_um, content: BoxContent::Text(lines) })
        }
        "table" => {
            // Framed table: render full first column group inside the frame width.
            let td = parse_table_data(&block.payload)?;
            let col_indices: Vec<usize> = (0..td.headers.len()).collect();
            let col_widths = distribute_column_widths(col_indices.len(), width_um);
            let mut laid_rows = Vec::new();
            let mut y_off = 0i64;
            let mut hdr = measure_table_row(
                &td.headers,
                &col_indices,
                &col_widths,
                true,
                fonts,
                body_font,
                strong_font,
                mono_font,
            )?;
            hdr.y_offset_um = y_off;
            y_off += hdr.height_um;
            laid_rows.push(hdr);
            for r in &td.rows {
                let mut lr = measure_table_row(
                    &r.cells,
                    &col_indices,
                    &col_widths,
                    r.is_header,
                    fonts,
                    body_font,
                    strong_font,
                    mono_font,
                )?;
                lr.y_offset_um = y_off;
                y_off += lr.height_um;
                laid_rows.push(lr);
            }
            Ok(MeasuredBox {
                width_um,
                height_um: y_off,
                content: BoxContent::Table(LaidTable {
                    column_widths_um: col_widths,
                    header_row_count: td.repeat_header_rows.min(1),
                    column_group_index: 0,
                    column_group_count: 1,
                    continuation: false,
                    rows: laid_rows,
                }),
            })
        }
        "image" => {
            let o = block.payload.as_obj();
            let digest_str = o
                .and_then(|m| m.get("cas_digest").or_else(|| m.get("digest")))
                .and_then(JsonVal::as_str)
                .ok_or_else(|| LayoutError::ResolvedInvalid(format!("image block {} missing digest", block.id)))?;
            let digest = Digest::parse(digest_str)
                .map_err(|_| LayoutError::ResolvedInvalid(format!("image block {} invalid digest", block.id)))?;
            let mime = o
                .and_then(|m| m.get("media_type").or_else(|| m.get("mime")))
                .and_then(JsonVal::as_str)
                .map(ToString::to_string);
            let caption = o.and_then(|m| m.get("caption")).and_then(JsonVal::as_str).map(ToString::to_string);
            let req_w = o
                .and_then(|m| m.get("width_01mm"))
                .and_then(|v| parse_01mm_val(v, "image.width").ok())
                .and_then(|u| convert_01mm_to_um(u, "image.width").ok())
                .unwrap_or(DEFAULT_IMAGE_WIDTH_UM)
                .min(width_um);
            let req_h = o
                .and_then(|m| m.get("height_01mm"))
                .and_then(|v| parse_01mm_val(v, "image.height").ok())
                .and_then(|u| convert_01mm_to_um(u, "image.height").ok())
                .or(frame_height_um)
                .unwrap_or(DEFAULT_IMAGE_HEIGHT_UM);
            Ok(MeasuredBox {
                width_um: req_w.max(1),
                height_um: req_h.max(1),
                content: BoxContent::Image { digest, mime, caption },
            })
        }
        "view" => {
            let o = block.payload.as_obj();
            let snapshot_digest = match o.and_then(|m| m.get("snapshot_digest")).and_then(JsonVal::as_str) {
                Some(ds) => Some(Digest::parse(ds).map_err(|_| {
                    LayoutError::ResolvedInvalid(format!("view block {} invalid snapshot_digest", block.id))
                })?),
                None => None,
            };
            let view_id = o.and_then(|m| m.get("view_id")).and_then(JsonVal::as_str).map(ToString::to_string);
            let caption = o.and_then(|m| m.get("caption")).and_then(JsonVal::as_str).map(ToString::to_string);
            let h = frame_height_um.unwrap_or(DEFAULT_VIEW_HEIGHT_UM);
            Ok(MeasuredBox {
                width_um,
                height_um: h.max(1),
                content: BoxContent::View { snapshot_digest, view_id, caption },
            })
        }
        "drawing" => {
            let o = block.payload.as_obj().ok_or_else(|| {
                LayoutError::ResolvedInvalid(format!("drawing block {} payload must be object", block.id))
            })?;
            let digest_str = o
                .get("sheet_digest")
                .or_else(|| o.get("cas_digest"))
                .or_else(|| o.get("digest"))
                .and_then(JsonVal::as_str)
                .ok_or_else(|| {
                    LayoutError::ResolvedInvalid(format!("drawing block {} missing sheet_digest", block.id))
                })?;
            let sheet_digest = Digest::parse(digest_str).map_err(|_| {
                LayoutError::ResolvedInvalid(format!("drawing block {} invalid sheet_digest", block.id))
            })?;
            let mime = o.get("media_type").or_else(|| o.get("mime")).and_then(JsonVal::as_str).map(ToString::to_string);

            let src_w_um = o
                .get("sheet_width_um")
                .and_then(JsonVal::as_i64)
                .or_else(|| {
                    o.get("sheet_width_01mm")
                        .and_then(|v| parse_01mm_val(v, "drawing.sheet_width").ok())
                        .and_then(|u| convert_01mm_to_um(u, "drawing.sheet_width").ok())
                })
                .unwrap_or(width_um);
            let src_h_um = o
                .get("sheet_height_um")
                .and_then(JsonVal::as_i64)
                .or_else(|| {
                    o.get("sheet_height_01mm")
                        .and_then(|v| parse_01mm_val(v, "drawing.sheet_height").ok())
                        .and_then(|u| convert_01mm_to_um(u, "drawing.sheet_height").ok())
                })
                .unwrap_or(DEFAULT_DRAWING_HEIGHT_UM);

            if src_w_um <= 0 || src_h_um <= 0 {
                return Err(LayoutError::LayoutInvalid { field: "drawing.sheet_size", reason: "must_be_positive" });
            }

            // Preserve exact integer geometry when sheet fits within target width (1:1 scale ->
            // zero rounding error on balloon coordinates, AC-3); otherwise scale down uniformly
            // using integer half-to-even rounding.
            let (draw_w, draw_h) = if let Some(fh) = frame_height_um {
                (width_um, fh)
            } else if src_w_um <= width_um {
                (src_w_um, src_h_um)
            } else {
                let scaled_h = scale_int(src_h_um, width_um, src_w_um);
                (width_um, scaled_h.max(1))
            };

            let mut balloons = Vec::new();
            if let Some(arr) = o.get("balloons").and_then(JsonVal::as_arr) {
                for bv in arr {
                    let Some(bo) = bv.as_obj() else {
                        continue;
                    };
                    let number =
                        bo.get("number").and_then(JsonVal::as_i64).and_then(|n| u32::try_from(n).ok()).unwrap_or(0);
                    let raw_x_um = bo
                        .get("x_um")
                        .and_then(JsonVal::as_i64)
                        .or_else(|| {
                            bo.get("x_01mm")
                                .or_else(|| bo.get("x"))
                                .and_then(|v| parse_01mm_val(v, "balloon.x").ok())
                                .and_then(|u| convert_01mm_to_um(u, "balloon.x").ok())
                        })
                        .unwrap_or(0);
                    let raw_y_um = bo
                        .get("y_um")
                        .and_then(JsonVal::as_i64)
                        .or_else(|| {
                            bo.get("y_01mm")
                                .or_else(|| bo.get("y"))
                                .and_then(|v| parse_01mm_val(v, "balloon.y").ok())
                                .and_then(|u| convert_01mm_to_um(u, "balloon.y").ok())
                        })
                        .unwrap_or(0);
                    let radius_um = bo
                        .get("radius_um")
                        .and_then(JsonVal::as_i64)
                        .or_else(|| {
                            bo.get("radius_01mm")
                                .and_then(|v| parse_01mm_val(v, "balloon.radius").ok())
                                .and_then(|u| convert_01mm_to_um(u, "balloon.radius").ok())
                        })
                        .unwrap_or(DEFAULT_BALLOON_RADIUS_UM);
                    let cx_um = if draw_w == src_w_um { raw_x_um } else { scale_int(raw_x_um, draw_w, src_w_um) };
                    let cy_um = if draw_h == src_h_um { raw_y_um } else { scale_int(raw_y_um, draw_h, src_h_um) };
                    balloons.push(LaidBalloon { number, cx_um, cy_um, radius_um: radius_um.max(500) });
                }
            }

            Ok(MeasuredBox {
                width_um: draw_w,
                height_um: draw_h,
                content: BoxContent::Drawing {
                    sheet_digest,
                    mime,
                    sheet_width_um: draw_w,
                    sheet_height_um: draw_h,
                    balloons,
                },
            })
        }
        "form_field" => {
            let o = block.payload.as_obj();
            let label = o.and_then(|m| m.get("label")).and_then(JsonVal::as_str).unwrap_or("").to_string();
            let value = match o.and_then(|m| m.get("value")) {
                Some(JsonVal::Str(s)) => s.clone(),
                Some(JsonVal::Obj(vt)) if vt.contains_key("display") => format_value_with_markers(vt),
                Some(JsonVal::Int(n)) => n.to_string(),
                _ => String::new(),
            };
            let combined = if label.is_empty() { value.clone() } else { format!("{label}: {value}") };
            let inner_w = (width_um - 2 * CELL_PAD_X_UM).max(1);
            let lines = wrap_text(&combined, body_font, BODY_FONT_UM, BODY_LINE_UM, inner_w, fonts)?;
            let height_um = (lines.len() as i64) * BODY_LINE_UM + 2 * CELL_PAD_Y_UM;
            Ok(MeasuredBox { width_um, height_um, content: BoxContent::FormField { label, value, lines } })
        }
        _ => {
            let height_um = frame_height_um.unwrap_or(20_000);
            Ok(MeasuredBox {
                width_um,
                height_um,
                content: BoxContent::Paint { block_id: block.id.clone(), kind: block.kind.clone() },
            })
        }
    }
}

fn scale_int(val: i64, num: i64, den: i64) -> i64 {
    crate::text::round_half_even(i128::from(val) * i128::from(num), i128::from(den)) as i64
}

#[allow(clippy::too_many_arguments)]
fn layout_flow_table(
    block: &ParsedBlock,
    blocks_by_id: &BTreeMap<String, &ParsedBlock>,
    cur: &mut PageBuilder,
    physical_pages: &mut Vec<LaidPage>,
    chrome_boxes: &[LaidBox],
    warnings: &mut Vec<LayoutWarning>,
    fonts: &FontSet,
    measurers: &MeasureRegistry<'_>,
    body_font: &FontId,
    strong_font: &FontId,
    mono_font: &FontId,
) -> Result<(), LayoutError> {
    let td = parse_table_data(&block.payload)?;
    let groups = compute_column_groups(td.headers.len(), &td.repeat_columns, td.max_columns_per_group);
    let group_count = u32::try_from(groups.len()).unwrap_or(1);

    // Pre-measure optional continuation identifying block (`REQ-003`, `AC-2`).
    let cont_block = td.continuation_block.as_deref().and_then(|id| blocks_by_id.get(id).copied());

    let body_um = cur.body_um;
    let spec = cur.spec;
    let logical_id = cur.logical_page_id.clone();

    for (group_idx, col_indices) in groups.iter().enumerate() {
        let col_widths = distribute_column_widths(col_indices.len(), body_um.width_um);
        let header_row =
            measure_table_row(&td.headers, col_indices, &col_widths, true, fonts, body_font, strong_font, mono_font)?;
        let mut data_rows = Vec::with_capacity(td.rows.len());
        for r in &td.rows {
            data_rows.push(measure_table_row(
                &r.cells,
                col_indices,
                &col_widths,
                r.is_header,
                fonts,
                body_font,
                strong_font,
                mono_font,
            )?);
        }

        // Build the list of rows to repeat on continuation pages (`repeat_header_rows`).
        let mut repeated_headers: Vec<LaidTableRow> = Vec::new();
        if td.repeat_header_rows > 0 {
            repeated_headers.push(header_row.clone());
            for extra in data_rows.iter().take(td.repeat_header_rows.saturating_sub(1)) {
                let mut h = extra.clone();
                h.is_header = true;
                repeated_headers.push(h);
            }
        }
        let repeated_h: i64 = repeated_headers.iter().map(|r| r.height_um).sum();

        // Subsequent column groups start cleanly on a new page if there is not room for headers + 1 row.
        let first_data_h = data_rows.first().map_or(0, |r| r.height_um);
        if cur.has_flow_content && (header_row.height_um + first_data_h) > cur.remaining_height_um() {
            let finished = std::mem::replace(cur, PageBuilder::new(logical_id.clone(), spec, body_um, chrome_boxes));
            push_physical_page(physical_pages, finished)?;
        }

        // Empty-body table: emit just the header row once.
        if data_rows.is_empty() {
            let mut hr = header_row.clone();
            hr.y_offset_um = 0;
            let h = hr.height_um;
            cur.push_flow_box(LaidBox {
                block_id: block.id.clone(),
                kind: block.kind.clone(),
                rect_um: RectUm::new(body_um.x_um, cur.next_y_um(), body_um.width_um, h),
                clipped: false,
                content: BoxContent::Table(LaidTable {
                    column_widths_um: col_widths.clone(),
                    header_row_count: 1,
                    column_group_index: group_idx as u32,
                    column_group_count: group_count,
                    continuation: false,
                    rows: vec![hr],
                }),
            });
            continue;
        }

        let mut row_cursor = 0usize;
        let mut is_continuation = false;

        while row_cursor < data_rows.len() {
            // On continuation pages, first place the identifying `continuation_block` if configured.
            if is_continuation {
                if let Some(cb) = cont_block {
                    let measured_cb = measure_single_block(
                        cb,
                        body_um.width_um,
                        None,
                        fonts,
                        measurers,
                        body_font,
                        strong_font,
                        mono_font,
                    )?;
                    cur.push_flow_box(LaidBox {
                        block_id: cb.id.clone(),
                        kind: cb.kind.clone(),
                        rect_um: RectUm::new(
                            body_um.x_um,
                            cur.next_y_um(),
                            measured_cb.width_um.min(body_um.width_um),
                            measured_cb.height_um.min(body_um.height_um),
                        ),
                        clipped: measured_cb.height_um > body_um.height_um,
                        content: measured_cb.content,
                    });
                }
            }

            let avail = cur.remaining_height_um();
            let mut slice_rows: Vec<LaidTableRow> = Vec::new();
            let mut y_off = 0i64;

            // Prefix with header row(s).
            let headers_to_place: &[LaidTableRow] =
                if is_continuation { &repeated_headers } else { std::slice::from_ref(&header_row) };
            let hdr_count = headers_to_place.len();
            for hr in headers_to_place {
                let mut r = hr.clone();
                r.y_offset_um = y_off;
                y_off += r.height_um;
                slice_rows.push(r);
            }

            // Pack as many whole data rows as fit (REQ-003); guarantee >= 1 data row per page.
            let mut clipped = false;
            let start_row = row_cursor;
            while row_cursor < data_rows.len() {
                let next_h = data_rows[row_cursor].height_um;
                if y_off + next_h > avail {
                    if row_cursor == start_row {
                        // Even 1 data row doesn't fit on this page!
                        if cur.has_flow_content && (repeated_h + next_h <= body_um.height_um) {
                            // Try on a fresh page instead (don't clip unnecessarily).
                            break;
                        }
                        // Single row taller than body area -> REQ-005: place clipped on its own page + warn.
                        let mut r = data_rows[row_cursor].clone();
                        r.y_offset_um = y_off;
                        y_off += r.height_um;
                        slice_rows.push(r);
                        row_cursor += 1;
                        clipped = true;
                        warnings.push(LayoutWarning {
                            block_id: block.id.clone(),
                            code: WARN_BLOCK_OVERFLOW.to_string(),
                            detail: Some(format!(
                                "table_row_{start_row}_height_um={y_off} exceeds available_um={avail}"
                            )),
                        });
                    }
                    break;
                }
                let mut r = data_rows[row_cursor].clone();
                r.y_offset_um = y_off;
                y_off += r.height_um;
                slice_rows.push(r);
                row_cursor += 1;
            }

            if row_cursor == start_row {
                // Advance to a fresh page and retry this row with continuation header.
                let finished =
                    std::mem::replace(cur, PageBuilder::new(logical_id.clone(), spec, body_um, chrome_boxes));
                push_physical_page(physical_pages, finished)?;
                continue;
            }

            let box_h = if clipped { avail.max(1) } else { y_off };
            cur.push_flow_box(LaidBox {
                block_id: block.id.clone(),
                kind: block.kind.clone(),
                rect_um: RectUm::new(body_um.x_um, cur.next_y_um(), body_um.width_um, box_h),
                clipped,
                content: BoxContent::Table(LaidTable {
                    column_widths_um: col_widths.clone(),
                    header_row_count: hdr_count,
                    column_group_index: group_idx as u32,
                    column_group_count: group_count,
                    continuation: is_continuation,
                    rows: slice_rows,
                }),
            });

            if row_cursor < data_rows.len() {
                let finished =
                    std::mem::replace(cur, PageBuilder::new(logical_id.clone(), spec, body_um, chrome_boxes));
                push_physical_page(physical_pages, finished)?;
                is_continuation = true;
            }
        }

        // Start a fresh page before the next column group so groups don't visually collide.
        if group_idx + 1 < groups.len() && cur.has_flow_content {
            let finished = std::mem::replace(cur, PageBuilder::new(logical_id.clone(), spec, body_um, chrome_boxes));
            push_physical_page(physical_pages, finished)?;
        }
    }

    Ok(())
}

// ------------------------------------------------------------------ post-pagination page numbers

fn fill_page_placeholders_in_page(
    page: &mut LaidPage,
    page_num: u32,
    total_pages: u32,
    fonts: &FontSet,
) -> Result<(), LayoutError> {
    let n_str = page_num.to_string();
    let m_str = total_pages.to_string();
    for b in &mut page.boxes {
        match &mut b.content {
            BoxContent::Text(lines) | BoxContent::FormField { lines, .. } => {
                fill_lines(lines, &n_str, &m_str, fonts)?;
            }
            BoxContent::Table(t) => {
                for row in &mut t.rows {
                    for cell in &mut row.cells {
                        fill_lines(&mut cell.lines, &n_str, &m_str, fonts)?;
                    }
                }
            }
            BoxContent::Image { .. }
            | BoxContent::View { .. }
            | BoxContent::Drawing { .. }
            | BoxContent::Paint { .. } => {}
        }
    }
    Ok(())
}

fn fill_lines(lines: &mut [ShapedLine], n_str: &str, m_str: &str, fonts: &FontSet) -> Result<(), LayoutError> {
    for line in lines {
        let Some(tmpl) = line.placeholder_template.as_ref() else {
            continue;
        };
        let filled = tmpl.replace(PLACEHOLDER_PAGE_NUM, n_str).replace(PLACEHOLDER_PAGE_COUNT, m_str);
        let shaped = fonts.shape(&line.font_id, &filled, line.font_size_um)?;
        line.runs = shaped.runs;
        line.text = filled;
        line.placeholder_template = None;
    }
    Ok(())
}
