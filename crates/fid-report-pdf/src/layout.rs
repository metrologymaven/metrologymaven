/// One wrapped, shaped line of text inside a box or table cell.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ShapedLine {
    /// Baseline distance down from the top of the containing text block or cell, in µm.
    pub baseline_offset_um: i64,
    /// Line box height in µm.
    pub height_um: i64,
    /// Shaped glyph runs in string order.
    pub runs: Vec<ShapedRun>,
    /// Final line text (equal to concatenation of `runs`).
    pub text: String,
    /// Font selected for re-shaping if this line contains a page placeholder.
    pub font_id: FontId,
    /// Font size in µm.
    pub font_size_um: i64,
    /// Unfilled template text containing [`PLACEHOLDER_PAGE_NUM`] / [`PLACEHOLDER_PAGE_COUNT`],
    /// if this line needs post-pagination fill-in (`REQ-006`).
    pub(crate) placeholder_template: Option<String>,
}

impl ShapedLine {
    /// Total horizontal advance width of this line in integer µm.
    pub fn advance_um(&self) -> i64 {
        self.runs.iter().map(ShapedRun::advance_um).sum()
    }

    pub fn to_json(&self) -> JsonVal {
        let runs: Vec<JsonVal> = self
            .runs
            .iter()
            .map(|r| {
                let glyphs: Vec<JsonVal> = r
                    .glyphs
                    .iter()
                    .map(|g| {
                        obj([
                            ("advance_um", JsonVal::Int(g.advance_um)),
                            ("cluster", JsonVal::Int(i64::from(g.cluster))),
                            ("glyph", JsonVal::Int(i64::from(g.glyph))),
                        ])
                    })
                    .collect();
                obj([
                    ("advance_um", JsonVal::Int(r.advance_um())),
                    ("font", JsonVal::Str(r.font.as_str().to_string())),
                    ("glyphs", JsonVal::Arr(glyphs)),
                    ("size_um", JsonVal::Int(r.size_um)),
                    ("start", JsonVal::Int(i64::from(r.start))),
                    ("text", JsonVal::Str(r.text.clone())),
                ])
            })
            .collect();
        obj([
            ("advance_um", JsonVal::Int(self.advance_um())),
            ("baseline_offset_um", JsonVal::Int(self.baseline_offset_um)),
            ("height_um", JsonVal::Int(self.height_um)),
            ("runs", JsonVal::Arr(runs)),
            ("text", JsonVal::Str(self.text.clone())),
        ])
    }
}

