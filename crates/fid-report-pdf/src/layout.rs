// ------------------------------------------------------------------ errors & warnings

/// Typed errors of the page layout engine (`Design: Errors`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum LayoutError {
    /// `report.layout_invalid`: impossible page or frame geometry.
    LayoutInvalid { field: &'static str, reason: &'static str },
    /// `report.resolved_invalid`: malformed `ResolvedReport` JSON input.
    ResolvedInvalid(String),
    /// Error propagated from text shaping (`RPT.OUTPUT.PDF.TEXT`).
    Text(TextError),
}

impl LayoutError {
    pub fn code(&self) -> &'static str {
        match self {
            LayoutError::LayoutInvalid { .. } => "report.layout_invalid",
            LayoutError::ResolvedInvalid(_) => "report.resolved_invalid",
            LayoutError::Text(e) => e.code(),
        }
    }
}

impl fmt::Display for LayoutError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            LayoutError::LayoutInvalid { field, reason } => {
                write!(f, "report.layout_invalid ({field}): {reason}")
            }
            LayoutError::ResolvedInvalid(msg) => write!(f, "report.resolved_invalid: {msg}"),
            LayoutError::Text(e) => e.fmt(f),
        }
    }
}

impl std::error::Error for LayoutError {}

impl From<TextError> for LayoutError {
    fn from(e: TextError) -> LayoutError {
        LayoutError::Text(e)
    }
}

impl From<JsonError> for LayoutError {
    fn from(e: JsonError) -> LayoutError {
        LayoutError::ResolvedInvalid(e.to_string())
    }
}

/// Non-fatal warning recorded during page layout (e.g. `report.block_overflow`, `REQ-005`).
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct LayoutWarning {
    pub block_id: String,
    pub code: String,
    pub detail: Option<String>,
}

impl LayoutWarning {
    pub fn to_json(&self) -> JsonVal {
        obj([
            ("block_id", JsonVal::Str(self.block_id.clone())),
            ("code", JsonVal::Str(self.code.clone())),
            ("detail", self.detail.as_ref().map_or(JsonVal::Null, |d| JsonVal::Str(d.clone()))),
        ])
    }
}

