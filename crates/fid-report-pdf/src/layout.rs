/// Parsed `ResolvedReport` document read strictly with integer JSON (zero floats).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ResolvedDoc {
    pub digest: Digest,
    pub provenance: JsonVal,
    pub default_page: Option<PageSpec>,
    pub page_overrides: BTreeMap<String, PageSpec>,
    pub pages: Vec<ParsedPage>,
}

/// One logical page in a [`ResolvedDoc`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ParsedPage {
    pub id: String,
    pub blocks: Vec<ParsedBlock>,
}

/// One resolved block in a [`ParsedPage`].
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ParsedBlock {
    pub id: String,
    pub kind: String,
    pub kind_version: u32,
    pub frame_01mm: Option<Frame01Mm>,
    pub payload: JsonVal,
}

impl ResolvedDoc {
    /// Parses a canonical `resolved_report@1` JSON document using pure-integer JSON.
    pub fn from_json_bytes(bytes: &[u8]) -> Result<ResolvedDoc, LayoutError> {
        let root = parse_json(bytes)?;
        Self::from_json(&root)
    }

    /// Parses a [`ResolvedDoc`] from an already-parsed [`JsonVal`].
    pub fn from_json(root: &JsonVal) -> Result<ResolvedDoc, LayoutError> {
        let obj = root
            .as_obj()
            .ok_or_else(|| LayoutError::ResolvedInvalid("resolved report root must be a JSON object".to_string()))?;
        let digest_str = obj
            .get("digest")
            .and_then(JsonVal::as_str)
            .ok_or_else(|| LayoutError::ResolvedInvalid("missing string field 'digest'".to_string()))?;
        let digest = Digest::parse(digest_str)
            .map_err(|_| LayoutError::ResolvedInvalid(format!("invalid digest: {digest_str}")))?;
        let provenance = obj.get("provenance").cloned().unwrap_or(JsonVal::Null);

        let (default_page, page_overrides) = match obj.get("page_layout") {
            None | Some(JsonVal::Null) => (None, BTreeMap::new()),
            Some(pl) => parse_page_layout_section(pl)?,
        };

        let pages_arr = obj
            .get("pages")
            .and_then(JsonVal::as_arr)
            .ok_or_else(|| LayoutError::ResolvedInvalid("missing array field 'pages'".to_string()))?;
        let mut pages = Vec::with_capacity(pages_arr.len());
        for pv in pages_arr {
            let po =
                pv.as_obj().ok_or_else(|| LayoutError::ResolvedInvalid("page entry must be an object".to_string()))?;
            let id = po
                .get("id")
                .and_then(JsonVal::as_str)
                .ok_or_else(|| LayoutError::ResolvedInvalid("page missing string 'id'".to_string()))?
                .to_string();
            let blocks_arr = po
                .get("blocks")
                .and_then(JsonVal::as_arr)
                .ok_or_else(|| LayoutError::ResolvedInvalid(format!("page {id} missing array 'blocks'")))?;
            let mut blocks = Vec::with_capacity(blocks_arr.len());
            for bv in blocks_arr {
                blocks.push(parse_block(bv)?);
            }
            pages.push(ParsedPage { id, blocks });
        }

        Ok(ResolvedDoc { digest, provenance, default_page, page_overrides, pages })
    }
}

fn parse_page_layout_section(v: &JsonVal) -> Result<(Option<PageSpec>, BTreeMap<String, PageSpec>), LayoutError> {
    let o = v.as_obj().ok_or(LayoutError::LayoutInvalid { field: "page_layout", reason: "must_be_object" })?;
    let default_page = if let Some(def) = o.get("default") {
        if def.is_null() {
            None
        } else {
            Some(parse_page_spec(def)?)
        }
    } else if o.contains_key("width") || o.contains_key("size_w") {
        Some(parse_page_spec(v)?)
    } else {
        None
    };
    let mut overrides = BTreeMap::new();
    if let Some(ov) = o.get("overrides").and_then(JsonVal::as_obj) {
        for (page_id, spec_v) in ov {
            overrides.insert(page_id.clone(), parse_page_spec(spec_v)?);
        }
    }
    Ok((default_page, overrides))
}

fn parse_page_spec(v: &JsonVal) -> Result<PageSpec, LayoutError> {
    let o = v.as_obj().ok_or(LayoutError::LayoutInvalid { field: "page_layout", reason: "must_be_object" })?;
    let mut width = parse_01mm_opt(o.get("width").or_else(|| o.get("size_w")), "page.width")?.unwrap_or(21_000);
    let mut height = parse_01mm_opt(o.get("height").or_else(|| o.get("size_h")), "page.height")?.unwrap_or(29_700);
    if o.get("orientation").and_then(JsonVal::as_str) == Some("landscape") && width < height {
        std::mem::swap(&mut width, &mut height);
    }
    let (mt, mr, mb, ml) = if let Some(arr) = o.get("margins").and_then(JsonVal::as_arr) {
        if arr.len() != 4 {
            return Err(LayoutError::LayoutInvalid { field: "margins", reason: "expected_4_elements" });
        }
        (
            parse_01mm_val(&arr[0], "margin_top")?,
            parse_01mm_val(&arr[1], "margin_right")?,
            parse_01mm_val(&arr[2], "margin_bottom")?,
            parse_01mm_val(&arr[3], "margin_left")?,
        )
    } else {
        (
            parse_01mm_opt(o.get("margin_top"), "margin_top")?.unwrap_or(1_500),
            parse_01mm_opt(o.get("margin_right"), "margin_right")?.unwrap_or(1_500),
            parse_01mm_opt(o.get("margin_bottom"), "margin_bottom")?.unwrap_or(1_500),
            parse_01mm_opt(o.get("margin_left"), "margin_left")?.unwrap_or(1_500),
        )
    };
    let header = parse_01mm_opt(o.get("header"), "header")?.unwrap_or(0);
    let footer = parse_01mm_opt(o.get("footer"), "footer")?.unwrap_or(0);
    PageSpec::from_01mm(width, height, mt, mr, mb, ml, header, footer)
}

fn parse_01mm_opt(v: Option<&JsonVal>, field: &'static str) -> Result<Option<i64>, LayoutError> {
    match v {
        None | Some(JsonVal::Null) => Ok(None),
        Some(other) => parse_01mm_val(other, field).map(Some),
    }
}

/// Parses an integer count of `0.01 mm` units from a JSON integer or string (supporting optional
/// exact `mm` or `in` suffixes using integer arithmetic only).
pub fn parse_01mm_val(v: &JsonVal, field: &'static str) -> Result<i64, LayoutError> {
    match v {
        JsonVal::Int(n) => Ok(*n),
        JsonVal::Str(s) => parse_01mm_str(s, field),
        _ => Err(LayoutError::LayoutInvalid { field, reason: "expected_integer_01mm" }),
    }
}

/// Parses a length string into exact `0.01 mm` units:
/// - bare integer string (e.g. `"1500"`) -> `1500` units (`15.00 mm = 15_000 µm`)
/// - `"15mm"` / `"15.25mm"` -> exact `1500` / `1525` units (rejects >2 decimal digits)
/// - `"8.5in"` / `"1in"` -> exact `21590` / `2540` units (`1 in = 2540` units)
pub fn parse_01mm_str(raw: &str, field: &'static str) -> Result<i64, LayoutError> {
    let s = raw.trim();
    if let Some(mm) = s.strip_suffix("mm") {
        return parse_scaled_decimal(mm.trim(), 100, field);
    }
    if let Some(inches) = s.strip_suffix("in") {
        return parse_scaled_decimal(inches.trim(), 2540, field);
    }
    s.parse::<i64>().map_err(|_| LayoutError::LayoutInvalid { field, reason: "invalid_01mm_integer" })
}

fn parse_scaled_decimal(raw: &str, scale: i64, field: &'static str) -> Result<i64, LayoutError> {
    if raw.is_empty() {
        return Err(LayoutError::LayoutInvalid { field, reason: "empty_length" });
    }
    let (neg, rest) = match raw.strip_prefix('-') {
        Some(r) => (true, r),
        None => (false, raw.strip_prefix('+').unwrap_or(raw)),
    };
    let (int_s, frac_s) = match rest.split_once('.') {
        Some((a, b)) => (a, b),
        None => (rest, ""),
    };
    if int_s.is_empty() || !int_s.bytes().all(|b| b.is_ascii_digit()) || !frac_s.bytes().all(|b| b.is_ascii_digit()) {
        return Err(LayoutError::LayoutInvalid { field, reason: "invalid_decimal_length" });
    }
    if frac_s.len() > 6 {
        return Err(LayoutError::LayoutInvalid { field, reason: "not_exact_multiple_of_01mm" });
    }
    let int_part: i128 = int_s.parse().map_err(|_| LayoutError::LayoutInvalid { field, reason: "overflow" })?;
    let mut denom: i128 = 1;
    for _ in 0..frac_s.len() {
        denom *= 10;
    }
    let frac_part: i128 = if frac_s.is_empty() {
        0
    } else {
        frac_s.parse().map_err(|_| LayoutError::LayoutInvalid { field, reason: "overflow" })?
    };
    let total_num = int_part
        .checked_mul(denom)
        .and_then(|v| v.checked_add(frac_part))
        .and_then(|v| v.checked_mul(i128::from(scale)))
        .ok_or(LayoutError::LayoutInvalid { field, reason: "overflow" })?;
    if total_num % denom != 0 {
        return Err(LayoutError::LayoutInvalid { field, reason: "not_exact_multiple_of_01mm" });
    }
    let mut units = total_num / denom;
    if neg {
        units = -units;
    }
    i64::try_from(units).map_err(|_| LayoutError::LayoutInvalid { field, reason: "overflow" })
}

fn parse_block(v: &JsonVal) -> Result<ParsedBlock, LayoutError> {
    let o = v.as_obj().ok_or_else(|| LayoutError::ResolvedInvalid("block entry must be an object".to_string()))?;
    let id = o
        .get("id")
        .and_then(JsonVal::as_str)
        .ok_or_else(|| LayoutError::ResolvedInvalid("block missing string 'id'".to_string()))?
        .to_string();
    let kind = o
        .get("kind")
        .and_then(JsonVal::as_str)
        .ok_or_else(|| LayoutError::ResolvedInvalid(format!("block {id} missing string 'kind'")))?
        .to_string();
    let kind_version = match o.get("kind_version") {
        Some(JsonVal::Int(n)) if *n >= 0 => u32::try_from(*n).unwrap_or(1),
        Some(JsonVal::Str(s)) => s.parse::<u32>().unwrap_or(1),
        _ => 1,
    };
    let frame_01mm = match o.get("frame") {
        None | Some(JsonVal::Null) => None,
        Some(fv) => {
            let fo = fv.as_obj().ok_or(LayoutError::LayoutInvalid { field: "frame", reason: "must_be_object" })?;
            let x = parse_01mm_val(
                fo.get("x").ok_or(LayoutError::LayoutInvalid { field: "frame.x", reason: "missing" })?,
                "frame.x",
            )?;
            let y = parse_01mm_val(
                fo.get("y").ok_or(LayoutError::LayoutInvalid { field: "frame.y", reason: "missing" })?,
                "frame.y",
            )?;
            let width = parse_01mm_val(
                fo.get("width").ok_or(LayoutError::LayoutInvalid { field: "frame.width", reason: "missing" })?,
                "frame.width",
            )?;
            let height = parse_01mm_val(
                fo.get("height").ok_or(LayoutError::LayoutInvalid { field: "frame.height", reason: "missing" })?,
                "frame.height",
            )?;
            Some(Frame01Mm { x, y, width, height })
        }
    };
    let payload = o.get("payload").cloned().unwrap_or(JsonVal::Null);
    Ok(ParsedBlock { id, kind, kind_version, frame_01mm, payload })
}

