//! Integer-µm page layout engine with page breaks, continuation headers, column groups,
//! designer frames, and page-number fill-in (spec node `RPT.OUTPUT.PDF.LAYOUT`).
//!
//! - All geometry and text positions are computed strictly in integer micrometres (`i64`) with
//!   no floating point, guaranteeing byte-identical display lists on x86-64, ARM64 and wasm32
//!   (`REQ-RPT.OUTPUT.PDF.LAYOUT-001`, D0).
//! - Designer frames stored in exact `0.01 mm` integer units convert to µm via `* 10`
//!   (`REQ-002`, `AC-5`). Unframed blocks stack top-to-bottom in document order within the body
//!   area (`REQ-002`).
//! - Tables paginate cleanly between rows, repeating `repeat_header_rows` and an optional
//!   identifying `continuation_block` on every continuation page (`REQ-003`, `AC-2`).
//! - Wide tables with `max_columns_per_group` split into successive column groups, each
//!   repeating `repeat_columns` (`REQ-004`, `AC-3`).
//! - Any unbreakable block or single table row taller than the body area is placed clipped on
//!   its own page with warning `report.block_overflow` naming the block (`REQ-005`, `AC-4`).
//! - After pagination, page-number and page-count placeholders are filled and re-shaped so
//!   every page reads `n of m` accurately (`REQ-006`, `AC-2`).

