//! `convergence-check` and `convergence-doc`: the registry-manifest `convergence` block of
//! iterative alignment methods, its CI check and its generated documentation fragment (spec
//! node `ALN.QA.HIST`, REQ-ALN.QA.HIST-003, -004, -005).
//!
//! # Input
//!
//! A registry manifest in the `CORE.REG.MAN` shape (`{"format", "commands": [..], ..}`),
//! parsed strictly with `fid-canon` (duplicate keys refused). Of each command only these
//! fields are read; everything else is ignored:
//!
//! - `id` (string) and `major` (integer `0..=99999`): the command `id@major`;
//! - `iterative` (boolean, absent = `false`): the command's algorithm is iterative;
//! - `convergence`: an array of criteria `{ "name", "unit", "default", "meaning" }`.
//!
//! Until `CORE.REG.DEF` declares `iterative` and `convergence` on `CommandDef` (see the
//! leaf's Open questions), the check reads them from a manifest-shaped file, as
//! `registry-gate` reads its current declarations.
//!
//! # Rules (REQ-003, REQ-004)
//!
//! For every command with `iterative: true`, in sorted command order (ID bytes, then major):
//!
//! - no `convergence` field, or an empty array: `manifest_convergence_missing`, field
//!   `/convergence`;
//! - a criterion without `name`, `unit`, `default` or `meaning`, or with an empty string
//!   there: `manifest_field_missing`, field `/convergence/<i>/<key>`;
//! - a value of the wrong type or form: `manifest_field_invalid` at the same field. `name` is
//!   `[a-z0-9_]`, 1 to 64 bytes, unique within the block; `unit` is 1 to 16 printable ASCII
//!   characters other than space, `|` and backtick; `default` is a string holding a JSON
//!   decimal number (`-?(0|[1-9][0-9]*)(\.[0-9]+)?([eE][+-]?[0-9]+)?`); `meaning` is 1 to
//!   [`MAX_MEANING_CHARS`] characters with no control character; `iterative` must be a
//!   boolean and `convergence` an array (field `/iterative`, `/convergence`).
//!
//! A command `id@major` listed twice is `manifest_duplicate_command`. Input that is not such
//! a manifest at all (unreadable, over [`MAX_MANIFEST_BYTES`], not JSON, no `commands` array,
//! a command without a string `id` or a valid `major`, more than [`MAX_COMMANDS`] commands
//! or [`MAX_CRITERIA`] criteria in one block) is `manifest_invalid`, exit 2.
//!
//! **Report.** One line per finding, the RFC 8785 form of
//! `{"code", "command", "field"}` (command as `id@major`), sorted by command, field and
//! code; then `convergence-check: fail (N)`, exit 1. Or `convergence-check: ok (K iterative
//! commands)`, exit 0.
//!
//! # Fragment (REQ-005)
//!
//! [`render_fragment`] writes Markdown from the manifest only: a header comment saying so,
//! then per iterative command in the same sorted order a level-2 heading with the command
//! `id@major` as code, and a table `| Criterion | Unit | Default | Meaning |` with one row per
//! criterion in declared order (a `|` in a meaning is escaped with a backslash). It refuses a manifest the check fails. LF line
//! ends; the bytes depend only on the input (D0). `convergence-doc --check <file>` fails when
//! a committed fragment differs from the generated one, so it is never edited by hand.

use fid_canon::{parse_with_limits, to_canonical_bytes, CValue};
use std::collections::BTreeMap;
use std::path::Path;
use std::process::ExitCode;

/// Largest accepted manifest file.
pub const MAX_MANIFEST_BYTES: usize = 16 * 1024 * 1024;
/// Deepest accepted JSON nesting.
pub const MAX_DEPTH: usize = 64;
/// Most commands in one manifest.
pub const MAX_COMMANDS: usize = 100_000;
/// Most criteria in one convergence block.
pub const MAX_CRITERIA: usize = 64;
/// Longest criterion meaning, in characters.
pub const MAX_MEANING_CHARS: usize = 120;
/// Longest unit, in bytes.
pub const MAX_UNIT_BYTES: usize = 16;
/// Longest criterion name, in bytes.
pub const MAX_NAME_BYTES: usize = 64;

/// The first line of every fragment.
pub const FRAGMENT_HEADER: &str = "<!-- Generated by `cargo xtask convergence-doc` from the registry manifest \
                                   (ALN.QA.HIST). Do not edit by hand. -->";

/// Usage of `convergence-check`.
pub const CHECK_USAGE: &str = "usage: cargo xtask convergence-check --manifest <registry manifest json>";
/// Usage of `convergence-doc`.
pub const DOC_USAGE: &str =
    "usage: cargo xtask convergence-doc --manifest <registry manifest json> [--out <file> | --check <file>]";

/// A command reference `id@major`, ordered by ID bytes then major.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct CommandKey {
    /// The command ID.
    pub id: String,
    /// The major version.
    pub major: u32,
}

impl CommandKey {
    /// `id@major`.
    pub fn text(&self) -> String {
        format!("{}@{}", self.id, self.major)
    }
}

/// One finding of the check.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct Finding {
    /// The command.
    pub command: CommandKey,
    /// RFC 6901 pointer into the command object.
    pub field: String,
    /// The code.
    pub code: &'static str,
}

impl Finding {
    /// The canonical report line.
    pub fn line(&self) -> String {
        let mut o = BTreeMap::new();
        o.insert("code".to_string(), CValue::Str(self.code.to_string()));
        o.insert("command".to_string(), CValue::Str(self.command.text()));
        o.insert("field".to_string(), CValue::Str(self.field.clone()));
        let bytes = to_canonical_bytes(&CValue::Obj(o)).unwrap_or_default();
        String::from_utf8(bytes).unwrap_or_default()
    }
}

/// A criterion of a valid block.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Criterion {
    pub name: String,
    pub unit: String,
    pub default: String,
    pub meaning: String,
}

/// The iterative commands of a manifest with their blocks, and the findings.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct Checked {
    /// Every iterative command in sorted order, with the criteria that passed.
    pub iterative: Vec<(CommandKey, Vec<Criterion>)>,
    /// The findings, sorted; empty when the check passes.
    pub findings: Vec<Finding>,
}

/// Why the input is not a manifest (`manifest_invalid`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct InvalidManifest(pub String);

impl std::fmt::Display for InvalidManifest {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "manifest_invalid: {}", self.0)
    }
}

fn invalid(s: impl Into<String>) -> InvalidManifest {
    InvalidManifest(s.into())
}

fn is_name(s: &str) -> bool {
    let b = s.as_bytes();
    !b.is_empty()
        && b.len() <= MAX_NAME_BYTES
        && b.iter().all(|&c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == b'_')
}

fn is_unit(s: &str) -> bool {
    let b = s.as_bytes();
    !b.is_empty() && b.len() <= MAX_UNIT_BYTES && b.iter().all(|&c| c.is_ascii_graphic() && c != b'|' && c != b'`')
}

/// A JSON decimal number: `-?(0|[1-9][0-9]*)(\.[0-9]+)?([eE][+-]?[0-9]+)?`.
pub fn is_decimal(s: &str) -> bool {
    let b = s.as_bytes();
    let mut i = 0;
    let digits = |i: &mut usize| {
        let start = *i;
        while b.get(*i).is_some_and(u8::is_ascii_digit) {
            *i += 1;
        }
        *i - start
    };
    if b.get(i) == Some(&b'-') {
        i += 1;
    }
    match b.get(i) {
        Some(b'0') => i += 1,
        Some(c) if c.is_ascii_digit() => {
            digits(&mut i);
        }
        _ => return false,
    }
    if b.get(i) == Some(&b'.') {
        i += 1;
        if digits(&mut i) == 0 {
            return false;
        }
    }
    if matches!(b.get(i), Some(b'e' | b'E')) {
        i += 1;
        if matches!(b.get(i), Some(b'+' | b'-')) {
            i += 1;
        }
        if digits(&mut i) == 0 {
            return false;
        }
    }
    i == b.len()
}

fn is_meaning(s: &str) -> bool {
    let n = s.chars().count();
    (1..=MAX_MEANING_CHARS).contains(&n) && !s.chars().any(char::is_control)
}

fn major_of(v: Option<&CValue>) -> Option<u32> {
    let x = match v? {
        CValue::Num(x) => *x,
        CValue::U64(u) => return u32::try_from(*u).ok().filter(|m| *m <= 99_999),
        CValue::I64(i) => return u32::try_from(*i).ok().filter(|m| *m <= 99_999),
        _ => return None,
    };
    if (0.0..=99_999.0).contains(&x) && x.fract() == 0.0 {
        Some(x as u32)
    } else {
        None
    }
}

/// Checks the criteria of one iterative command.
fn check_block(
    key: &CommandKey,
    cmd: &BTreeMap<String, CValue>,
    findings: &mut Vec<Finding>,
) -> Result<Vec<Criterion>, InvalidManifest> {
    let mut find = |field: String, code: &'static str| findings.push(Finding { command: key.clone(), field, code });
    let items = match cmd.get("convergence") {
        None => {
            find("/convergence".into(), "manifest_convergence_missing");
            return Ok(Vec::new());
        }
        Some(CValue::Arr(a)) if a.is_empty() => {
            find("/convergence".into(), "manifest_convergence_missing");
            return Ok(Vec::new());
        }
        Some(CValue::Arr(a)) => a,
        Some(_) => {
            find("/convergence".into(), "manifest_field_invalid");
            return Ok(Vec::new());
        }
    };
    if items.len() > MAX_CRITERIA {
        return Err(invalid(format!("{}: more than {MAX_CRITERIA} criteria", key.text())));
    }
    let mut out = Vec::new();
    let mut names: Vec<&str> = Vec::new();
    for (i, item) in items.iter().enumerate() {
        let CValue::Obj(o) = item else {
            find(format!("/convergence/{i}"), "manifest_field_invalid");
            continue;
        };
        let mut vals: [Option<&str>; 4] = [None; 4];
        let keys = ["name", "unit", "default", "meaning"];
        let checks: [fn(&str) -> bool; 4] = [is_name, is_unit, is_decimal, is_meaning];
        for (k, (&field, ok)) in keys.iter().zip(checks).enumerate() {
            let pointer = format!("/convergence/{i}/{field}");
            match o.get(field) {
                None => find(pointer, "manifest_field_missing"),
                Some(CValue::Str(s)) if s.is_empty() => find(pointer, "manifest_field_missing"),
                Some(CValue::Str(s)) if ok(s) => vals[k] = Some(s),
                Some(_) => find(pointer, "manifest_field_invalid"),
            }
        }
        if let Some(n) = vals[0] {
            if names.contains(&n) {
                find(format!("/convergence/{i}/name"), "manifest_field_invalid");
                continue;
            }
            names.push(n);
        }
        if let [Some(name), Some(unit), Some(default), Some(meaning)] = vals {
            out.push(Criterion {
                name: name.to_string(),
                unit: unit.to_string(),
                default: default.to_string(),
                meaning: meaning.to_string(),
            });
        }
    }
    Ok(out)
}

/// Checks a parsed manifest (rules in the [module documentation](self)).
pub fn check(manifest: &CValue) -> Result<Checked, InvalidManifest> {
    let CValue::Obj(top) = manifest else { return Err(invalid("not an object")) };
    let Some(CValue::Arr(commands)) = top.get("commands") else { return Err(invalid("no commands array")) };
    if commands.len() > MAX_COMMANDS {
        return Err(invalid(format!("more than {MAX_COMMANDS} commands")));
    }
    let mut keyed: Vec<(CommandKey, &BTreeMap<String, CValue>)> = Vec::new();
    for (i, c) in commands.iter().enumerate() {
        let CValue::Obj(o) = c else { return Err(invalid(format!("commands[{i}] is not an object"))) };
        let Some(CValue::Str(id)) = o.get("id") else { return Err(invalid(format!("commands[{i}] has no id"))) };
        let Some(major) = major_of(o.get("major")) else {
            return Err(invalid(format!("commands[{i}] has no valid major")));
        };
        keyed.push((CommandKey { id: id.clone(), major }, o));
    }
    keyed.sort_by(|a, b| a.0.cmp(&b.0));
    let mut out = Checked::default();
    for (n, (key, cmd)) in keyed.iter().enumerate() {
        if n > 0 && keyed.get(n - 1).is_some_and(|p| p.0 == *key) {
            out.findings.push(Finding {
                command: key.clone(),
                field: String::new(),
                code: "manifest_duplicate_command",
            });
            continue;
        }
        let iterative = match cmd.get("iterative") {
            None | Some(CValue::Bool(false)) => false,
            Some(CValue::Bool(true)) => true,
            Some(_) => {
                out.findings.push(Finding {
                    command: key.clone(),
                    field: "/iterative".into(),
                    code: "manifest_field_invalid",
                });
                continue;
            }
        };
        if iterative {
            let crit = check_block(key, cmd, &mut out.findings)?;
            out.iterative.push((key.clone(), crit));
        }
    }
    out.findings.sort();
    out.findings.dedup();
    Ok(out)
}

/// Reads and parses a manifest file within the bounds.
pub fn load(path: &Path) -> Result<CValue, InvalidManifest> {
    use std::io::Read;
    let f = std::fs::File::open(path).map_err(|e| invalid(format!("{}: {e}", path.display())))?;
    let mut bytes = Vec::new();
    f.take(MAX_MANIFEST_BYTES as u64 + 1)
        .read_to_end(&mut bytes)
        .map_err(|e| invalid(format!("{}: {e}", path.display())))?;
    if bytes.len() > MAX_MANIFEST_BYTES {
        return Err(invalid(format!("{}: larger than {MAX_MANIFEST_BYTES} bytes", path.display())));
    }
    parse_with_limits(&bytes, MAX_MANIFEST_BYTES, MAX_DEPTH).map_err(|e| invalid(format!("{}: {e}", path.display())))
}

/// The check report (rules in the [module documentation](self)).
pub fn report(c: &Checked) -> String {
    let mut s = String::new();
    for f in &c.findings {
        s.push_str(&f.line());
        s.push('\n');
    }
    if c.findings.is_empty() {
        s.push_str(&format!("convergence-check: ok ({} iterative commands)\n", c.iterative.len()));
    } else {
        s.push_str(&format!("convergence-check: fail ({})\n", c.findings.len()));
    }
    s
}

/// The documentation fragment of a manifest that passed the check; `None` otherwise.
pub fn render_fragment(c: &Checked) -> Option<String> {
    if !c.findings.is_empty() {
        return None;
    }
    let mut s = String::new();
    s.push_str(FRAGMENT_HEADER);
    s.push('\n');
    if c.iterative.is_empty() {
        s.push_str("\n_No iterative commands._\n");
    }
    for (key, crit) in &c.iterative {
        s.push_str(&format!("\n## `{}`\n\n", key.text()));
        s.push_str("| Criterion | Unit | Default | Meaning |\n|---|---|---|---|\n");
        for k in crit {
            let meaning = k.meaning.replace('|', "\\|");
            s.push_str(&format!("| `{}` | {} | {} | {} |\n", k.name, k.unit, k.default, meaning));
        }
    }
    Some(s)
}

/// The `--manifest` value and the other `(flag, value)` pairs of a command line.
type Args = (Option<String>, Vec<(String, String)>);

fn manifest_arg(args: &[String], usage: &str) -> Result<Args, ExitCode> {
    let mut manifest = None;
    let mut rest = Vec::new();
    let mut it = args.iter();
    while let Some(a) = it.next() {
        match (a.as_str(), it.next()) {
            ("--manifest", Some(v)) => manifest = Some(v.clone()),
            (k @ ("--out" | "--check"), Some(v)) => rest.push((k.to_string(), v.clone())),
            _ => {
                eprintln!("{usage}");
                return Err(ExitCode::from(2));
            }
        }
    }
    Ok((manifest, rest))
}

fn load_checked(manifest: Option<String>, usage: &str) -> Result<Checked, ExitCode> {
    let Some(m) = manifest else {
        eprintln!("--manifest is required\n{usage}");
        return Err(ExitCode::from(2));
    };
    match load(Path::new(&m)).and_then(|v| check(&v)) {
        Ok(c) => Ok(c),
        Err(e) => {
            eprintln!("{e}");
            Err(ExitCode::from(2))
        }
    }
}

/// `convergence-check`: exit 0 pass, 1 findings, 2 usage or `manifest_invalid`.
pub fn check_cli(args: &[String]) -> ExitCode {
    let (manifest, rest) = match manifest_arg(args, CHECK_USAGE) {
        Ok(x) => x,
        Err(code) => return code,
    };
    if !rest.is_empty() {
        eprintln!("{CHECK_USAGE}");
        return ExitCode::from(2);
    }
    let c = match load_checked(manifest, CHECK_USAGE) {
        Ok(c) => c,
        Err(code) => return code,
    };
    print!("{}", report(&c));
    if c.findings.is_empty() {
        ExitCode::SUCCESS
    } else {
        ExitCode::from(1)
    }
}

/// `convergence-doc`: prints the fragment, writes it (`--out`) or compares it with a file
/// (`--check`, exit 1 when it differs). Exit 1 when the manifest fails the check.
pub fn doc_cli(args: &[String]) -> ExitCode {
    let (manifest, rest) = match manifest_arg(args, DOC_USAGE) {
        Ok(x) => x,
        Err(code) => return code,
    };
    if rest.len() > 1 {
        eprintln!("{DOC_USAGE}");
        return ExitCode::from(2);
    }
    let c = match load_checked(manifest, DOC_USAGE) {
        Ok(c) => c,
        Err(code) => return code,
    };
    let Some(text) = render_fragment(&c) else {
        eprint!("{}", report(&c));
        return ExitCode::from(1);
    };
    match rest.first().map(|(k, v)| (k.as_str(), v)) {
        None => {
            print!("{text}");
            ExitCode::SUCCESS
        }
        Some(("--out", path)) => match std::fs::write(path, text.as_bytes()) {
            Ok(()) => ExitCode::SUCCESS,
            Err(e) => {
                eprintln!("convergence-doc: {path}: {e}");
                ExitCode::from(2)
            }
        },
        Some((_, path)) => match std::fs::read(path) {
            Ok(b) if b == text.as_bytes() => {
                println!("convergence-doc: {path} is up to date");
                ExitCode::SUCCESS
            }
            Ok(_) => {
                eprintln!("convergence-doc: {path} differs from the fragment generated from the manifest");
                ExitCode::from(1)
            }
            Err(e) => {
                eprintln!("convergence-doc: {path}: {e}");
                ExitCode::from(2)
            }
        },
    }
}

#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]
    use super::*;

    #[test]
    fn decimals() {
        for ok in ["0", "-0", "1e-9", "1E+3", "12.5", "100", "0.001", "-3.25e-12"] {
            assert!(is_decimal(ok), "{ok}");
        }
        for bad in ["", "-", "01", ".5", "5.", "1e", "1e+", "+1", "0x10", "NaN", "inf", "1 ", "1,0"] {
            assert!(!is_decimal(bad), "{bad}");
        }
    }

    #[test]
    fn units_names_meanings() {
        assert!(is_unit("m") && is_unit("rad") && is_unit("1") && is_unit("m^2"));
        assert!(!is_unit("") && !is_unit("a b") && !is_unit("a|b") && !is_unit("`m`") && !is_unit(&"m".repeat(17)));
        assert!(is_name("max_iterations") && !is_name("Max") && !is_name(""));
        assert!(is_meaning(&"é".repeat(120)) && !is_meaning(&"x".repeat(121)) && !is_meaning("a\nb"));
    }
}
