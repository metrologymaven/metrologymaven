//! `cargo xtask rel notes`: the release notes generator (spec node `ECO.REL.PROC.NOTES`).
//!
//! Writes `<out>/release-notes.md` from two inputs and nothing else:
//!
//! - `--prs <json>`: the exported list of merged PRs for the release, an object
//!   `{tag, channel, previous_tag, commit, prs: [{number, title, labels, merged_at, merge_commit}]}`.
//!   The export step (`ECO.REL.PROC.FLOW`) limits `prs` to the range from the previous tag on the
//!   same channel to the current tag and records that range in `previous_tag` and `tag`; this tool
//!   checks the range (both tags parse, are on `--channel`, and the previous one has lower
//!   precedence) and that every PR appears once.
//! - `--reports <dir>`: the six attached reports (`parity.json`, `parity.md`, `status.json`,
//!   `status.md`, `release-numbers.json`, `release-gates.json`), the evidence-bundle statement
//!   `evidence/statement.json` (`QUAL.EVID.LAYOUT`) and the threat register summary
//!   `threat/register-summary.json` (`QUAL.THREAT.REG`).
//!
//! PRs are grouped by the first of their labels in the fixed order `feature`, `fix`,
//! `security`, `breaking`, `docs`, `internal` (labels compare ASCII case-insensitively, as the
//! code host treats them); a PR with none of these goes to "Other". Within a group PRs are sorted
//! by number. PR titles and gate notes are untrusted: control and bidirectional formatting
//! characters become spaces, text over [`MAX_TITLE_CHARS`] characters is cut and marked, and every
//! ASCII punctuation character is backslash-escaped (CommonMark renders an escaped punctuation
//! character literally, so no link, emphasis, HTML or heading can be formed).
//!
//! The tool reads files only: no git, no network, no clock. The output is a pure function of
//! the input bytes (D0) with LF line endings on every OS; it is written to a temporary file in
//! the output directory and renamed into place, and nothing is written when a check fails.

use super::sums::hash_file;
use super::version::{check_tag, Channel, Version};
use fid_canon::{parse_with_limits, CValue};
use fid_types::Digest;
use std::collections::{BTreeMap, BTreeSet};
use std::fmt;
use std::io::Read;
use std::path::Path;
use std::process::ExitCode;

/// Usage line, printed by the binary on bad usage.
pub const USAGE: &str = "usage: cargo xtask rel notes --tag <tag> --channel nightly|beta|stable|lts --prs <prs.json> \
                         --reports <dir> --out <dir>";
/// First line of every generated file (REQ-ECO.REL.PROC.NOTES-004).
pub const HEADER: &str = "Generated by fid-xtask rel notes. Do not edit.";
/// Name of the output file.
pub const NOTES_FILE: &str = "release-notes.md";
/// The reports attached to the release, in table order (REQ-ECO.REL.PROC.NOTES-002).
pub const ATTACHMENTS: [&str; 6] =
    ["parity.json", "parity.md", "status.json", "status.md", "release-numbers.json", "release-gates.json"];
/// The gate verdict, among the attachments.
pub const GATES_FILE: &str = "release-gates.json";
/// The evidence-bundle statement, relative to the reports directory.
pub const EVIDENCE_FILE: &str = "evidence/statement.json";
/// The threat register summary, relative to the reports directory.
pub const THREAT_FILE: &str = "threat/register-summary.json";
/// Schema name the threat summary must carry.
pub const THREAT_SCHEMA: &str = "qual-threat-summary/1";
/// The gate whose notes are the Tier 2 build failures (`ECO.REL.PKG.PLAN` package-build gate).
pub const PKG_GATE: &str = "pkg-plan";
/// Labels in group order, with their headings; anything else goes to [`OTHER`].
pub const GROUPS: [(&str, &str); 6] = [
    ("feature", "Features"),
    ("fix", "Fixes"),
    ("security", "Security"),
    ("breaking", "Breaking changes"),
    ("docs", "Documentation"),
    ("internal", "Internal"),
];
/// Heading of the group for PRs with none of the [`GROUPS`] labels.
pub const OTHER: &str = "Other";
/// Longest title (or gate note) shown, in characters; longer ones are cut and marked.
pub const MAX_TITLE_CHARS: usize = 200;
/// Appended to a cut title.
pub const TRUNCATED: &str = "... (truncated)";
/// Largest JSON input read (`prs.json`, `release-gates.json`, the threat summary).
pub const MAX_JSON_BYTES: u64 = 16 << 20;
/// Deepest JSON nesting accepted.
pub const MAX_DEPTH: usize = 16;
/// Most PRs in one export.
pub const MAX_PRS: usize = 20_000;
/// Most labels on one PR, gates in the verdict, or notes on one gate.
pub const MAX_ITEMS: usize = 1_000;
/// Longest label, gate ID, tag or timestamp string, in bytes.
pub const MAX_SHORT_BYTES: usize = 256;
/// Largest PR number accepted (the largest integer a JSON double holds exactly).
pub const MAX_PR_NUMBER: f64 = 9_007_199_254_740_991.0;

/// A failure. [`fmt::Display`] gives the line the tool prints.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum NotesError {
    /// `NOTES-MISSING <file>`: a required report is absent (exit 1).
    Missing(String),
    /// `INPUT-PARSE: <reason>`: an input is unreadable or not the expected shape (exit 2).
    Parse(String),
    /// `NOTES-IO: <reason>`: the output could not be written (exit 2).
    Io(String),
}

impl NotesError {
    /// Stable error code.
    pub fn code(&self) -> &'static str {
        match self {
            NotesError::Missing(_) => "NOTES-MISSING",
            NotesError::Parse(_) => "INPUT-PARSE",
            NotesError::Io(_) => "NOTES-IO",
        }
    }

    /// Process exit code: 1 for a missing report, 2 otherwise.
    pub fn exit_code(&self) -> u8 {
        match self {
            NotesError::Missing(_) => 1,
            NotesError::Parse(_) | NotesError::Io(_) => 2,
        }
    }
}

impl fmt::Display for NotesError {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            NotesError::Missing(n) => write!(f, "{} {n}", self.code()),
            NotesError::Parse(m) | NotesError::Io(m) => write!(f, "{}: {m}", self.code()),
        }
    }
}

impl std::error::Error for NotesError {}

fn parse_err(m: impl Into<String>) -> NotesError {
    NotesError::Parse(m.into())
}

/// One merged PR.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Pr {
    pub number: u64,
    pub title: String,
    pub labels: Vec<String>,
    pub merged_at: String,
    pub merge_commit: String,
}

/// The PR export for one release.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Export {
    pub tag: String,
    pub version: Version,
    pub channel: Channel,
    pub previous_tag: Option<String>,
    pub commit: String,
    pub prs: Vec<Pr>,
}

/// What the notes take from `release-gates.json`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Gates {
    pub verdict: String,
    pub tier2_failures: Vec<String>,
}

/// Everything read from the reports directory.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Reports {
    /// (file name, digest), in [`ATTACHMENTS`] order.
    pub attachments: Vec<(&'static str, Digest)>,
    pub gates: Gates,
    pub evidence: Digest,
    pub high_threats: u64,
}

/// Shortens untrusted text for messages.
fn shown(s: &str) -> String {
    let mut end = s.len().min(64);
    while !s.is_char_boundary(end) {
        end -= 1;
    }
    let cut = s.get(..end).unwrap_or("");
    if cut.len() < s.len() {
        format!("{cut:?}...")
    } else {
        format!("{cut:?}")
    }
}

/// Reads a file of at most `max` bytes; `Ok(None)` when it does not exist.
fn read_bounded(path: &Path, max: u64) -> Result<Option<Vec<u8>>, NotesError> {
    let file = match std::fs::File::open(path) {
        Ok(f) => f,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(None),
        Err(e) => return Err(parse_err(format!("cannot read {}: {e}", path.display()))),
    };
    let mut bytes = Vec::new();
    file.take(max + 1)
        .read_to_end(&mut bytes)
        .map_err(|e| parse_err(format!("cannot read {}: {e}", path.display())))?;
    if bytes.len() as u64 > max {
        return Err(parse_err(format!("{} is larger than {max} bytes", path.display())));
    }
    Ok(Some(bytes))
}

fn json(bytes: &[u8], label: &str) -> Result<BTreeMap<String, CValue>, NotesError> {
    let max = usize::try_from(MAX_JSON_BYTES).unwrap_or(usize::MAX);
    match parse_with_limits(bytes, max, MAX_DEPTH) {
        Ok(CValue::Obj(o)) => Ok(o),
        Ok(_) => Err(parse_err(format!("{label}: not a JSON object"))),
        Err(e) => Err(parse_err(format!("{label}: {e}"))),
    }
}

fn get_str<'a>(o: &'a BTreeMap<String, CValue>, key: &str, at: &str) -> Result<&'a str, NotesError> {
    match o.get(key) {
        Some(CValue::Str(s)) => Ok(s),
        Some(_) => Err(parse_err(format!("{at}: `{key}` must be a string"))),
        None => Err(parse_err(format!("{at}: missing `{key}`"))),
    }
}

fn get_short<'a>(o: &'a BTreeMap<String, CValue>, key: &str, at: &str) -> Result<&'a str, NotesError> {
    let s = get_str(o, key, at)?;
    if s.is_empty() || s.len() > MAX_SHORT_BYTES {
        return Err(parse_err(format!("{at}: `{key}` must hold 1 to {MAX_SHORT_BYTES} bytes")));
    }
    Ok(s)
}

fn get_arr<'a>(o: &'a BTreeMap<String, CValue>, key: &str, at: &str, max: usize) -> Result<&'a [CValue], NotesError> {
    match o.get(key) {
        Some(CValue::Arr(a)) if a.len() <= max => Ok(a.as_slice()),
        Some(CValue::Arr(_)) => Err(parse_err(format!("{at}: `{key}` has more than {max} entries"))),
        Some(_) => Err(parse_err(format!("{at}: `{key}` must be an array"))),
        None => Err(parse_err(format!("{at}: missing `{key}`"))),
    }
}

/// A non-negative JSON integer no larger than `max`.
fn as_int(v: &CValue, max: f64) -> Option<u64> {
    match v {
        CValue::Num(n) if (0.0..=max).contains(n) && n.trunc() == *n => Some(*n as u64),
        _ => None,
    }
}

/// A git object ID: 40 (SHA-1) or 64 (SHA-256) lowercase hex digits.
pub fn is_commit(s: &str) -> bool {
    (s.len() == 40 || s.len() == 64) && s.bytes().all(|b| b.is_ascii_digit() || (b'a'..=b'f').contains(&b))
}

fn parse_pr(v: &CValue, i: usize) -> Result<Pr, NotesError> {
    let at = format!("prs.json: prs[{i}]");
    let CValue::Obj(o) = v else { return Err(parse_err(format!("{at}: not an object"))) };
    let number = match o.get("number") {
        Some(n) => as_int(n, MAX_PR_NUMBER).filter(|n| *n >= 1),
        None => return Err(parse_err(format!("{at}: missing `number`"))),
    }
    .ok_or_else(|| parse_err(format!("{at}: `number` must be a positive integer")))?;
    let at = format!("prs.json: PR #{number}");
    let title = get_str(o, "title", &at)?.to_string();
    let mut labels = Vec::new();
    for l in get_arr(o, "labels", &at, MAX_ITEMS)? {
        match l {
            CValue::Str(s) if !s.is_empty() && s.len() <= MAX_SHORT_BYTES => labels.push(s.clone()),
            _ => return Err(parse_err(format!("{at}: every label must be a string of 1 to {MAX_SHORT_BYTES} bytes"))),
        }
    }
    let merged_at = get_short(o, "merged_at", &at)?.to_string();
    let merge_commit = get_str(o, "merge_commit", &at)?;
    if !is_commit(merge_commit) {
        return Err(parse_err(format!("{at}: merge_commit {} is not a git object ID", shown(merge_commit))));
    }
    Ok(Pr { number, title, labels, merged_at, merge_commit: merge_commit.to_string() })
}

/// Parses and checks the PR export against `--tag` and `--channel`.
pub fn parse_export(bytes: &[u8], tag: &str, channel: Channel) -> Result<Export, NotesError> {
    const L: &str = "prs.json";
    let version = check_tag(tag, channel).map_err(|e| parse_err(format!("--tag: {e}")))?;
    let o = json(bytes, L)?;
    let export_tag = get_short(&o, "tag", L)?;
    if export_tag != tag {
        return Err(parse_err(format!("{L}: export is for tag {}, not {}", shown(export_tag), shown(tag))));
    }
    let export_channel = get_short(&o, "channel", L)?;
    if export_channel != channel.name() {
        return Err(parse_err(format!("{L}: export is for channel {}, not {}", shown(export_channel), channel.name())));
    }
    let previous_tag = match o.get("previous_tag") {
        Some(CValue::Null) => None,
        Some(CValue::Str(p)) => {
            let prev = check_tag(p, channel).map_err(|e| parse_err(format!("{L}: previous_tag: {e}")))?;
            if prev.precedence(&version) != std::cmp::Ordering::Less {
                return Err(parse_err(format!("{L}: previous_tag {} is not lower than {}", shown(p), shown(tag))));
            }
            Some(p.clone())
        }
        Some(_) => return Err(parse_err(format!("{L}: `previous_tag` must be a string or null"))),
        None => return Err(parse_err(format!("{L}: missing `previous_tag` (null for a channel's first release)"))),
    };
    let commit = get_str(&o, "commit", L)?;
    if !is_commit(commit) {
        return Err(parse_err(format!("{L}: commit {} is not a git object ID", shown(commit))));
    }
    let items = get_arr(&o, "prs", L, MAX_PRS)?;
    let mut prs = Vec::with_capacity(items.len());
    let mut seen = BTreeSet::new();
    for (i, v) in items.iter().enumerate() {
        let pr = parse_pr(v, i)?;
        if !seen.insert(pr.number) {
            return Err(parse_err(format!("{L}: PR #{} is listed twice", pr.number)));
        }
        prs.push(pr);
    }
    Ok(Export { tag: tag.to_string(), version, channel, previous_tag, commit: commit.to_string(), prs })
}

/// Index into [`GROUPS`] of the first of `labels` in group order, or `GROUPS.len()` for Other.
pub fn group_of(labels: &[String]) -> usize {
    GROUPS.iter().position(|(name, _)| labels.iter().any(|l| l.eq_ignore_ascii_case(name))).unwrap_or(GROUPS.len())
}

/// Whether a character could break the line or reorder how it displays.
fn is_unsafe_char(c: char) -> bool {
    c.is_control()
        || matches!(
            c,
            '\u{200E}' | '\u{200F}' | '\u{2028}' | '\u{2029}' | '\u{202A}'..='\u{202E}' | '\u{2066}'..='\u{2069}' | '\u{FEFF}'
        )
}

/// Untrusted text as one line of inert Markdown (REQ-ECO.REL.PROC.NOTES-005): unsafe characters
/// become spaces, the result is trimmed, cut to [`MAX_TITLE_CHARS`] characters with
/// [`TRUNCATED`] appended, and every ASCII punctuation character is backslash-escaped.
pub fn escape_title(raw: &str) -> String {
    let clean: String = raw.chars().map(|c| if is_unsafe_char(c) { ' ' } else { c }).collect();
    let clean = clean.trim();
    if clean.is_empty() {
        return "(no title)".to_string();
    }
    let mut out = String::with_capacity(clean.len().min(4 * MAX_TITLE_CHARS) + 16);
    for (count, c) in clean.chars().enumerate() {
        if count == MAX_TITLE_CHARS {
            out.push_str(TRUNCATED);
            return out;
        }
        if c.is_ascii_punctuation() {
            out.push('\\');
        }
        out.push(c);
    }
    out
}

/// Checks that `rel` under `dir` is a regular file and hashes it. `Ok(None)` when absent.
fn hash_report(dir: &Path, rel: &str) -> Result<Option<Digest>, NotesError> {
    let path = dir.join(rel);
    match std::fs::symlink_metadata(&path) {
        Ok(m) if m.is_file() => {}
        Ok(_) => return Err(parse_err(format!("{rel}: not a regular file"))),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(None),
        Err(e) => return Err(parse_err(format!("cannot read {}: {e}", path.display()))),
    }
    hash_file(&path).map(|(d, _)| Some(d)).map_err(|e| parse_err(e.to_string()))
}

/// Parses `release-gates.json`: `{release, channel, verdict, gates: [{id, notes?, ...}], ...}`.
/// The Tier 2 build failures are the `notes` of gate [`PKG_GATE`].
pub fn parse_gates(bytes: &[u8], tag: &str, channel: Channel) -> Result<Gates, NotesError> {
    const L: &str = GATES_FILE;
    let o = json(bytes, L)?;
    let release = get_short(&o, "release", L)?;
    if release != tag {
        return Err(parse_err(format!("{L}: verdict is for release {}, not {}", shown(release), shown(tag))));
    }
    let ch = get_short(&o, "channel", L)?;
    if ch != channel.name() {
        return Err(parse_err(format!("{L}: verdict is for channel {}, not {}", shown(ch), channel.name())));
    }
    let verdict = get_short(&o, "verdict", L)?;
    if verdict != "pass" && verdict != "block" {
        return Err(parse_err(format!("{L}: verdict {} must be pass or block", shown(verdict))));
    }
    let mut ids = BTreeSet::new();
    let mut tier2_failures = Vec::new();
    for (i, g) in get_arr(&o, "gates", L, MAX_ITEMS)?.iter().enumerate() {
        let at = format!("{L}: gates[{i}]");
        let CValue::Obj(g) = g else { return Err(parse_err(format!("{at}: not an object"))) };
        let id = get_short(g, "id", &at)?;
        if !ids.insert(id.to_ascii_lowercase()) {
            return Err(parse_err(format!("{L}: gate {} is listed twice", shown(id))));
        }
        if id != PKG_GATE || !g.contains_key("notes") {
            continue;
        }
        for n in get_arr(g, "notes", &at, MAX_ITEMS)? {
            match n {
                CValue::Str(s) => tier2_failures.push(s.clone()),
                _ => return Err(parse_err(format!("{at}: every note must be a string"))),
            }
        }
    }
    Ok(Gates { verdict: verdict.to_string(), tier2_failures })
}

/// Parses `threat/register-summary.json` and returns the number of `high` entries.
pub fn parse_threat_summary(bytes: &[u8]) -> Result<u64, NotesError> {
    const L: &str = THREAT_FILE;
    let o = json(bytes, L)?;
    let schema = get_short(&o, "schema", L)?;
    if schema != THREAT_SCHEMA {
        return Err(parse_err(format!("{L}: schema {} is not {THREAT_SCHEMA}", shown(schema))));
    }
    let Some(CValue::Obj(counts)) = o.get("counts") else {
        return Err(parse_err(format!("{L}: `counts` must be an object")));
    };
    let high = counts
        .get("high")
        .and_then(|v| as_int(v, MAX_PR_NUMBER))
        .ok_or_else(|| parse_err(format!("{L}: `counts.high` must be a non-negative integer")))?;
    if o.contains_key("high_ids") {
        let ids = get_arr(&o, "high_ids", L, MAX_PRS)?;
        if ids.len() as u64 != high {
            return Err(parse_err(format!("{L}: `counts.high` is {high} but `high_ids` lists {}", ids.len())));
        }
    }
    Ok(high)
}

/// Reads the reports directory. Every missing report is named at once, in a fixed order
/// (attachments in table order, then the evidence statement, then the threat summary).
pub fn read_reports(dir: &Path, tag: &str, channel: Channel) -> Result<Reports, Vec<NotesError>> {
    let mut missing = Vec::new();
    let mut attachments = Vec::new();
    for name in ATTACHMENTS {
        match hash_report(dir, name).map_err(|e| vec![e])? {
            Some(d) => attachments.push((name, d)),
            None => missing.push(NotesError::Missing(name.to_string())),
        }
    }
    let evidence = hash_report(dir, EVIDENCE_FILE).map_err(|e| vec![e])?;
    if evidence.is_none() {
        missing.push(NotesError::Missing(EVIDENCE_FILE.to_string()));
    }
    let threat = read_bounded(&dir.join(THREAT_FILE), MAX_JSON_BYTES).map_err(|e| vec![e])?;
    if threat.is_none() {
        missing.push(NotesError::Missing(THREAT_FILE.to_string()));
    }
    let (Some(evidence), Some(threat)) = (evidence, threat) else { return Err(missing) };
    if !missing.is_empty() {
        return Err(missing);
    }
    let gates_bytes = read_bounded(&dir.join(GATES_FILE), MAX_JSON_BYTES)
        .map_err(|e| vec![e])?
        .ok_or_else(|| vec![NotesError::Missing(GATES_FILE.to_string())])?;
    let gates = parse_gates(&gates_bytes, tag, channel).map_err(|e| vec![e])?;
    let high_threats = parse_threat_summary(&threat).map_err(|e| vec![e])?;
    Ok(Reports { attachments, gates, evidence, high_threats })
}

/// Renders `release-notes.md` (LF line endings).
pub fn render(export: &Export, reports: &Reports) -> String {
    let mut s = String::new();
    let mut line = |l: &str| {
        s.push_str(l);
        s.push('\n');
    };
    line(HEADER);
    line("");
    line(&format!("# Release {}", export.tag));
    line("");
    line(&format!("- Version: {}", export.version));
    line(&format!("- Channel: {}", export.channel.name()));
    line(&format!("- Commit: {}", export.commit));
    line(&format!("- Previous release on this channel: {}", export.previous_tag.as_deref().unwrap_or("none")));
    line(&format!("- Pull requests: {}", export.prs.len()));
    line("");
    line("## Changes");
    line("");
    let mut groups: Vec<Vec<&Pr>> = vec![Vec::new(); GROUPS.len() + 1];
    for pr in &export.prs {
        if let Some(g) = groups.get_mut(group_of(&pr.labels)) {
            g.push(pr);
        }
    }
    if export.prs.is_empty() {
        line("None.");
        line("");
    }
    for (i, prs) in groups.iter_mut().enumerate() {
        if prs.is_empty() {
            continue;
        }
        prs.sort_by_key(|p| p.number);
        line(&format!("### {}", GROUPS.get(i).map_or(OTHER, |g| g.1)));
        line("");
        for pr in prs.iter() {
            line(&format!("- #{} {}", pr.number, escape_title(&pr.title)));
        }
        line("");
    }
    line("## Attachments");
    line("");
    line("| File | SHA-256 |");
    line("| --- | --- |");
    for (name, digest) in &reports.attachments {
        line(&format!("| [{name}]({name}) | `{digest}` |"));
    }
    line("");
    line("## Release gates");
    line("");
    line(&format!("- Verdict: {}", reports.gates.verdict));
    line("");
    line("## Tier 2 build failures");
    line("");
    if reports.gates.tier2_failures.is_empty() {
        line("None.");
    }
    for f in &reports.gates.tier2_failures {
        line(&format!("- {}", escape_title(f)));
    }
    line("");
    line("## Evidence and threats");
    line("");
    line(&format!("- Evidence-bundle statement: `{}`", reports.evidence));
    line(&format!("- High residual-risk threats: {}", reports.high_threats));
    s
}

/// `rel notes`: reads the export and the reports, then writes `<out>/release-notes.md` (the
/// directory is created if absent). Returns the rendered text.
pub fn run(tag: &str, channel: Channel, prs: &Path, reports: &Path, out: &Path) -> Result<String, Vec<NotesError>> {
    let bytes = read_bounded(prs, MAX_JSON_BYTES)
        .map_err(|e| vec![e])?
        .ok_or_else(|| vec![parse_err(format!("{} does not exist", prs.display()))])?;
    let export = parse_export(&bytes, tag, channel).map_err(|e| vec![e])?;
    let reports = read_reports(reports, tag, channel)?;
    let text = render(&export, &reports);
    let io = |p: &Path, e: std::io::Error| vec![NotesError::Io(format!("{}: {e}", p.display()))];
    std::fs::create_dir_all(out).map_err(|e| io(out, e))?;
    let (tmp, dest) = (out.join(".release-notes.md.tmp"), out.join(NOTES_FILE));
    if let Err(e) = std::fs::write(&tmp, text.as_bytes()) {
        let _ = std::fs::remove_file(&tmp);
        return Err(io(&tmp, e));
    }
    if let Err(e) = std::fs::rename(&tmp, &dest) {
        let _ = std::fs::remove_file(&tmp);
        return Err(io(&dest, e));
    }
    Ok(text)
}

/// The `rel notes` command line. Exit 0: written; 1: a report is missing; 2: bad usage, an
/// unreadable input or a write failure.
pub fn cli(args: &[String]) -> ExitCode {
    let (mut tag, mut channel, mut prs, mut reports, mut out) = (None, None, None, None, None);
    let mut it = args.iter();
    while let Some(a) = it.next() {
        match (a.as_str(), it.next()) {
            ("--tag", Some(v)) => tag = Some(v.as_str()),
            ("--channel", Some(v)) => match Channel::parse(v) {
                Some(c) => channel = Some(c),
                None => {
                    eprintln!("rel notes: unknown channel {}\n{USAGE}", shown(v));
                    return ExitCode::from(2);
                }
            },
            ("--prs", Some(v)) => prs = Some(Path::new(v)),
            ("--reports", Some(v)) => reports = Some(Path::new(v)),
            ("--out", Some(v)) => out = Some(Path::new(v)),
            _ => {
                eprintln!("{USAGE}");
                return ExitCode::from(2);
            }
        }
    }
    let (Some(tag), Some(channel), Some(prs), Some(reports), Some(out)) = (tag, channel, prs, reports, out) else {
        eprintln!("rel notes: --tag, --channel, --prs, --reports and --out are required\n{USAGE}");
        return ExitCode::from(2);
    };
    match run(tag, channel, prs, reports, out) {
        Ok(_) => {
            println!("notes: ok {}", out.join(NOTES_FILE).display());
            ExitCode::SUCCESS
        }
        Err(errors) => {
            for e in &errors {
                println!("{e}");
            }
            ExitCode::from(errors.iter().map(NotesError::exit_code).max().unwrap_or(2))
        }
    }
}
