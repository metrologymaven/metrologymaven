//! `cargo xtask rel runbook-check` and `cargo xtask rel runbook-render`: the release runbook
//! and its consistency check (spec node `ECO.REL.PROC.RUNBOOK`).
//!
//! A release directory holds `runbook.toml` (the ordered `[[step]]` list), `gates.toml` (the
//! `[[gate]]` list owned by `ECO.REL.PROC.GATES`; only each gate's `id` is read here),
//! `RUNBOOK.preamble.md` (hand written) and `RUNBOOK.md` (rendered from the other two). The
//! release workflow is read only for its job IDs; until `ECO.REL.PROC.FLOW` provides the
//! real workflow, the default is the skeleton `<dir>/release-workflow.yml`.
//!
//! The check reads files and nothing else: no network, no git, no clock, and it never
//! creates tags, releases or signatures (R0). Rendering is a pure function of the TOML and
//! the preamble (D0), with LF line endings on every OS. The rendering rules are written out
//! in `fixtures/rel/runbook/make_fixtures.py`, an independent Python reference.

use fid_canon::{to_canonical_bytes, CValue};
use std::collections::{BTreeMap, BTreeSet};
use std::fmt;
use std::io::Read;
use std::path::{Path, PathBuf};
use toml::{Table, Value};

/// Largest file read (runbook, gates, preamble, RUNBOOK.md, workflow).
pub const MAX_FILE_BYTES: u64 = 1 << 20;
/// Most steps, gates or workflow jobs accepted.
pub const MAX_ITEMS: usize = 1024;
/// Longest ID (step, gate, job or role name).
pub const MAX_ID_BYTES: usize = 64;
/// The one step a person performs.
pub const SIGN_APPROVAL: &str = "sign-approval";
/// The release channels a step may apply to.
pub const CHANNELS: [&str; 4] = ["nightly", "beta", "stable", "lts"];
/// Default workflow file name inside the release directory.
pub const DEFAULT_WORKFLOW: &str = "release-workflow.yml";

/// First line of `RUNBOOK.md`.
pub const HEADER: &str = "<!-- Generated by `cargo xtask rel runbook-render` from runbook.toml and \
                          RUNBOOK.preamble.md. Do not edit this file: edit those two and render again. -->\n";

/// Who performs a step.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Performer {
    Ci,
    Role(String),
}

impl fmt::Display for Performer {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Performer::Ci => f.write_str("ci"),
            Performer::Role(r) => write!(f, "role:{r}"),
        }
    }
}

/// Whether the tool that performs a step exists today.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Status {
    Available,
    Planned,
}

impl Status {
    pub fn name(self) -> &'static str {
        match self {
            Status::Available => "available",
            Status::Planned => "planned",
        }
    }
}

/// One `[[step]]` of `runbook.toml`.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Step {
    pub id: String,
    pub title: String,
    pub performer: Performer,
    pub job: Option<String>,
    pub gates: Vec<String>,
    pub channels: Vec<String>,
    pub status: Status,
    pub tool: Option<String>,
    pub notes: Option<String>,
}

/// Finding codes. All exit 1 except `Parse` (exit 2).
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum Code {
    HumanStep,
    UnknownJob,
    OrphanJob,
    UnknownGate,
    UnusedGate,
    Drift,
    Parse,
}

impl Code {
    pub fn name(self) -> &'static str {
        match self {
            Code::HumanStep => "RUNBOOK-HUMAN-STEP",
            Code::UnknownJob => "RUNBOOK-UNKNOWN-JOB",
            Code::OrphanJob => "RUNBOOK-ORPHAN-JOB",
            Code::UnknownGate => "RUNBOOK-UNKNOWN-GATE",
            Code::UnusedGate => "RUNBOOK-UNUSED-GATE",
            Code::Drift => "RUNBOOK-DRIFT",
            Code::Parse => "RUNBOOK-PARSE",
        }
    }

    pub fn exit_code(self) -> u8 {
        match self {
            Code::Parse => 2,
            _ => 1,
        }
    }
}

/// A failed check: `<CODE> <subject>: <message>`. The subject is the step, job, gate or
/// file the finding is about.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Finding {
    pub code: Code,
    pub subject: String,
    pub message: String,
}

impl Finding {
    fn new(code: Code, subject: &str, message: impl Into<String>) -> Finding {
        Finding { code, subject: subject.to_string(), message: message.into() }
    }

    fn parse(file: &str, message: impl Into<String>) -> Finding {
        Finding::new(Code::Parse, file, message)
    }
}

impl fmt::Display for Finding {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{} {}: {}", self.code.name(), self.subject, self.message)
    }
}

/// The exit code for a list of findings (the highest of them; 0 when empty).
pub fn exit_code(findings: &[Finding]) -> u8 {
    findings.iter().map(|f| f.code.exit_code()).max().unwrap_or(0)
}

/// Reads a UTF-8 file of at most [`MAX_FILE_BYTES`]; `Ok(None)` when it does not exist.
fn read_text(path: &Path, label: &str) -> Result<Option<String>, Finding> {
    let file = match std::fs::File::open(path) {
        Ok(f) => f,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(None),
        Err(e) => return Err(Finding::parse(label, format!("cannot read {}: {e}", path.display()))),
    };
    let mut bytes = Vec::new();
    file.take(MAX_FILE_BYTES + 1)
        .read_to_end(&mut bytes)
        .map_err(|e| Finding::parse(label, format!("cannot read {}: {e}", path.display())))?;
    if bytes.len() as u64 > MAX_FILE_BYTES {
        return Err(Finding::parse(label, format!("larger than {MAX_FILE_BYTES} bytes")));
    }
    String::from_utf8(bytes).map(Some).map_err(|_| Finding::parse(label, "not UTF-8"))
}

fn read_required(path: &Path, label: &str) -> Result<String, Finding> {
    read_text(path, label)?.ok_or_else(|| Finding::parse(label, format!("{} does not exist", path.display())))
}

/// Step, gate and role IDs: lowercase ASCII letters, digits and `-`.
fn is_id(s: &str) -> bool {
    !s.is_empty()
        && s.len() <= MAX_ID_BYTES
        && s.bytes().all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
}

/// Workflow job IDs (GitHub Actions rule): ASCII letters, digits, `_` and `-`.
fn is_job_id(s: &str) -> bool {
    !s.is_empty() && s.len() <= MAX_ID_BYTES && s.bytes().all(|b| b.is_ascii_alphanumeric() || b == b'_' || b == b'-')
}

fn shown(s: &str) -> String {
    let mut end = s.len().min(MAX_ID_BYTES);
    while !s.is_char_boundary(end) {
        end -= 1;
    }
    let cut = s.get(..end).unwrap_or("");
    if cut.len() < s.len() {
        format!("{cut:?}...")
    } else {
        format!("{cut:?}")
    }
}

fn parse_table(text: &str, label: &str) -> Result<Table, Finding> {
    text.parse::<Table>().map_err(|e| Finding::parse(label, e.message().trim_end().replace('\n', " ")))
}

/// The array of tables `key` of a document; other top-level keys are refused.
fn array_of_tables<'a>(doc: &'a Table, key: &str, label: &str) -> Result<Vec<&'a Table>, Finding> {
    if let Some(other) = doc.keys().find(|k| k.as_str() != key) {
        return Err(Finding::parse(label, format!("unknown top-level key {}", shown(other))));
    }
    let Some(v) = doc.get(key) else { return Ok(Vec::new()) };
    let Some(items) = v.as_array() else {
        return Err(Finding::parse(label, format!("`{key}` must be an array of tables ([[{key}]])")));
    };
    if items.len() > MAX_ITEMS {
        return Err(Finding::parse(label, format!("more than {MAX_ITEMS} [[{key}]] entries")));
    }
    items
        .iter()
        .enumerate()
        .map(|(i, v)| v.as_table().ok_or_else(|| Finding::parse(label, format!("[[{key}]] #{} is not a table", i + 1))))
        .collect()
}

fn get_str<'a>(t: &'a Table, key: &str, label: &str, at: &str) -> Result<Option<&'a str>, Finding> {
    match t.get(key) {
        None => Ok(None),
        Some(Value::String(s)) => Ok(Some(s.as_str())),
        Some(_) => Err(Finding::parse(label, format!("{at}: `{key}` must be a string"))),
    }
}

fn get_list(t: &Table, key: &str, label: &str, at: &str) -> Result<Vec<String>, Finding> {
    match t.get(key) {
        None => Ok(Vec::new()),
        Some(Value::Array(a)) if a.len() <= MAX_ITEMS => a
            .iter()
            .map(|v| v.as_str().map(String::from))
            .collect::<Option<Vec<_>>>()
            .ok_or_else(|| Finding::parse(label, format!("{at}: `{key}` must list strings"))),
        Some(_) => Err(Finding::parse(label, format!("{at}: `{key}` must be an array of strings"))),
    }
}

const STEP_KEYS: [&str; 9] = ["id", "title", "performer", "job", "gates", "channels", "status", "tool", "notes"];

fn parse_step(t: &Table, index: usize) -> Result<Step, Finding> {
    const L: &str = "runbook.toml";
    let at0 = format!("[[step]] #{index}");
    if let Some(k) = t.keys().find(|k| !STEP_KEYS.contains(&k.as_str())) {
        return Err(Finding::parse(L, format!("{at0}: unknown key {}", shown(k))));
    }
    let id = get_str(t, "id", L, &at0)?.ok_or_else(|| Finding::parse(L, format!("{at0}: missing `id`")))?;
    if !is_id(id) {
        return Err(Finding::parse(L, format!("{at0}: id {} must be lowercase letters, digits and -", shown(id))));
    }
    let at = format!("step {id}");
    let title = get_str(t, "title", L, &at)?.ok_or_else(|| Finding::parse(L, format!("{at}: missing `title`")))?;
    if title.trim().is_empty() || title.contains(['\n', '\r', '|']) {
        return Err(Finding::parse(L, format!("{at}: `title` must be one non-empty line without `|`")));
    }
    let performer = match get_str(t, "performer", L, &at)? {
        Some("ci") => Performer::Ci,
        Some(p) => match p.strip_prefix("role:") {
            Some(r) if is_id(r) => Performer::Role(r.to_string()),
            _ => {
                return Err(Finding::parse(L, format!("{at}: performer {} must be `ci` or `role:<name>`", shown(p))));
            }
        },
        None => return Err(Finding::parse(L, format!("{at}: missing `performer`"))),
    };
    let job = get_str(t, "job", L, &at)?.map(String::from);
    if let Some(j) = &job {
        if !is_job_id(j) {
            return Err(Finding::parse(L, format!("{at}: job {} is not a workflow job ID", shown(j))));
        }
    } else if performer == Performer::Ci {
        return Err(Finding::parse(L, format!("{at}: a `ci` step must name its workflow `job`")));
    }
    let gates = get_list(t, "gates", L, &at)?;
    let mut seen = BTreeSet::new();
    for g in &gates {
        if !is_id(g) {
            return Err(Finding::parse(L, format!("{at}: gate {} must be lowercase letters, digits and -", shown(g))));
        }
        if !seen.insert(g.as_str()) {
            return Err(Finding::parse(L, format!("{at}: gate {g} is listed twice")));
        }
    }
    if !t.contains_key("channels") {
        return Err(Finding::parse(L, format!("{at}: missing `channels`")));
    }
    let channels = get_list(t, "channels", L, &at)?;
    if channels.is_empty() {
        return Err(Finding::parse(L, format!("{at}: `channels` is empty")));
    }
    let mut seen = BTreeSet::new();
    for c in &channels {
        if !CHANNELS.contains(&c.as_str()) {
            return Err(Finding::parse(L, format!("{at}: channel {} is not nightly, beta, stable or lts", shown(c))));
        }
        if !seen.insert(c.as_str()) {
            return Err(Finding::parse(L, format!("{at}: channel {c} is listed twice")));
        }
    }
    let status = match get_str(t, "status", L, &at)? {
        Some("available") => Status::Available,
        Some("planned") => Status::Planned,
        Some(s) => return Err(Finding::parse(L, format!("{at}: status {} must be available or planned", shown(s)))),
        None => return Err(Finding::parse(L, format!("{at}: missing `status`"))),
    };
    let tool = get_str(t, "tool", L, &at)?.map(String::from);
    if let Some(tool) = &tool {
        if tool.trim().is_empty() || tool.contains(['\n', '\r', '`', '|']) {
            return Err(Finding::parse(L, format!("{at}: `tool` must be one non-empty line without ` or |")));
        }
    }
    let notes = get_str(t, "notes", L, &at)?.map(String::from);
    Ok(Step { id: id.to_string(), title: title.to_string(), performer, job, gates, channels, status, tool, notes })
}

/// Parses `runbook.toml`. Step IDs must be unique.
pub fn parse_runbook(text: &str) -> Result<Vec<Step>, Finding> {
    let doc = parse_table(text, "runbook.toml")?;
    let tables = array_of_tables(&doc, "step", "runbook.toml")?;
    let mut steps = Vec::with_capacity(tables.len());
    let mut ids = BTreeSet::new();
    for (i, t) in tables.into_iter().enumerate() {
        let step = parse_step(t, i + 1)?;
        if !ids.insert(step.id.clone()) {
            return Err(Finding::parse("runbook.toml", format!("step id {} is used twice", step.id)));
        }
        steps.push(step);
    }
    if steps.is_empty() {
        return Err(Finding::parse("runbook.toml", "no [[step]] entries"));
    }
    Ok(steps)
}

/// The gate IDs of `gates.toml`, in file order. Only `id` is read; the other fields belong
/// to `ECO.REL.PROC.GATES`.
pub fn parse_gate_ids(text: &str) -> Result<Vec<String>, Finding> {
    const L: &str = "gates.toml";
    let doc = parse_table(text, L)?;
    let mut ids = Vec::new();
    let mut seen = BTreeSet::new();
    for (i, t) in array_of_tables(&doc, "gate", L)?.into_iter().enumerate() {
        let at = format!("[[gate]] #{}", i + 1);
        let id = get_str(t, "id", L, &at)?.ok_or_else(|| Finding::parse(L, format!("{at}: missing `id`")))?;
        if !is_id(id) {
            return Err(Finding::parse(L, format!("{at}: id {} must be lowercase letters, digits and -", shown(id))));
        }
        if !seen.insert(id.to_string()) {
            return Err(Finding::parse(L, format!("gate id {id} is used twice")));
        }
        ids.push(id.to_string());
    }
    Ok(ids)
}

/// Strips a trailing `# comment` and trailing spaces from a YAML line (no `#` inside quotes
/// is expected on the lines this parser reads: the `jobs:` line and job keys).
fn strip_comment(line: &str) -> &str {
    let mut prev_space = true;
    for (i, c) in line.char_indices() {
        if c == '#' && prev_space {
            return line.get(..i).unwrap_or("").trim_end();
        }
        prev_space = c == ' ' || c == '\t';
    }
    line.trim_end()
}

/// The job IDs of a workflow YAML file, in file order. Only the block mapping under the
/// top-level `jobs:` key is read: its keys at the first indentation level found. Anything
/// this bounded reader does not understand there (tabs, flow style, odd indentation, keys
/// that are not job IDs) is a parse error rather than a guess.
pub fn parse_workflow_jobs(text: &str, label: &str) -> Result<Vec<String>, Finding> {
    let mut lines = text.lines().enumerate();
    let mut found = false;
    for (_, line) in lines.by_ref() {
        if !line.starts_with([' ', '\t', '#']) && strip_comment(line).trim_start_matches('\u{feff}') == "jobs:" {
            found = true;
            break;
        }
    }
    if !found {
        return Err(Finding::parse(label, "no top-level block mapping `jobs:`"));
    }
    let mut jobs = Vec::new();
    let mut seen = BTreeSet::new();
    let mut indent: Option<usize> = None;
    for (n, line) in lines {
        let lineno = n + 1;
        let body = line.trim_start_matches(' ');
        if body.is_empty() || body.starts_with('#') || body.trim().is_empty() {
            continue;
        }
        let depth = line.len() - body.len();
        if body.starts_with('\t') {
            return Err(Finding::parse(label, format!("line {lineno}: tab in indentation")));
        }
        if depth == 0 {
            break; // the next top-level key
        }
        let level = *indent.get_or_insert(depth);
        if depth > level {
            continue; // inside a job
        }
        if depth < level {
            return Err(Finding::parse(label, format!("line {lineno}: unexpected indentation under `jobs:`")));
        }
        let content = strip_comment(body);
        let Some((key, rest)) = content.split_once(':') else {
            return Err(Finding::parse(label, format!("line {lineno}: expected `<job-id>:`")));
        };
        if !(rest.is_empty() || rest.starts_with(' ')) {
            return Err(Finding::parse(label, format!("line {lineno}: expected `<job-id>:`")));
        }
        let key = key
            .strip_prefix('"')
            .and_then(|k| k.strip_suffix('"'))
            .or_else(|| key.strip_prefix('\'').and_then(|k| k.strip_suffix('\'')))
            .unwrap_or(key);
        if !is_job_id(key) {
            return Err(Finding::parse(label, format!("line {lineno}: {} is not a job ID", shown(key))));
        }
        if !seen.insert(key.to_string()) {
            return Err(Finding::parse(label, format!("line {lineno}: job {key} is defined twice")));
        }
        if jobs.len() == MAX_ITEMS {
            return Err(Finding::parse(label, format!("more than {MAX_ITEMS} jobs")));
        }
        jobs.push(key.to_string());
    }
    Ok(jobs)
}

const WS: [char; 4] = [' ', '\t', '\r', '\n'];

/// Renders `RUNBOOK.md` from the steps and the preamble. LF line endings on every OS.
pub fn render(steps: &[Step], preamble: &str) -> String {
    let mut out = String::new();
    out.push_str(HEADER);
    out.push('\n');
    let pre = preamble.replace("\r\n", "\n");
    let pre = pre.trim_end_matches(WS);
    if !pre.is_empty() {
        out.push_str(pre);
        out.push_str("\n\n");
    }
    let job = |s: &Step| s.job.as_ref().map_or_else(|| "-".to_string(), |j| format!("`{j}`"));
    let gates = |s: &Step| {
        if s.gates.is_empty() {
            "-".to_string()
        } else {
            s.gates.iter().map(|g| format!("`{g}`")).collect::<Vec<_>>().join(", ")
        }
    };
    let chans = |s: &Step| s.channels.join(", ");
    out.push_str("## Steps\n\n");
    out.push_str("| # | Step | Title | Performer | Job | Gates | Channels | Status |\n");
    out.push_str("|---|---|---|---|---|---|---|---|\n");
    for (i, s) in steps.iter().enumerate() {
        out.push_str(&format!(
            "| {} | `{}` | {} | `{}` | {} | {} | {} | {} |\n",
            i + 1,
            s.id,
            s.title,
            s.performer,
            job(s),
            gates(s),
            chans(s),
            s.status.name()
        ));
    }
    out.push_str("\n## Step details\n");
    for (i, s) in steps.iter().enumerate() {
        out.push_str(&format!("\n### {}. `{}`: {}\n\n", i + 1, s.id, s.title));
        out.push_str(&format!("- Performer: `{}`\n", s.performer));
        out.push_str(&format!("- Workflow job: {}\n", job(s)));
        out.push_str(&format!("- Gates: {}\n", gates(s)));
        out.push_str(&format!("- Channels: {}\n", chans(s)));
        out.push_str(&format!("- Status: {}\n", s.status.name()));
        if let Some(tool) = &s.tool {
            out.push_str(&format!("- Tool: `{tool}`\n"));
        }
        if let Some(notes) = &s.notes {
            let notes = notes.replace("\r\n", "\n");
            let notes = notes.trim_matches(WS);
            if !notes.is_empty() {
                out.push('\n');
                out.push_str(notes);
                out.push('\n');
            }
        }
    }
    out
}

/// Reads `<dir>/runbook.toml` and `<dir>/RUNBOOK.preamble.md` and renders `RUNBOOK.md`.
pub fn render_dir(dir: &Path) -> Result<(Vec<Step>, String), Finding> {
    let steps = parse_runbook(&read_required(&dir.join("runbook.toml"), "runbook.toml")?)?;
    let preamble = read_required(&dir.join("RUNBOOK.preamble.md"), "RUNBOOK.preamble.md")?;
    let text = render(&steps, &preamble);
    Ok((steps, text))
}

/// The consistency checks over parsed inputs, in a fixed order: people, jobs, gates.
pub fn check_consistency(steps: &[Step], jobs: &[String], gate_ids: &[String]) -> Vec<Finding> {
    let mut findings = Vec::new();
    // REQ-002: exactly one step is performed by a person, and it is sign-approval.
    for s in steps {
        if let Performer::Role(role) = &s.performer {
            if s.id != SIGN_APPROVAL {
                let msg = format!("performed by role:{role}; only {SIGN_APPROVAL} may be performed by a person");
                findings.push(Finding::new(Code::HumanStep, &s.id, msg));
            }
        }
    }
    let approval = steps.iter().find(|s| s.id == SIGN_APPROVAL);
    match approval.map(|s| &s.performer) {
        Some(Performer::Role(_)) => {}
        Some(Performer::Ci) => findings.push(Finding::new(
            Code::HumanStep,
            SIGN_APPROVAL,
            "must be performed by a person (`role:<name>`), not ci",
        )),
        None => findings.push(Finding::new(Code::HumanStep, SIGN_APPROVAL, "the runbook has no sign-approval step")),
    }
    // REQ-003: every named job exists, every job is named.
    let job_set: BTreeSet<&str> = jobs.iter().map(String::as_str).collect();
    let mut named = BTreeSet::new();
    for s in steps {
        if let Some(j) = &s.job {
            if !job_set.contains(j.as_str()) && named.insert(j.as_str()) {
                let msg = format!("named by step {} but not a job of the release workflow", s.id);
                findings.push(Finding::new(Code::UnknownJob, j, msg));
            }
            named.insert(j.as_str());
        }
    }
    for j in jobs {
        if !named.contains(j.as_str()) {
            findings.push(Finding::new(Code::OrphanJob, j, "release workflow job named by no step"));
        }
    }
    // REQ-004: every listed gate is defined, every defined gate is listed.
    let gate_set: BTreeSet<&str> = gate_ids.iter().map(String::as_str).collect();
    let mut listed: BTreeMap<&str, &str> = BTreeMap::new();
    for s in steps {
        for g in &s.gates {
            if !gate_set.contains(g.as_str()) && !listed.contains_key(g.as_str()) {
                let msg = format!("listed by step {} but not defined in gates.toml", s.id);
                findings.push(Finding::new(Code::UnknownGate, g, msg));
            }
            listed.entry(g.as_str()).or_insert(s.id.as_str());
        }
    }
    for g in gate_ids {
        if !listed.contains_key(g.as_str()) {
            findings.push(Finding::new(Code::UnusedGate, g, "defined in gates.toml but listed by no step"));
        }
    }
    findings
}

struct Loaded {
    steps: Vec<Step>,
    rendered: String,
    gate_ids: Vec<String>,
    jobs: Vec<String>,
    current: Option<String>,
}

fn load(dir: &Path, wf_path: &Path) -> Result<Loaded, Finding> {
    let wf_label = wf_path.file_name().and_then(|n| n.to_str()).unwrap_or("workflow").to_string();
    let (steps, rendered) = render_dir(dir)?;
    let gate_ids = parse_gate_ids(&read_required(&dir.join("gates.toml"), "gates.toml")?)?;
    let jobs = parse_workflow_jobs(&read_required(wf_path, &wf_label)?, &wf_label)?;
    let current = read_text(&dir.join("RUNBOOK.md"), "RUNBOOK.md")?;
    Ok(Loaded { steps, rendered, gate_ids, jobs, current })
}

/// The full check of a release directory. Returns the number of steps, or the findings
/// (a parse error stops the check and is the only finding).
pub fn check(dir: &Path, workflow: Option<&Path>) -> Result<usize, Vec<Finding>> {
    let wf_path: PathBuf = workflow.map_or_else(|| dir.join(DEFAULT_WORKFLOW), Path::to_path_buf);
    let Loaded { steps, rendered, gate_ids, jobs, current } = load(dir, &wf_path).map_err(|f| vec![f])?;
    let mut findings = check_consistency(&steps, &jobs, &gate_ids);
    // REQ-006: RUNBOOK.md is exactly the rendering (CRLF from a checkout is tolerated).
    match current.map(|t| t.replace("\r\n", "\n")) {
        None => findings.push(Finding::new(Code::Drift, "RUNBOOK.md", "missing; run `cargo xtask rel runbook-render`")),
        Some(text) if text != rendered => {
            let line = text
                .lines()
                .zip(rendered.lines())
                .position(|(a, b)| a != b)
                .unwrap_or_else(|| text.lines().count().min(rendered.lines().count()))
                + 1;
            findings.push(Finding::new(
                Code::Drift,
                "RUNBOOK.md",
                format!(
                    "differs from the rendering of runbook.toml and RUNBOOK.preamble.md (first at line {line}); \
                     edit those and run `cargo xtask rel runbook-render --dir <dir> --out <dir>/RUNBOOK.md`"
                ),
            ));
        }
        Some(_) => {}
    }
    if findings.is_empty() {
        Ok(steps.len())
    } else {
        Err(findings)
    }
}

/// The `--json` report: `{"ok":true,"steps":<n>}`, or
/// `{"findings":[{"code","message","subject"}],"ok":false}` in canonical JSON (RFC 8785).
pub fn report_json(result: &Result<usize, Vec<Finding>>) -> String {
    match result {
        Ok(n) => format!("{{\"ok\":true,\"steps\":{n}}}"),
        Err(findings) => {
            let s = |x: &str| CValue::Str(x.to_string());
            let list = findings
                .iter()
                .map(|f| {
                    let mut m = BTreeMap::new();
                    m.insert("code".to_string(), s(f.code.name()));
                    m.insert("subject".to_string(), s(&f.subject));
                    m.insert("message".to_string(), s(&f.message));
                    CValue::Obj(m)
                })
                .collect();
            let mut o = BTreeMap::new();
            o.insert("ok".to_string(), CValue::Bool(false));
            o.insert("findings".to_string(), CValue::Arr(list));
            to_canonical_bytes(&CValue::Obj(o))
                .ok()
                .and_then(|b| String::from_utf8(b).ok())
                .unwrap_or_else(|| "{\"ok\":false}".to_string())
        }
    }
}

#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]
    use super::*;

    #[test]
    fn workflow_jobs_basic() {
        let y = "name: x\non:\n  push:\njobs:  # all jobs\n  a:\n    runs-on: x\n    steps:\n      - run: |\n\
                 \x20         echo jobs:\n\n  # comment\n  \"b-2\": {}\n  c_3:\npermissions:\n  d: read\n";
        assert_eq!(parse_workflow_jobs(y, "w").unwrap(), vec!["a", "b-2", "c_3"]);
    }

    #[test]
    fn workflow_jobs_errors() {
        assert!(parse_workflow_jobs("name: x\n", "w").is_err());
        assert!(parse_workflow_jobs("jobs: {a: {}}\n", "w").is_err());
        assert!(parse_workflow_jobs("jobs:\n    a:\n  b:\n", "w").is_err());
        assert!(parse_workflow_jobs("jobs:\n  a:\n  a:\n", "w").is_err());
        assert!(parse_workflow_jobs("jobs:\n  a b:\n", "w").is_err());
        assert!(parse_workflow_jobs("jobs:\n\ta:\n", "w").is_err());
        assert!(parse_workflow_jobs("jobs:\n  a:b\n", "w").is_err());
    }

    #[test]
    fn workflow_crlf_and_empty_jobs() {
        assert_eq!(parse_workflow_jobs("jobs:\r\n  a:\r\n    x: 1\r\n", "w").unwrap(), vec!["a"]);
        assert!(parse_workflow_jobs("jobs:\nother: 1\n", "w").unwrap().is_empty());
    }

    fn step(id: &str, performer: &str) -> String {
        format!("[[step]]\nid = \"{id}\"\ntitle = \"T\"\nperformer = \"{performer}\"\njob = \"{id}\"\nchannels = [\"beta\"]\nstatus = \"planned\"\n")
    }

    #[test]
    fn runbook_parse_errors() {
        let ok = step("a", "ci");
        assert!(parse_runbook(&ok).is_ok());
        for bad in [
            format!("{ok}{ok}"),                              // duplicate id
            ok.replace("\"ci\"", "\"bot\""),                  // performer
            ok.replace("\"ci\"", "\"role:\""),                // empty role
            ok.replace("[\"beta\"]", "[\"rc\"]"),             // channel
            ok.replace("[\"beta\"]", "[]"),                   // no channel
            ok.replace("[\"beta\"]", "[\"beta\", \"beta\"]"), // repeated channel
            ok.replace("planned", "done"),                    // status
            ok.replace("job = \"a\"\n", ""),                  // ci without job
            ok.replace("title = \"T\"", "title = \"a | b\""), // pipe in title
            format!("{ok}extra = 1\n"),                       // unknown key
            format!("other = 1\n{ok}"),                       // unknown top-level key
            ok.replace("id = \"a\"", "id = \"A\""),           // id charset
            "[[step]\n".to_string(),                          // TOML syntax
            String::new(),                                    // no steps
        ] {
            let e = parse_runbook(&bad).unwrap_err();
            assert_eq!(e.code, Code::Parse, "{bad}");
        }
    }

    #[test]
    fn human_steps() {
        let mut steps = parse_runbook(&format!("{}{}", step("a", "role:x"), step("b", "ci"))).unwrap();
        let f = check_consistency(&steps, &["a".into(), "b".into()], &[]);
        let got: Vec<_> = f.iter().map(|f| (f.code, f.subject.as_str())).collect();
        assert_eq!(got, vec![(Code::HumanStep, "a"), (Code::HumanStep, SIGN_APPROVAL)]);
        steps[0].id = SIGN_APPROVAL.into();
        assert!(check_consistency(&steps, &["a".into(), "b".into()], &[]).is_empty());
    }

    #[test]
    fn unknown_job_and_unused_gate() {
        let mut steps = parse_runbook(&format!("{}{}", step("sign-approval", "role:x"), step("b", "ci"))).unwrap();
        steps[1].gates = vec!["g1".into()];
        let f = check_consistency(&steps, &["sign-approval".into()], &["g1".into(), "g2".into()]);
        let got: Vec<_> = f.iter().map(|f| (f.code, f.subject.as_str())).collect();
        assert_eq!(got, vec![(Code::UnknownJob, "b"), (Code::UnusedGate, "g2")]);
    }

    #[test]
    fn render_normalises_line_endings() {
        let steps = parse_runbook(&step("a", "ci")).unwrap();
        assert_eq!(render(&steps, "P\r\nQ\r\n\r\n"), render(&steps, "P\nQ"));
        assert!(!render(&steps, "P\r\n").contains('\r'));
        assert!(render(&steps, "").starts_with(&format!("{HEADER}\n## Steps\n")));
    }
}
