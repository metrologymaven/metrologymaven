"""Independent reference for PLAT.DEPLOY.KIOSK.DISPLAY REQ-002 (pixel density).

Writes px-per-mm-cases.toml next to this script: for each (diagonal_in, width, height) the
expected `px_per_mm = hypot(w, h) / (diagonal_in * 25.4)`, formatted to 3 decimals. The Rust
tests in crates/fid-platform/tests/kiosk_display.rs compare against this file; the values are
never produced by running the Rust code. Inputs are chosen away from rounding ties (the script
checks that the 4th-6th decimals are not 500).

Run from anywhere with Python 3 (stdlib only):  python fixtures/plat/kiosk/make_px_per_mm_cases.py
"""

import math
import pathlib

MM_PER_IN = 25.4

# (diagonal_in, width, height); the first row is the shipped reference display.
INPUTS = [
    (21.5, 1920, 1080),
    (10, 800, 800),
    (43, 7680, 7680),
    (43, 800, 800),
    (10, 7680, 4320),
    (15.6, 1600, 900),
    (24, 1920, 1200),
    (27, 2560, 1440),
    (32, 3840, 2160),
    (12.1, 1280, 800),
]


def px_per_mm(diagonal_in, w, h):
    return math.hypot(w, h) / (diagonal_in * MM_PER_IN)


def main():
    lines = [
        "# Generated by make_px_per_mm_cases.py (PLAT.DEPLOY.KIOSK.DISPLAY REQ-002). Do not edit.",
        "# expected = format(hypot(w, h) / (diagonal_in * 25.4), '.3f')",
        "",
    ]
    for d, w, h in INPUTS:
        raw = px_per_mm(d, w, h)
        frac = abs(raw * 1000 - math.floor(raw * 1000) - 0.5)
        if frac < 1e-6:
            raise SystemExit(f"rounding tie too close for {(d, w, h)}: {raw!r}")
        lines += [
            "[[case]]",
            f"diagonal_in = {float(d)!r}",
            f"resolution = [{w}, {h}]",
            f'expected = "{raw:.3f}"',
            "",
        ]
    out = pathlib.Path(__file__).with_name("px-per-mm-cases.toml")
    out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"wrote {out} ({len(INPUTS)} cases)")


if __name__ == "__main__":
    main()
