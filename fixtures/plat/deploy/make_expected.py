#!/usr/bin/env python3
"""Independent reference for PLAT.DEPLOY.OFFLINE.NETLIST: writes network-features.json and
network-features.md in this folder from manifest-net.json and settings-manifest.json.

Applies the spec's rules (NODE.md Requirements, Design and Build prompt) directly, without
running or reading the Rust crate. The Rust tests and CI compare the output of
`cargo xtask plat-deploy netlist` with the files written here, byte for byte.

Rules: list every command whose side_effect is X1, I1 or D1, sorted by (id, major); CLI name
per CONSTITUTION section 3 (`fid <domain> <verb-object>`, dots to spaces, underscores to
hyphens; `fid <domain>` when cli_bare; none when `cli` is not in exposure); domain is the
first dotted segment; phase from lifecycle.phase; for X1 the opt_in_setting and its default
from the settings manifest, which must be off (false, "off", "disabled" or an empty list).
JSON is RFC 8785 (no floats occur, so sorted keys and compact separators are enough) plus a
final newline.

Fixtures and this script: MIT OR Apache-2.0 (D-001).
Run:  python fixtures/plat/deploy/make_expected.py [--check]
"""

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
NET = {"X1", "I1", "D1"}


def jcs(v):
    return json.dumps(v, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def is_off(v):
    if isinstance(v, bool):
        return v is False
    if isinstance(v, str):
        return v in ("off", "disabled")
    if isinstance(v, list):
        return len(v) == 0
    return False


def cli_name(name, bare):
    if "." not in name:
        return "fid " + name
    domain, rest = name.split(".", 1)
    if bare:
        return "fid " + domain
    return "fid " + domain + " " + rest.replace(".", " ").replace("_", "-")


def build(manifest, settings):
    defaults = {s["key"]: s["default"] for s in settings["settings"]}
    rows = []
    for c in manifest["commands"]:
        if c["side_effect"] not in NET:
            continue
        row = {
            "id": "%s@%d" % (c["id"], c["major"]),
            "class": c["side_effect"],
            "cli": cli_name(c["id"], c.get("cli_bare", False)) if "cli" in c.get("exposure", []) else None,
            "domain": c["id"].split(".")[0],
            "phase": c.get("lifecycle", {}).get("phase"),
        }
        if c["side_effect"] == "X1":
            key = c["opt_in_setting"]
            assert is_off(defaults[key]), row["id"]
            row["opt_in_setting"] = key
            row["default"] = defaults[key]
        rows.append(((c["id"], c["major"]), row))
    rows.sort(key=lambda r: r[0])
    return [r for _, r in rows]


def cell(s):
    return s.replace("|", "\\|")


def render_md(rows):
    out = [
        "<!-- Generated by `cargo xtask plat-deploy netlist` (spec node PLAT.DEPLOY.OFFLINE.NETLIST). "
        "Do not edit: `cargo xtask plat-deploy netlist --check` fails when this file differs from a fresh generation. -->",
        "",
        "# Network features",
        "",
        "Only commands of side-effect class X1 (egress), I1 (simulator I/O) and D1 (device I/O) may open network "
        "sockets (CONSTITUTION section 3.1, CORE.BUS.POL.EGRESS). This list is generated from the registry manifest "
        "and the settings manifest, and names every such command.",
        "",
        "Every X1 command is off by default: its opt-in setting below defaults to off (`false`, `off`, `disabled` "
        "or an empty list), and generation fails otherwise.",
        "",
        "I1 and D1 commands reach only the simulators and devices that have been configured, and run only on "
        "explicit user action.",
        "",
    ]
    if not rows:
        out.append("_No command in the registry manifest can use the network._")
        return "\n".join(out) + "\n"
    out.append("| Command | Class | CLI | Domain | Phase | Opt-in setting | Default |")
    out.append("|---|---|---|---|---|---|---|")
    code = lambda s: "`" + cell(s) + "`"
    for r in rows:
        key = code(r["opt_in_setting"]) if "opt_in_setting" in r else "n/a"
        default = code(jcs(r["default"])) if "opt_in_setting" in r else "n/a"
        out.append(
            "| %s | %s | %s | %s | %s | %s | %s |"
            % (
                code(r["id"]),
                r["class"],
                code(r["cli"]) if r["cli"] is not None else "n/a",
                cell(r["domain"]),
                cell(r["phase"]) if r["phase"] is not None else "n/a",
                key,
                default,
            )
        )
    n = len(rows)
    out.append("")
    out.append("%d command%s." % (n, "" if n == 1 else "s"))
    return "\n".join(out) + "\n"


def main():
    manifest = json.loads((HERE / "manifest-net.json").read_text(encoding="utf-8"))
    settings = json.loads((HERE / "settings-manifest.json").read_text(encoding="utf-8"))
    rows = build(manifest, settings)
    assert len(rows) == 3, rows  # AC-1: exactly three commands
    files = {
        "network-features.json": (jcs({"commands": rows, "format": 1}) + "\n").encode("utf-8"),
        "network-features.md": render_md(rows).encode("utf-8"),
    }
    check = "--check" in sys.argv[1:]
    stale = []
    for name, data in files.items():
        p = HERE / name
        if check:
            if not p.exists() or p.read_bytes() != data:
                stale.append(name)
        else:
            p.write_bytes(data)
    if stale:
        print("stale: " + ", ".join(stale) + " (run python fixtures/plat/deploy/make_expected.py)")
        return 1
    print("ok" if check else "written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
