#!/usr/bin/env python3
"""Independent reference for PLAT.MATRIX.PAGE: renders support matrix pages.

Reads matrix files with Python's tomllib and applies the leaf's rules (NODE.md Requirements,
Design and Build prompt) directly, without running or reading the Rust crate. Inputs are
assumed valid (validation is PLAT.MATRIX.FILE's job and is covered by make_expected.py).

Outputs (LF line endings, UTF-8):
  fixtures/plat/matrix/valid.toml          -> fixtures/plat/matrix/expected-page.md
  fixtures/plat/matrix/escape.toml         -> fixtures/plat/matrix/expected-escape-page.md
  platform/support-matrix.toml             -> docs/platform/support-matrix.md

The Rust tests compare `fid_platform::page::render` (and `cargo xtask plat-matrix page`) with
these files byte for byte. Fixtures and this script: MIT OR Apache-2.0 (D-001).
Run:  python fixtures/plat/matrix/make_page.py [--check]   (Python 3.11+)
"""

import hashlib
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent.parent

# Fixed section order (Build prompt) and display names.
FAMILIES = [
    ("windows", "Windows"),
    ("macos", "macOS"),
    ("ubuntu", "Ubuntu"),
    ("debian", "Debian"),
    ("fedora", "Fedora"),
    ("rhel", "RHEL"),
]
# Architecture order inside a section: the schema's declaration order.
ARCHES = ["x86_64", "aarch64"]
TIER_NAMES = {"tier1": "Tier 1", "tier2": "Tier 2", "tier3": "Tier 3"}

# Characters that get a backslash so they are literal in a GFM table cell.
BACKSLASHED = set("\\`*_[]|~$")
ENTITIES = {"&": "&amp;", "<": "&lt;", ">": "&gt;"}


def escape(text):
    out = []
    for ch in text:
        if ord(ch) < 0x20 or ord(ch) == 0x7F:
            out.append(" ")  # newlines, tabs and other controls would break the table row
        elif ch in ENTITIES:
            out.append(ENTITIES[ch])
        elif ch in BACKSLASHED:
            out.append("\\" + ch)
        else:
            out.append(ch)
    return "".join(out)


def vkey(s):
    parts = [int(p) for p in s.split(".")]
    return tuple(parts + [0] * (4 - len(parts)))


def versions(row):
    if "version_max" in row:
        return f"{row['version_min']} to before {row['version_max']}"
    return f"{row['version_min']} and later"


def render(raw):
    data = tomllib.loads(raw.decode("utf-8"))
    rows = data.get("row", [])
    digest = hashlib.sha256(raw).hexdigest()
    lines = [
        f"<!-- generated from platform/support-matrix.toml sha256:{digest}; do not edit -->",
        "# Support matrix",
        "",
        "This page is generated by `cargo xtask plat-matrix page` from the machine-readable "
        "support matrix; do not edit it by hand. Tier definitions: [tiers.md](tiers.md).",
    ]
    if not rows:
        lines += ["", "The matrix lists no platforms."]
    for os_name, title in FAMILIES:
        group = [r for r in rows if r["os"] == os_name]
        if not group:
            continue
        group.sort(key=lambda r: (ARCHES.index(r["arch"]), vkey(r["version_min"])))
        lines += ["", f"## {title}", "", "| Versions | Arch | Tier | Since | Notes |", "|---|---|---|---|---|"]
        for r in group:
            cells = [versions(r), r["arch"], TIER_NAMES[r["tier"]], r["since_phase"], r["notes"]]
            lines.append("| " + " | ".join(escape(c) for c in cells) + " |")
    return ("\n".join(lines) + "\n").encode("utf-8")


JOBS = [
    (HERE / "valid.toml", HERE / "expected-page.md"),
    (HERE / "escape.toml", HERE / "expected-escape-page.md"),
    (ROOT / "platform" / "support-matrix.toml", ROOT / "docs" / "platform" / "support-matrix.md"),
]


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for src, dst in JOBS:
        page = render(src.read_bytes())
        if check:
            if not dst.exists() or dst.read_bytes() != page:
                stale.append(dst)
        else:
            dst.write_bytes(page)
            print(f"wrote {dst.relative_to(ROOT).as_posix()}")
    for s in stale:
        print(f"stale: {s.relative_to(ROOT).as_posix()}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
