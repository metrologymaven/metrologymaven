"""Reference for UntrustedText::as_display escaping (IO.REG.LIMITS, REQ-005).

Rule, from the PR #68 review: write "\\" as "\\\\"; write every code point of general
category Cc, Cf, Zl or Zp as "\\u{<lowercase hex>}"; keep everything else. The category
data comes from Python's own `unicodedata`, independent of the Rust code. Requires a
Python whose unicodedata.unidata_version is 16.0.0 (Python 3.13+) so the ranges match the
Rust table exactly.

Writes escape_cases.txt:
  unicode <version>
  range <lo hex> <hi hex>      # maximal runs of code points that must be escaped
  case <input utf-8 hex> <expected display utf-8 hex>

Run from the repository root:  python fixtures/io/reg/limits/make_escape_cases.py
"""

import unicodedata
from pathlib import Path

HERE = Path(__file__).resolve().parent
ESCAPED = {"Cc", "Cf", "Zl", "Zp"}


def escaped(cp: int) -> bool:
    return unicodedata.category(chr(cp)) in ESCAPED


def display(s: str) -> str:
    out = []
    for ch in s:
        if ch == "\\":
            out.append("\\\\")
        elif escaped(ord(ch)):
            out.append("\\u{%x}" % ord(ch))
        else:
            out.append(ch)
    return "".join(out)


ranges = []
start = None
for cp in range(0x110000):
    hit = escaped(cp)
    if hit and start is None:
        start = cp
    if not hit and start is not None:
        ranges.append((start, cp - 1))
        start = None
if start is not None:
    ranges.append((start, 0x10FFFF))

cases = [
    "plain label",
    "back\\slash",
    "a\\u{202e}b",  # literal text that looks like an escape: the backslash is doubled
    "tab\tnew\nline\x00nul\x7fdel\x85nel",
    "rtl‮override⁦isolate⁩؜",
    "zero​width‌‍⁠joiner﻿bom",
    "line para sep",
    "soft­hyphen tag\U000e0041 ⁣invisible",
    "keep  nbsp 中文 \U0001f600 é",
]

with open(HERE / "escape_cases.txt", "w", encoding="utf-8", newline="\n") as f:
    f.write("# Generated by make_escape_cases.py.\n")
    f.write(f"unicode {unicodedata.unidata_version}\n")
    for lo, hi in ranges:
        f.write(f"range {lo:x} {hi:x}\n")
    for s in cases:
        f.write(f"case {s.encode('utf-8').hex()} {display(s).encode('utf-8').hex()}\n")
print(unicodedata.unidata_version, len(ranges), "ranges,", len(cases), "cases")
