"""Reference generator for the IO.REG.LIMITS fixtures and their expected outcomes.

Independent of the Rust code: the files are defined here, and every expected value in
expected.txt is derived from the spec's rules (spec/io/reg/limits/NODE.md, AC-1..AC-3)
by plain arithmetic over the bytes this script writes. No third-party data, no randomness
(the "seed" is the fixed content rule below), so the output is byte-identical on every run.

Run from the repository root:  python fixtures/io/reg/limits/make_fixtures.py
"""

from pathlib import Path

HERE = Path(__file__).resolve().parent

# AC-1: nesting depth 10,000: "[" * 10000 + "]" * 10000 + "\n".
DEPTH = 10_000
deep = b"[" * DEPTH + b"]" * DEPTH + b"\n"

# AC-2: 2 MiB of zero bytes.
zeros = bytes(2 * 1024 * 1024)

# AC-3: 5,000 lines "line 1\n" .. "line 5000\n".
lines = [f"line {i}\n".encode("ascii") for i in range(1, 5001)]
text = b"".join(lines)

(HERE / "deep_nest.json").write_bytes(deep)
(HERE / "zeros_2mib.bin").write_bytes(zeros)
(HERE / "lines_5000.txt").write_bytes(text)

# ---- expected outcomes, from the spec rules ------------------------------------------
# AC-1: default depth limit 64. Entering level k happens at the k-th "[" (byte k-1).
# Level 65 is the first one over the limit, so the error is at byte offset 64,
# line 1, column 65 (1-based).
DEFAULT_DEPTH = 64
ac1_offset = DEFAULT_DEPTH  # zero-based offset of the 65th "["
assert deep[ac1_offset : ac1_offset + 1] == b"["

# AC-2: byte limit 1 MiB; the source delivers exactly 1 MiB and fails at that offset.
BYTE_LIMIT = 1024 * 1024
assert len(zeros) > BYTE_LIMIT

# AC-3: element limit 1,000, one element per line; line 1,001 is the first over the
# limit. Its byte offset is the total length of the first 1,000 lines.
ELEMENT_LIMIT = 1000
ac3_line = ELEMENT_LIMIT + 1
ac3_offset = sum(len(l) for l in lines[:ELEMENT_LIMIT])

expected = {
    "deep_nest.size": len(deep),
    "ac1.limit": "depth",
    "ac1.value": DEFAULT_DEPTH,
    "ac1.byte": ac1_offset,
    "ac1.line": 1,
    "ac1.col": ac1_offset + 1,
    "zeros_2mib.size": len(zeros),
    "ac2.limit": "bytes",
    "ac2.value": BYTE_LIMIT,
    "ac2.byte": BYTE_LIMIT,
    "lines_5000.size": len(text),
    "lines_5000.count": len(lines),
    "ac3.limit": "elements",
    "ac3.value": ELEMENT_LIMIT,
    "ac3.line": ac3_line,
    "ac3.byte": ac3_offset,
}
with open(HERE / "expected.txt", "w", encoding="utf-8", newline="\n") as f:
    f.write("# Generated by make_fixtures.py. key value\n")
    for k, v in expected.items():
        f.write(f"{k} {v}\n")
print("wrote", sorted(p.name for p in HERE.iterdir()))
