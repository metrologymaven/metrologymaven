#!/usr/bin/env python3
"""Generate and verify test fixtures for IO.REG.PLUGIN.ABI (CC-BY-4.0).

Usage:
    python3 fixtures/io/reg/plugin/abi/make_fixtures.py
    python3 fixtures/io/reg/plugin/abi/make_fixtures.py --check
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent


def make_descriptor(major: int, minor: int) -> dict:
    return {
        "contract": {"major": major, "minor": minor},
        "formats": [
            {
                "direction": "import",
                "extensions": ["tplg"],
                "format_id": "toy-plugin",
                "options_schema": {
                    "additionalProperties": False,
                    "properties": {"scale": {"type": "number"}},
                    "type": "object",
                },
                "phase": 1,
                "signatures": [{"bytes": list(b"TOYPLG\n"), "offset": 0}],
                "version_max": "1",
                "version_min": "1",
            },
            {
                "direction": "export",
                "extensions": ["tplg"],
                "format_id": "toy-plugin",
                "options_schema": {"additionalProperties": False, "properties": {}, "type": "object"},
                "phase": 1,
                "signatures": [{"bytes": list(b"TOYPLG\n"), "offset": 0}],
                "version_max": "1",
                "version_min": "1",
            },
        ],
        "plugin_id": "toy-plugin-reader",
        "requested_caps": {"max_memory_bytes": 67108864, "max_wall_ms": 5000},
        "version": "1.0.0",
    }


def render_json(obj: dict) -> str:
    return json.dumps(obj, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def make_files() -> dict[str, str]:
    readme = (
        "# IO.REG.PLUGIN.ABI test fixtures\n"
        "\n"
        "License: CC-BY-4.0.\n"
        "\n"
        "Generated by `make_fixtures.py` (`python3 fixtures/io/reg/plugin/abi/make_fixtures.py --check`).\n"
        "\n"
        "- `descriptor-v1-0.json`: valid contract 1.0 plugin descriptor declaring `toy-plugin` (import & export).\n"
        "- `descriptor-major-mismatch.json`: contract 2.0 descriptor for AC-2 (`plugin_abi_mismatch`).\n"
        "- `descriptor-minor-too-high.json`: contract 1.2 descriptor for AC-3 (`plugin_abi_mismatch` against host 1.1).\n"
        "- `sample.tplg`: synthetic `toy-plugin` input exercising points, table, and warning records (AC-4).\n"
    )
    sample_tplg = (
        "TOYPLG\n"
        "UNIT mm\n"
        "POINTS datum_plane 0 0 0;10 0 0;0 10 0\n"
        "TABLE inspection_notes col_a,col_b|hello,world\n"
        "WARN sample_note trailing comment ignored\n"
    )
    return {
        "README.md": readme,
        "descriptor-v1-0.json": render_json(make_descriptor(1, 0)),
        "descriptor-major-mismatch.json": render_json(make_descriptor(2, 0)),
        "descriptor-minor-too-high.json": render_json(make_descriptor(1, 2)),
        "sample.tplg": sample_tplg,
    }


def main() -> int:
    check_mode = "--check" in sys.argv[1:]
    files = make_files()

    if check_mode:
        errors: list[str] = []
        for name, want in sorted(files.items()):
            path = HERE / name
            if not path.is_file():
                errors.append(f"missing fixture: {name}")
                continue
            got = path.read_text(encoding="utf-8")
            if got != want:
                errors.append(f"fixture out of date: {name}")
        if errors:
            for e in errors:
                print(e, file=sys.stderr)
            return 1
        return 0

    for name, content in sorted(files.items()):
        (HERE / name).write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
