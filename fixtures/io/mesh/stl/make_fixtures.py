from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path

OUT_DIR = Path(__file__).resolve().parent


def cube_triangles() -> list[tuple[tuple[float, float, float], tuple[float, float, float], tuple[float, float, float], tuple[float, float, float]]]:
    """12-triangle 10x10x10 mm cube: list of (normal, v0, v1, v2) with exact f32 coordinates."""
    s = 10.0
    p = [
        (0.0, 0.0, 0.0),  # 0
        (s, 0.0, 0.0),    # 1
        (s, s, 0.0),      # 2
        (0.0, s, 0.0),    # 3
        (0.0, 0.0, s),    # 4
        (s, 0.0, s),      # 5
        (s, s, s),        # 6
        (0.0, s, s),      # 7
    ]
    return [
        # -Z face
        ((0.0, 0.0, -1.0), p[0], p[2], p[1]),
        ((0.0, 0.0, -1.0), p[0], p[3], p[2]),
        # +Z face
        ((0.0, 0.0, 1.0), p[4], p[5], p[6]),
        ((0.0, 0.0, 1.0), p[4], p[6], p[7]),
        # -Y face
        ((0.0, -1.0, 0.0), p[0], p[1], p[5]),
        ((0.0, -1.0, 0.0), p[0], p[5], p[4]),
        # +Y face
        ((0.0, 1.0, 0.0), p[3], p[7], p[6]),
        ((0.0, 1.0, 0.0), p[3], p[6], p[2]),
        # -X face
        ((-1.0, 0.0, 0.0), p[0], p[4], p[7]),
        ((-1.0, 0.0, 0.0), p[0], p[7], p[3]),
        # +X face
        ((1.0, 0.0, 0.0), p[1], p[2], p[6]),
        ((1.0, 0.0, 0.0), p[1], p[6], p[5]),
    ]


def encode_binary_stl(header_text: bytes, tris: list) -> bytes:
    header = header_text[:80].ljust(80, b"\x00")
    out = bytearray(header)
    out.extend(struct.pack("<I", len(tris)))
    for n, v0, v1, v2 in tris:
        out.extend(struct.pack("<12fH", *n, *v0, *v1, *v2, 0))
    return bytes(out)


def encode_ascii_stl(solid_name: str, tris: list) -> bytes:
    lines = [f"solid {solid_name}"]
    for n, v0, v1, v2 in tris:
        lines.append(f"  facet normal {n[0]:g} {n[1]:g} {n[2]:g}")
        lines.append("    outer loop")
        lines.append(f"      vertex {v0[0]:g} {v0[1]:g} {v0[2]:g}")
        lines.append(f"      vertex {v1[0]:g} {v1[1]:g} {v1[2]:g}")
        lines.append(f"      vertex {v2[0]:g} {v2[1]:g} {v2[2]:g}")
        lines.append("    endloop")
        lines.append("  endfacet")
    lines.append(f"endsolid {solid_name}")
    return ("\n".join(lines) + "\n").encode("ascii")


def build_fixtures() -> dict[str, bytes]:
    tris = cube_triangles()
    cube_bin = encode_binary_stl(b"fiducial cube binary", tris)
    cube_bin_solid = encode_binary_stl(b"solid cube", tris)
    cube_ascii = encode_ascii_stl("cube", tris)
    # AC-4: last 20 bytes removed from cube_bin.stl
    cube_bin_truncated = cube_bin[:-20]
    # AC-5: ASCII STL with `vertex 1 2` on line 4
    bad_vertex = (
        "solid bad\n"
        "  facet normal 0 0 1\n"
        "    outer loop\n"
        "      vertex 1 2\n"
        "      vertex 1 0 0\n"
        "      vertex 0 1 0\n"
        "    endloop\n"
        "  endfacet\n"
        "endsolid bad\n"
    ).encode("ascii")

    return {
        "cube_bin.stl": cube_bin,
        "cube_bin_solid_header.stl": cube_bin_solid,
        "cube_ascii.stl": cube_ascii,
        "cube_bin_truncated.stl": cube_bin_truncated,
        "bad_vertex.stl": bad_vertex,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate or check IO.MESH.STL fixtures.")
    parser.add_argument("--check", action="store_true", help="Verify fixtures match generated bytes.")
    args = parser.parse_args()

    fixtures = build_fixtures()
    mismatches: list[str] = []
    for name, expected in sorted(fixtures.items()):
        path = OUT_DIR / name
        if args.check:
            if not path.exists() or path.read_bytes() != expected:
                mismatches.append(name)
        else:
            path.write_bytes(expected)

    if args.check:
        if mismatches:
            print("IO.MESH.STL fixture mismatch:", ", ".join(mismatches), file=sys.stderr)
            return 1
        print(f"IO.MESH.STL fixtures OK ({len(fixtures)} files)")
    else:
        print(f"Wrote {len(fixtures)} IO.MESH.STL fixtures to {OUT_DIR}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
