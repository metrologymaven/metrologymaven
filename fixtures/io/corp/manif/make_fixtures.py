#!/usr/bin/env python3
"""Independent fixture generator for IO.CORP.MANIF (CC-BY-4.0 project data).

Writes small synthetic corpus files, their manifests and two registry listings under
fixtures/io/corp/manif/. Every SHA-256 in the manifests is computed here with hashlib,
never by the Rust code under test. All files are synthetic and first-party: no
third-party corpus data (decision D-038 is open).

Layout:
  ok/                 AC-1: two manifests, two in-repo files, one url entry
  ok/files/           in-repo corpus files
  remote/             the file the url entry points to (served by the test harness)
  bad_licence/        AC-3: in-repo files with licence `unknown` and `GPL-3.0-only`
  registry_ok.json    list-formats output: mesh.ply, mesh.stl (+ one plugin format)
  registry_obj.json   the same plus first-party mesh.obj (AC-2)

The url in ok/mesh.stl.toml uses the reserved `.invalid` TLD (RFC 6761), so it can
never reach the internet; tests serve it from remote/ or rewrite it to a file:// URL.

Run:  python fixtures/io/corp/manif/make_fixtures.py
"""

import hashlib
import json
import struct
from pathlib import Path

HERE = Path(__file__).resolve().parent
REMOTE_URL = "https://corpus.example.invalid/mesh.stl/truncated_binary.stl"


def sha(data: bytes) -> str:
    return "sha256:" + hashlib.sha256(data).hexdigest()


def write(rel: str, data: bytes) -> bytes:
    p = HERE / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(data)
    return data


def tetra_stl() -> bytes:
    v = [(0, 0, 0), (1, 0, 0), (0, 1, 0), (0, 0, 1)]
    faces = [(0, 2, 1), (0, 1, 3), (0, 3, 2), (1, 2, 3)]
    out = ["solid tetra"]
    for a, b, c in faces:
        out.append("  facet normal 0 0 0")
        out.append("    outer loop")
        for i in (a, b, c):
            out.append("      vertex %d %d %d" % v[i])
        out.append("    endloop")
        out.append("  endfacet")
    out.append("endsolid tetra")
    return ("\n".join(out) + "\n").encode("ascii")


def tri_ply() -> bytes:
    text = (
        "ply\n"
        "format ascii 1.0\n"
        "comment synthetic IO.CORP.MANIF fixture\n"
        "element vertex 3\n"
        "property float x\nproperty float y\nproperty float z\n"
        "element face 1\n"
        "property list uchar int vertex_indices\n"
        "end_header\n"
        "0 0 0\n1 0 0\n0 1 0\n"
        "3 0 1 2\n"
    )
    return text.encode("ascii")


def truncated_binary_stl() -> bytes:
    # 80-byte header, facet count 2, but only one 50-byte facet record follows.
    header = b"synthetic truncated binary STL (IO.CORP.MANIF)".ljust(80, b" ")
    facet = struct.pack("<12fH", 0, 0, 1, 0, 0, 0, 1, 0, 0, 0, 1, 0, 0)
    return header + struct.pack("<I", 2) + facet


def toml_str(s: str) -> str:
    return json.dumps(s)  # a JSON string is a valid TOML basic string for this ASCII data


def entry(loc_key, loc, licence, digest, expect, tags) -> str:
    return (
        "[[entry]]\n"
        f"{loc_key} = {toml_str(loc)}\n"
        f"source = {toml_str('synthetic, fixtures/io/corp/manif/make_fixtures.py')}\n"
        f"licence = {toml_str(licence)}\n"
        f"sha256 = {toml_str(digest)}\n"
        f"expect = {expect}\n"
        f"tags = [{', '.join(toml_str(t) for t in tags)}]\n"
    )


def manifest(fmt: str, entries) -> bytes:
    head = f"# Corpus manifest (IO.CORP.MANIF). Generated by make_fixtures.py; do not edit.\nformat = {toml_str(fmt)}\n"
    return (head + "".join("\n" + e for e in entries)).encode("ascii")


def main() -> None:
    tetra = write("ok/files/tetra.stl", tetra_stl())
    tri = write("ok/files/tri.ply", tri_ply())
    trunc = write("remote/truncated_binary.stl", truncated_binary_stl())

    accept_tetra = "{ accept = { counts = { facets = 4 } } }"
    accept_tri = "{ accept = { counts = { faces = 1, vertices = 3 } } }"
    reject_trunc = '{ reject = { error = "truncated_file" } }'

    write(
        "ok/mesh.stl.toml",
        manifest(
            "mesh.stl",
            [
                entry("path", "files/tetra.stl", "CC-BY-4.0", sha(tetra), accept_tetra, ["p0-subset"]),
                entry("url", REMOTE_URL, "CC-BY-4.0", sha(trunc), reject_trunc, ["hostile"]),
            ],
        ),
    )
    ply_manifest = manifest(
        "mesh.ply", [entry("path", "files/tri.ply", "CC0-1.0", sha(tri), accept_tri, ["p0-subset"])]
    )
    write("ok/mesh.ply.toml", ply_manifest)

    # AC-3: same files, but the STL entries carry licences that forbid storing them in the repository.
    write("bad_licence/files/tetra.stl", tetra)
    write("bad_licence/files/tri.ply", tri)
    other = write("bad_licence/files/other.stl", tetra.replace(b"tetra", b"other"))
    write("bad_licence/mesh.ply.toml", ply_manifest)
    write(
        "bad_licence/mesh.stl.toml",
        manifest(
            "mesh.stl",
            [
                entry("path", "files/tetra.stl", "unknown", sha(tetra), accept_tetra, []),
                entry("path", "files/other.stl", "GPL-3.0-only", sha(other), accept_tetra, []),
            ],
        ),
    )

    listing = [
        {"id": "mesh.ply", "origin": "first_party"},
        {"id": "mesh.stl", "origin": "first_party"},
        {"id": "vendor.jt", "origin": "plugin"},
    ]
    write("registry_ok.json", (json.dumps(listing, indent=2) + "\n").encode("ascii"))
    with_obj = [{"id": "mesh.obj", "origin": "first_party"}] + listing
    envelope = {"command_id": "import.list_formats@1", "envelope_version": 1, "outcome": "computed", "result": with_obj}
    write("registry_obj.json", (json.dumps(envelope, indent=2) + "\n").encode("ascii"))


if __name__ == "__main__":
    main()
