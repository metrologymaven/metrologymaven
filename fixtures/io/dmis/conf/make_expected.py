#!/usr/bin/env python3
"""Independent reference generator for the DMIS conformance table (spec node IO.DMIS.CONF).

CC-BY-4.0 project data. Written separately from the Rust generator in crates/fid-io-dmis,
from the leaf's rules: a `partial` or `full` claim needs at least one test, all of them in
the inventory (else conformance_unproven); a module level gets the minimum over its
statements with none < partial < full; JSON is RFC 8785 canonical (sorted keys, no spaces;
the inputs here are ASCII strings and small integers, where json.dumps matches RFC 8785).

Run (stdlib only, Python 3.11+):
  python fixtures/io/dmis/conf/make_expected.py           # rewrite expected.json / expected.md
  python fixtures/io/dmis/conf/make_expected.py --check   # fail if they are stale
  python fixtures/io/dmis/conf/make_expected.py --decl D --tests T --out-dir O [--check]
"""

import json
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
RANK = {"none": 0, "partial": 1, "full": 2}
NAMES = {v: k for k, v in RANK.items()}


class Unproven(Exception):
    pass


def inventory(text):
    ids = set()
    for line in text.splitlines():
        line = line.rstrip("\r")
        if line.endswith(": test"):
            if line[: -len(": test")]:
                ids.add(line[: -len(": test")])
        elif line and not any(c.isspace() for c in line):
            ids.add(line)
    return ids


def generate(decl_text, inv_text):
    doc = tomllib.loads(decl_text)
    assert doc["schema"] == "fid.dmis-support" and doc["version"] == 1
    inv = inventory(inv_text)
    stmts = sorted(doc.get("statement", []), key=lambda s: s["keyword"])
    for s in stmts:
        tests = s.get("tests", [])
        if (s["import"] != "none" or s["export"] != "none") and (not tests or any(t not in inv for t in tests)):
            raise Unproven(s["keyword"])
    levels = {}
    for s in stmts:
        for m in s.get("modules", []):
            key = (m["module"], m["level"])
            e = levels.setdefault(key, {"import": 2, "export": 2, "statements": []})
            e["import"] = min(e["import"], RANK[s["import"]])
            e["export"] = min(e["export"], RANK[s["export"]])
            e["statements"].append(s["keyword"])

    def mods(s):
        return sorted((m["module"], m["level"]) for m in s.get("modules", []))

    table = {
        "schema": "fid.dmis-conformance",
        "version": 1,
        "standard": "DMIS 5.3",
        "module_levels": [
            {"module": k[0], "level": k[1], "import": NAMES[v["import"]], "export": NAMES[v["export"]],
             "statements": v["statements"]}
            for k, v in sorted(levels.items())
        ],
        "statements": [
            {"keyword": s["keyword"], "import": s["import"], "export": s["export"],
             "module_levels": [{"module": a, "level": b} for a, b in mods(s)],
             "tests": sorted(s.get("tests", []))}
            for s in stmts
        ],
    }
    js = json.dumps(table, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")

    md = ["<!-- Generated by dmis-conformance (spec node IO.DMIS.CONF). Do not edit by hand. -->",
          "# DMIS 5.3 conformance table", "",
          "Support is `none`, `partial` or `full` per direction. A module level is `full` only if "
          "every statement tagged to it is `full`; every `partial` or `full` claim names a test.", "",
          "## Conformance module levels", ""]
    if not levels:
        md += ["_No statement is tagged to a conformance module level yet._", ""]
    else:
        md += ["| Module | Level | Import | Export | Statements |", "| --- | --- | --- | --- | --- |"]
        for (mod, lvl), v in sorted(levels.items()):
            md.append(f"| {mod} | {lvl} | {NAMES[v['import']]} | {NAMES[v['export']]} | {', '.join(v['statements'])} |")
        md.append("")
    md += ["## Statements", ""]
    if not stmts:
        md.append("_No statements are declared._")
    else:
        md += ["| Statement | Import | Export | Module levels | Tests |", "| --- | --- | --- | --- | --- |"]
        for s in stmts:
            ml = ", ".join(f"{a} level {b}" for a, b in mods(s)) or "unassigned"
            ts = ", ".join(f"`{t}`" for t in sorted(s.get("tests", []))) or "none"
            md.append(f"| {s['keyword']} | {s['import']} | {s['export']} | {ml} | {ts} |")
    return js, ("\n".join(md) + "\n").encode("utf-8")


def emit(decl, tests, out_json, out_md, check):
    js, md = generate(decl.read_text(encoding="utf-8"), tests.read_text(encoding="utf-8"))
    stale = []
    for path, data in ((out_json, js), (out_md, md)):
        if check:
            if not path.exists() or path.read_bytes() != data:
                stale.append(str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    return stale


def main(argv):
    check = "--check" in argv
    args = [a for a in argv if a != "--check"]
    opts = dict(zip(args[::2], args[1::2]))
    stale = []
    if opts:
        out = Path(opts["--out-dir"])
        stale += emit(Path(opts["--decl"]), Path(opts["--tests"]),
                      out / "dmis-conformance.json", out / "dmis-conformance.md", check)
    else:
        stale += emit(HERE / "decl_small.toml", HERE / "tests.txt", HERE / "expected.json", HERE / "expected.md", check)
        try:
            generate((HERE / "decl_unproven.toml").read_text(encoding="utf-8"),
                     (HERE / "tests.txt").read_text(encoding="utf-8"))
            stale.append("decl_unproven.toml did not fail")
        except Unproven as e:
            if str(e) != "STMTB":
                stale.append(f"decl_unproven.toml failed on {e}, expected STMTB")
    for s in stale:
        print(f"stale: {s}")
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
