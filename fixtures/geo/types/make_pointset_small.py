#!/usr/bin/env python3
"""Independent reference for GEO.TYPES.ENV AC-1 and AC-6 (CC-BY-4.0 project data).

Writes fixtures/geo/types/pointset_small.txt: 1 000 points from the project's seeded
synthetic generator (Philox4x32-10, seed 1, stream 0, as in KRN.NUM.RNG), uniform in a
0.1 m cube, together with the fixture's frame ID and the expected axis-aligned bounding
box. Coordinates and box corners are written as f64 bit patterns (16 hex digits), so the
Rust test compares them bitwise.

Point i takes draws 3i, 3i+1, 3i+2 of the stream for x, y, z; each coordinate is
uniform_f64 * 0.1 (one IEEE 754 multiplication, round to nearest even).
The box is a min/max fold in IEEE 754 totalOrder (KNP-1), computed here in Python.
The frame ID is the first 16 bytes of SHA-256("GEO.TYPES.ENV pointset_small frame").

Run:  python fixtures/geo/types/make_pointset_small.py
"""

import hashlib
import struct
from pathlib import Path

M0, M1 = 0xD2511F53, 0xCD9E8D57
W0, W1 = 0x9E3779B9, 0xBB67AE85
MASK = 0xFFFFFFFF


def philox(ctr, key):
    c0, c1, c2, c3 = ctr
    k0, k1 = key
    for r in range(10):
        if r:
            k0, k1 = (k0 + W0) & MASK, (k1 + W1) & MASK
        p0, p1 = M0 * c0, M1 * c2
        hi0, lo0, hi1, lo1 = p0 >> 32, p0 & MASK, p1 >> 32, p1 & MASK
        c0, c1, c2, c3 = hi1 ^ c1 ^ k0, lo1, hi0 ^ c3 ^ k1, lo0
    return (c0, c1, c2, c3)


# Published Random123 known answer for philox4x32_10 (kat_vectors), as a self-check.
assert philox((0, 0, 0, 0), (0, 0)) == (0x6627E8D5, 0xE169C58D, 0xBC57AC4C, 0x9B00DBD8)


def next_u64(seed, stream, index):
    w = philox((index & MASK, index >> 32, stream & MASK, stream >> 32), (seed & MASK, seed >> 32))
    return (w[1] << 32) | w[0]


def uniform_f64(u):
    return (u >> 11) * 2.0 ** -53


def bits(x):
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def total_key(x):
    """IEEE 754 totalOrder key (the same order as Rust's f64::total_cmp)."""
    b = bits(x)
    return b ^ 0xFFFFFFFFFFFFFFFF if b >> 63 else b | (1 << 63)


SEED, STREAM, N, SIDE = 1, 0, 1000, 0.1
pts = []
for i in range(N):
    pts.append(tuple(uniform_f64(next_u64(SEED, STREAM, 3 * i + k)) * SIDE for k in range(3)))

lo = [min((p[k] for p in pts), key=total_key) for k in range(3)]
hi = [max((p[k] for p in pts), key=total_key) for k in range(3)]
assert all(0.0 <= lo[k] <= hi[k] < SIDE for k in range(3))

frame = hashlib.sha256(b"GEO.TYPES.ENV pointset_small frame").digest()[:16]

out = [
    "# GEO.TYPES.ENV AC-1 / AC-6 fixture. Generated by make_pointset_small.py (CC-BY-4.0).",
    "# Philox4x32-10 seed 1 stream 0; point i = draws 3i..3i+2 as uniform_f64 * 0.1 (metres).",
    "# Values are f64 bit patterns in hex. Lines: p <index> <x> <y> <z>.",
    f"frame {frame.hex()}",
    f"count {N}",
    "aabb_min " + " ".join(f"{bits(v):016x}" for v in lo),
    "aabb_max " + " ".join(f"{bits(v):016x}" for v in hi),
]
for i, p in enumerate(pts):
    out.append(f"p {i} " + " ".join(f"{bits(v):016x}" for v in p))

path = Path(__file__).parent / "pointset_small.txt"
path.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
print(f"wrote {path} ({N} points); aabb min {lo} max {hi}")
