#!/usr/bin/env python3
"""Independent reference for GEO.TYPES.POINTS AC-1, AC-4 and AC-5 (CC-BY-4.0 project data).

Stdlib only. Writes three files next to this script:

pointset_small_attrs.txt
    Normals and intensity for the 1 000 points of pointset_small.txt (GEO.TYPES.ENV;
    that file is unchanged). Philox4x32-10 seed 1, stream 1 (stream 0 holds the
    coordinates). Point i takes draws 4i..4i+3: v = 2u - 1 for draws 4i..4i+2, normal =
    v / |v| (|v| = sqrt((vx*vx + vy*vy) + vz*vz)); intensity = draw 4i+3 rounded to f32.
    Every normal is checked here to satisfy the spec rule | |n| - 1 | <= 1e-9.

normal_cases.txt
    Normals near and away from the 1e-9 tolerance with the expected verdict, decided by
    the spec rule alone: reject if any component is non-finite, else compute
    s = (x*x + y*y) + z*z in IEEE 754 binary64 (no fused multiply-add), len = sqrt(s)
    (correctly rounded), accept iff len is finite and |len - 1| <= 1e-9.

cloud_grid_2scans.txt
    Two simulated organised scans of 64 rows x 48 columns, scanner IDs 1 and 2, seed 2
    (scanner s uses stream s). Point k = r*48 + c of a scan: elevation
    -0.3 + 0.6*r/63, azimuth a0_s + (pi/2)*c/47, range 2 + 0.5*u(draw 2k); intensity =
    u(draw 2k+1) rounded to f32; timestamp_ns = s*1e9 + 1000*k; quality = 1 if the range
    exceeds 2.45 m else 0. Point = origin + range * direction. The combined cloud lists
    scan 1 then scan 2 (row-major), so its grid is 128 x 48. The expected bounding box is
    a min/max fold in IEEE 754 totalOrder, computed here.

All f64 values are written as 16-hex-digit bit patterns and f32 values as 8-hex-digit
bit patterns, so the Rust tests compare bitwise. The Rust code never produces any
expected value in these files.

Run:  python fixtures/geo/types/make_points_fixtures.py
"""

import hashlib
import math
import struct
from pathlib import Path

M0, M1 = 0xD2511F53, 0xCD9E8D57
W0, W1 = 0x9E3779B9, 0xBB67AE85
MASK = 0xFFFFFFFF
HERE = Path(__file__).parent
TOL = 1e-9


def philox(ctr, key):
    c0, c1, c2, c3 = ctr
    k0, k1 = key
    for r in range(10):
        if r:
            k0, k1 = (k0 + W0) & MASK, (k1 + W1) & MASK
        p0, p1 = M0 * c0, M1 * c2
        hi0, lo0, hi1, lo1 = p0 >> 32, p0 & MASK, p1 >> 32, p1 & MASK
        c0, c1, c2, c3 = hi1 ^ c1 ^ k0, lo1, hi0 ^ c3 ^ k1, lo0
    return (c0, c1, c2, c3)


# Published Random123 known answer for philox4x32_10 (kat_vectors), as a self-check.
assert philox((0, 0, 0, 0), (0, 0)) == (0x6627E8D5, 0xE169C58D, 0xBC57AC4C, 0x9B00DBD8)


def uniform(seed, stream, index):
    w = philox((index & MASK, index >> 32, stream & MASK, stream >> 32), (seed & MASK, seed >> 32))
    return (((w[1] << 32) | w[0]) >> 11) * 2.0 ** -53


def bits(x):
    return f"{struct.unpack('<Q', struct.pack('<d', x))[0]:016x}"


def f32_bits(x):
    return f"{struct.unpack('<I', struct.pack('<f', x))[0]:08x}"


def total_key(x):
    """IEEE 754 totalOrder key (the same order as Rust's f64::total_cmp)."""
    b = struct.unpack("<Q", struct.pack("<d", x))[0]
    return b ^ 0xFFFFFFFFFFFFFFFF if b >> 63 else b | (1 << 63)


def normal_accepted(n):
    """The spec rule of REQ-GEO.TYPES.POINTS-004, written independently."""
    if not all(math.isfinite(v) for v in n):
        return False
    s = (n[0] * n[0] + n[1] * n[1]) + n[2] * n[2]
    if not math.isfinite(s):
        return False
    length = math.sqrt(s)
    return abs(length - 1.0) <= TOL


def frame_of(label):
    return hashlib.sha256(label.encode()).digest()[:16].hex()


def write(name, lines):
    path = HERE / name
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"wrote {path}")


# --- pointset_small_attrs.txt -------------------------------------------------------
N = 1000
attrs = [
    "# GEO.TYPES.POINTS AC-1 fixture: normals and intensity for pointset_small.txt.",
    "# Generated by make_points_fixtures.py (CC-BY-4.0). Philox4x32-10 seed 1 stream 1.",
    "# Lines: a <index> <nx> <ny> <nz> (f64 bits) <intensity> (f32 bits).",
    f"frame {frame_of('GEO.TYPES.ENV pointset_small frame')}",
    f"count {N}",
]
for i in range(N):
    u = [uniform(1, 1, 4 * i + k) for k in range(4)]
    v = [2.0 * u[k] - 1.0 for k in range(3)]
    l2 = (v[0] * v[0] + v[1] * v[1]) + v[2] * v[2]
    if l2 < 1e-6:
        n = [0.0, 0.0, 1.0]
    else:
        ln = math.sqrt(l2)
        n = [v[k] / ln for k in range(3)]
    assert normal_accepted(n), (i, n)
    attrs.append(f"a {i} " + " ".join(bits(c) for c in n) + f" {f32_bits(u[3])}")
write("pointset_small_attrs.txt", attrs)

# --- normal_cases.txt -----------------------------------------------------------------
r3 = 1.0 / math.sqrt(3.0)
cases = [
    ("unit_x", (1.0, 0.0, 0.0)),
    ("unit_neg_z", (0.0, 0.0, -1.0)),
    ("three_four_five", (0.6, 0.8, 0.0)),
    ("diagonal", (r3, r3, r3)),
    ("plus_1e-10", (1.0 + 1e-10, 0.0, 0.0)),
    ("minus_1e-10", (1.0 - 1e-10, 0.0, 0.0)),
    ("plus_9e-10", (1.0 + 9e-10, 0.0, 0.0)),
    ("minus_9e-10", (0.0, 1.0 - 9e-10, 0.0)),
    ("plus_1.1e-9", (1.0 + 1.1e-9, 0.0, 0.0)),
    ("minus_1.1e-9", (0.0, 0.0, 1.0 - 1.1e-9)),
    ("plus_1e-6", (1.0 + 1e-6, 0.0, 0.0)),
    ("minus_1e-6", (1.0 - 1e-6, 0.0, 0.0)),
    ("zero", (0.0, 0.0, 0.0)),
    ("half", (0.5, 0.0, 0.0)),
    ("huge", (1e200, 0.0, 0.0)),
    ("tiny", (1e-200, 0.0, 0.0)),
    ("nan", (float("nan"), 0.0, 0.0)),
    ("pos_inf", (0.0, float("inf"), 0.0)),
    ("neg_inf", (0.0, 0.0, float("-inf"))),
]
expect = {"plus_1e-10": True, "plus_1e-6": False, "zero": False, "nan": False}
nc = [
    "# GEO.TYPES.POINTS AC-4 fixture. Generated by make_points_fixtures.py (CC-BY-4.0).",
    "# Lines: n <label> <nx> <ny> <nz> (f64 bits) <accept 1|0>; verdict from the spec rule.",
]
for label, n in cases:
    ok = normal_accepted(n)
    if label in expect:
        assert ok == expect[label], label
    nc.append(f"n {label} " + " ".join(bits(c) for c in n) + f" {int(ok)}")
write("normal_cases.txt", nc)

# --- cloud_grid_2scans.txt -------------------------------------------------------------
ROWS, COLS = 64, 48
scans = [(1, (0.0, 0.0, 1.5), 0.0), (2, (4.0, 3.0, 1.25), math.pi)]
pts = []
for sid, origin, a0 in scans:
    for r in range(ROWS):
        for c in range(COLS):
            k = r * COLS + c
            el = -0.3 + 0.6 * r / (ROWS - 1)
            az = a0 + (math.pi / 2) * c / (COLS - 1)
            rng = 2.0 + 0.5 * uniform(2, sid, 2 * k)
            inten = uniform(2, sid, 2 * k + 1)
            d = (math.cos(el) * math.cos(az), math.cos(el) * math.sin(az), math.sin(el))
            p = tuple(origin[j] + rng * d[j] for j in range(3))
            ts = sid * 1_000_000_000 + 1000 * k
            q = 1 if rng > 2.45 else 0
            pts.append((sid, p, inten, ts, q))
lo = [min((p[1][k] for p in pts), key=total_key) for k in range(3)]
hi = [max((p[1][k] for p in pts), key=total_key) for k in range(3)]
cg = [
    "# GEO.TYPES.POINTS AC-5 fixture. Generated by make_points_fixtures.py (CC-BY-4.0).",
    "# Two organised scans, 64 rows x 48 columns each, seed 2; combined grid 128 x 48.",
    "# Lines: origin <scanner_id> <x> <y> <z>; p <index> <scanner_id> <x> <y> <z>",
    "#        <intensity f32 bits> <timestamp_ns> <quality>. f64 values are bit patterns.",
    f"frame {frame_of('GEO.TYPES.POINTS cloud_grid_2scans frame')}",
    f"count {len(pts)}",
    f"scan_grid {ROWS} {COLS}",
]
for sid, origin, _ in scans:
    cg.append(f"origin {sid} " + " ".join(bits(v) for v in origin))
cg.append("aabb_min " + " ".join(bits(v) for v in lo))
cg.append("aabb_max " + " ".join(bits(v) for v in hi))
for i, (sid, p, inten, ts, q) in enumerate(pts):
    cg.append(f"p {i} {sid} " + " ".join(bits(v) for v in p) + f" {f32_bits(inten)} {ts} {q}")
write("cloud_grid_2scans.txt", cg)
