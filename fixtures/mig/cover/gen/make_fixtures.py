#!/usr/bin/env python3
"""Synthetic fixtures and independent reference outputs for MIG.COVER.GEN (project-authored, CC0-1.0).

Every corpus file here is invented: the "files" are never written, their SHA-256 values are
digests of short made-up labels, and the reports are hand-designed so that each construct
lands in a known status. No vendor file, no third-party data and no incumbent format text is
used (D-038). Nothing here runs the Rust code: the expected tables are computed below from
the leaf's rules, restated here, and the hand-labelled status of each construct is asserted
before anything is written.

Writes, next to itself:

- csv-points/: taxo.json (6 constructs), corpus.json (4 public files), reports.json (a
  mig-report-set@1 with 4 mig-mapreport@1 reports, one per file) and expected/ with
  coverage-csv-points.json and coverage-csv-points.md (AC-1: one UNTESTED, one PARTIAL and
  one UNSUPPORTED row, three SUPPORTED rows).
- csv-points/drift/: the expected pair with one count edited by hand in the Markdown, and
  expected-drift.txt naming the line (AC-4: DRIFT-DIFF coverage-csv-points.md:<line>).
- csv-points/foreign-reports.json: the AC-1 reports plus one whose corpus file digest is not
  in the manifest (AC-3: coverage_foreign_report naming that report).
- csv-points/private-corpus.json and expected-private/: the AC-1 corpus with one file
  private, so the header says private_run true.
- dmis-prog/: taxo.json, corpus.json (3 programs), reports.json (3 mig-equivalence@1 reports;
  program b is DIVERGENT and contains GOTO, whose every occurrence is MAPPED) and expected/
  (AC-2: GOTO is PARTIAL, not SUPPORTED).

Rules restated from the leaf (MIG.COVER.GEN REQ-001..008) and the module's pinned rules:

- Per construct, in taxonomy order, count MAPPED, PARTIAL and UNSUPPORTED occurrences over
  every report item. No occurrence: UNTESTED. At least one, all MAPPED and (program tables)
  every program containing it EQUIVALENT: SUPPORTED. Otherwise any MAPPED or PARTIAL:
  PARTIAL. Otherwise: UNSUPPORTED.
- A table is a program table when any report is mig-equivalence@1; its rows also count the
  programs containing the construct whose verdict is EQUIVALENT, and those whose verdict is
  anything else.
- Digests are sha256:<hex> of RFC 8785 canonical JSON. Every document here holds only ASCII
  strings, booleans, small non-negative integers, arrays and objects, for which RFC 8785 is
  JSON with keys sorted and no whitespace, so json.dumps(sort_keys=True,
  separators=(",", ":")) is an independent implementation of it. The corpus digest sorts
  entries by catalogue ID first (MIG.COVER.CORPUS REQ-005).
- The table JSON is canonical with no trailing newline; the Markdown layout is written out
  below line by line, LF endings.

Run:  python fixtures/mig/cover/gen/make_fixtures.py          (write)
      python fixtures/mig/cover/gen/make_fixtures.py --check  (compare, exit 1 on drift)
"""

import copy
import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
GENERATED = "Generated by fid migrate generate-coverage. Do not edit."
GENERATOR = "migrate.generate_coverage@1"
GENERATOR_VERSION = "1.0.0"
RELEASE = "0.1.0"
ATTEST = {
    "date": "2026-11-24",
    "reviewer": "Metrology Maven maintainers",
    "statement": "Construct descriptions authored in original project wording for this fixture.",
}


def canon(v):
    return json.dumps(v, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def sha(text):
    return "sha256:" + hashlib.sha256(text.encode()).hexdigest()


def fake_file(label):
    """Digest of an invented label, standing in for a corpus file the fixtures never hold."""
    return sha("mig cover gen fixture file " + label)


def pretty(v):
    return json.dumps(v, indent=2, ensure_ascii=False) + "\n"


# ------------------------------------------------------------------ inputs


def taxonomy(format_id, constructs):
    return {
        "schema": "mig-taxonomy@1",
        "format_id": format_id,
        "version": "1.0.0",
        "reviewer_attestation": ATTEST,
        "constructs": [dict(c) for c in constructs],
    }


def corpus(format_id, name, files, private=()):
    return {
        "schema": "mig-corpus@1",
        "format_id": format_id,
        "name": name,
        "entries": [
            {
                "catalogue_id": cid,
                "sha256": fake_file(cid),
                "format_id": format_id,
                "visibility": "private" if cid in private else "public",
            }
            for cid in files
        ],
    }


def corpus_digest(c):
    c = copy.deepcopy(c)
    c["entries"].sort(key=lambda e: e["catalogue_id"])
    return sha(canon(c))


def mapreport(format_id, file_id, items):
    """A mig-mapreport@1 report as MIG.PROJ.MAPREP's build prompt describes it."""
    out, summary = [], {"MAPPED": 0, "PARTIAL": 0, "UNSUPPORTED": 0}
    for i, (construct, status) in enumerate(items, start=1):
        item = {"locator": "line %d" % (i + 1), "construct_id": construct, "status": status}
        if status == "PARTIAL":
            item["reason"] = "missing_field"
        elif status == "UNSUPPORTED":
            item["reason"] = "unsupported_construct"
        out.append(item)
        summary[status] += 1
    return {
        "schema": "mig-mapreport@1",
        "header": {
            "profile_id": "demo-csv-profile",
            "profile_version": "1.0.0",
            "source_sha256": fake_file(file_id),
            "format_id": format_id,
            "importer_version": "0.1.0",
        },
        "items": out,
        "summary": summary,
    }


def equivalence(format_id, file_id, verdict, items):
    """A mig-equivalence@1 report reduced to the fields MIG.COVER.GEN reads (MIG.PROGEQ is P2)."""
    return {
        "schema": "mig-equivalence@1",
        "header": {"source_sha256": fake_file(file_id), "format_id": format_id},
        "verdict": verdict,
        "items": [{"line": i + 1, "construct_id": c, "status": s} for i, (c, s) in enumerate(items)],
    }


def report_set(named):
    return {"schema": "mig-report-set@1", "reports": [{"name": n, "report": r} for n, r in named]}


# ------------------------------------------------------------------ reference generator


def generate(tax, corp, rset):
    reports = [e["report"] for e in rset["reports"]]
    program = any(r["schema"] == "mig-equivalence@1" for r in reports)
    rows = []
    for con in tax["constructs"]:
        cid = con["id"]
        m = p = u = 0
        eq, ne = set(), set()
        for r in reports:
            src = r["header"]["source_sha256"]
            for it in r["items"]:
                if it["construct_id"] != cid:
                    continue
                m += it["status"] == "MAPPED"
                p += it["status"] == "PARTIAL"
                u += it["status"] == "UNSUPPORTED"
                if program:
                    (eq if r.get("verdict") == "EQUIVALENT" else ne).add(src)
        if m + p + u == 0:
            status = "UNTESTED"
        elif p == 0 and u == 0 and (not program or not ne):
            status = "SUPPORTED"
        elif m + p > 0:
            status = "PARTIAL"
        else:
            status = "UNSUPPORTED"
        row = {"construct_id": cid, "status": status, "mapped": m, "partial": p, "unsupported": u}
        if program:
            row["programs_equivalent"] = len(eq)
            row["programs_not_equivalent"] = len(ne)
        rows.append(row)
    header = {
        "generated": GENERATED,
        "generator": GENERATOR,
        "generator_version": GENERATOR_VERSION,
        "release": RELEASE,
        "format_id": tax["format_id"],
        "corpus_name": corp["name"],
        "corpus_digest": corpus_digest(corp),
        "taxonomy_version": tax["version"],
        "taxonomy_digest": sha(canon(tax)),
        "private_run": any(e["visibility"] == "private" for e in corp["entries"]),
        "reports": sorted(sha(canon(r)) for r in reports),
    }
    return {"schema": "mig-coverage@1", "header": header, "rows": rows}, program


def render_md(table, program):
    h = table["header"]
    lines = [GENERATED, "", "# Migration coverage: " + h["format_id"], ""]
    lines.append("- Release: " + h["release"])
    lines.append("- Corpus: %s, digest `%s`" % (h["corpus_name"], h["corpus_digest"]))
    lines.append("- Taxonomy: version %s, digest `%s`" % (h["taxonomy_version"], h["taxonomy_digest"]))
    lines.append("- Generator: %s version %s" % (GENERATOR, GENERATOR_VERSION))
    if h["private_run"]:
        lines.append("- Private run: yes (the corpus holds files the project may not redistribute)")
    else:
        lines.append("- Private run: no")
    if h["reports"]:
        lines.append("- Input reports (%d):" % len(h["reports"]))
        lines += ["  - `%s`" % d for d in h["reports"]]
    else:
        lines.append("- Input reports: none")
    lines.append("")
    if program:
        lines.append(
            "| Construct | Status | Mapped | Partial | Unsupported | Programs equivalent | Programs not equivalent |"
        )
        lines.append("|---|---|---:|---:|---:|---:|---:|")
    else:
        lines.append("| Construct | Status | Mapped | Partial | Unsupported |")
        lines.append("|---|---|---:|---:|---:|")
    for r in table["rows"]:
        cells = ["`%s`" % r["construct_id"], r["status"], str(r["mapped"]), str(r["partial"]), str(r["unsupported"])]
        if program:
            cells += [str(r["programs_equivalent"]), str(r["programs_not_equivalent"])]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------ fixtures

CSV_CONSTRUCTS = [
    {"id": "column.header", "kind": "layout", "description": "Header row naming the exported columns."},
    {"id": "point_set.xyz", "kind": "record", "description": "Row of three Cartesian coordinates."},
    {"id": "point_set.ijk_normal", "kind": "field", "description": "Optional surface normal columns per point."},
    {"id": "result.row", "kind": "record", "description": "Row with a characteristic value and its limits."},
    {"id": "unit.column", "kind": "field", "description": "Column holding a unit symbol per row."},
    {"id": "comment.line", "kind": "layout", "description": "Free comment line between data rows."},
]
CSV_FILES = ["mig-csv-demo-1", "mig-csv-demo-2", "mig-csv-demo-3", "mig-csv-demo-4"]
M, P, U = "MAPPED", "PARTIAL", "UNSUPPORTED"
CSV_ITEMS = {
    "mig-csv-demo-1": [("column.header", M), ("point_set.xyz", M), ("point_set.xyz", M), ("point_set.ijk_normal", M)],
    "mig-csv-demo-2": [("column.header", M), ("point_set.xyz", M), ("point_set.ijk_normal", P), ("unit.column", U)],
    "mig-csv-demo-3": [("column.header", M), ("result.row", M), ("result.row", M), ("unit.column", U)],
    "mig-csv-demo-4": [("column.header", M), ("point_set.xyz", M), ("point_set.ijk_normal", M)],
}
# Hand-labelled from the rules, independent of generate() above.
CSV_LABELS = {
    "column.header": "SUPPORTED",
    "point_set.xyz": "SUPPORTED",
    "point_set.ijk_normal": "PARTIAL",
    "result.row": "SUPPORTED",
    "unit.column": "UNSUPPORTED",
    "comment.line": "UNTESTED",
}

DMIS_CONSTRUCTS = [
    {"id": "stmt.dmismn", "kind": "statement", "dmis_keyword": "DMISMN", "description": "Program header."},
    {"id": "stmt.goto", "kind": "statement", "dmis_keyword": "GOTO", "description": "Move to a point."},
    {"id": "stmt.feat", "kind": "statement", "dmis_keyword": "FEAT", "description": "Feature definition."},
    {"id": "stmt.endfil", "kind": "statement", "dmis_keyword": "ENDFIL", "description": "End of program."},
]
DMIS_PROGRAMS = [
    ("mig-dmis-prog-a", "EQUIVALENT", [("stmt.dmismn", M), ("stmt.goto", M), ("stmt.goto", M), ("stmt.feat", M)]),
    ("mig-dmis-prog-b", "DIVERGENT", [("stmt.dmismn", M), ("stmt.goto", M)]),
    ("mig-dmis-prog-c", "EQUIVALENT", [("stmt.dmismn", M), ("stmt.feat", M)]),
]
DMIS_LABELS = {
    "stmt.dmismn": ("PARTIAL", 2, 1),
    "stmt.goto": ("PARTIAL", 1, 1),
    "stmt.feat": ("SUPPORTED", 2, 0),
    "stmt.endfil": ("UNTESTED", 0, 0),
}


def outputs():
    out = {}

    # ---- csv-points (AC-1, AC-3, AC-4)
    tax = taxonomy("csv-points", CSV_CONSTRUCTS)
    corp = corpus("csv-points", "CSV points demo corpus", CSV_FILES)
    named = [(f + ".mapreport.json", mapreport("csv-points", f, CSV_ITEMS[f])) for f in CSV_FILES]
    rset = report_set(named)
    table, program = generate(tax, corp, rset)
    got = {r["construct_id"]: r["status"] for r in table["rows"]}
    assert got == CSV_LABELS, got
    statuses = [r["status"] for r in table["rows"]]
    assert statuses.count("UNTESTED") == 1 and statuses.count("PARTIAL") == 1
    assert statuses.count("UNSUPPORTED") == 1 and not program
    md = render_md(table, program)
    out["csv-points/taxo.json"] = pretty(tax)
    out["csv-points/corpus.json"] = pretty(corp)
    out["csv-points/reports.json"] = pretty(rset)
    out["csv-points/expected/coverage-csv-points.json"] = canon(table)
    out["csv-points/expected/coverage-csv-points.md"] = md

    # AC-4: edit the mapped count of point_set.xyz (4) by hand in the Markdown copy.
    lines = md.split("\n")
    idx = next(i for i, l in enumerate(lines) if l.startswith("| `point_set.xyz` |"))
    assert lines[idx] == "| `point_set.xyz` | SUPPORTED | 4 | 0 | 0 |", lines[idx]
    lines[idx] = "| `point_set.xyz` | SUPPORTED | 5 | 0 | 0 |"
    out["csv-points/drift/coverage-csv-points.json"] = canon(table)
    out["csv-points/drift/coverage-csv-points.md"] = "\n".join(lines)
    out["csv-points/drift/expected-drift.txt"] = "DRIFT-DIFF coverage-csv-points.md:%d\n" % (idx + 1)

    # AC-3: a report for a corpus file outside the manifest.
    foreign = copy.deepcopy(rset)
    foreign["reports"].append(
        {"name": "mig-csv-stray.mapreport.json", "report": mapreport("csv-points", "mig-csv-stray", [("column.header", M)])}
    )
    out["csv-points/foreign-reports.json"] = pretty(foreign)

    # private_run: one file private.
    pcorp = corpus("csv-points", "CSV points demo corpus", CSV_FILES, private={"mig-csv-demo-3"})
    ptable, _ = generate(tax, pcorp, rset)
    assert ptable["header"]["private_run"] is True
    out["csv-points/private-corpus.json"] = pretty(pcorp)
    out["csv-points/expected-private/coverage-csv-points.json"] = canon(ptable)
    out["csv-points/expected-private/coverage-csv-points.md"] = render_md(ptable, False)

    # ---- dmis-prog (AC-2)
    dtax = taxonomy("dmis-prog", DMIS_CONSTRUCTS)
    dcorp = corpus("dmis-prog", "DMIS programs demo corpus", [p[0] for p in DMIS_PROGRAMS])
    dset = report_set([(f + ".equivalence.json", equivalence("dmis-prog", f, v, it)) for f, v, it in DMIS_PROGRAMS])
    dtable, dprogram = generate(dtax, dcorp, dset)
    assert dprogram
    got = {
        r["construct_id"]: (r["status"], r["programs_equivalent"], r["programs_not_equivalent"]) for r in dtable["rows"]
    }
    assert got == DMIS_LABELS, got
    goto = next(r for r in dtable["rows"] if r["construct_id"] == "stmt.goto")
    assert goto["partial"] == 0 and goto["unsupported"] == 0 and goto["mapped"] == 3
    out["dmis-prog/taxo.json"] = pretty(dtax)
    out["dmis-prog/corpus.json"] = pretty(dcorp)
    out["dmis-prog/reports.json"] = pretty(dset)
    out["dmis-prog/expected/coverage-dmis-prog.json"] = canon(dtable)
    out["dmis-prog/expected/coverage-dmis-prog.md"] = render_md(dtable, dprogram)
    return out


def main():
    check = "--check" in sys.argv[1:]
    drift = False
    for name, text in outputs().items():
        path = HERE / name
        if check:
            if not path.exists() or path.read_bytes() != text.encode():
                print("drift: " + name)
                drift = True
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(text.encode())
    return 1 if drift else 0


if __name__ == "__main__":
    sys.exit(main())
