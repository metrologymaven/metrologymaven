#!/usr/bin/env python3
"""Deterministic fixture generator for MIG.EXPLAIN.CAT (CC0-1.0).

Generates fixtures/mig/explain/cat/:
  - valid-set.json: one candidate per factor in mig-factors@1
  - valid-set.digest: independent SHA-256 of canonical CandidateSet JSON
  - bad-factor.json: candidate at index 0 naming unknown factor PROBE_RADIUS
  - too-large.json: 65 valid candidates (> MAX_CANDIDATES = 64)
"""

from __future__ import annotations

import argparse
import hashlib
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent

FACTOR_ORDER = {
    "FIT_METHOD": 0,
    "FILTER": 1,
    "ALIGNMENT": 2,
    "DATUM_INTERPRETATION": 3,
    "POINT_SELECTION": 4,
    "ROUNDING": 5,
}


def canon_bytes(obj: object) -> bytes:
    return json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")


def sha256_canon(obj: object) -> str:
    return "sha256:" + hashlib.sha256(canon_bytes(obj)).hexdigest()


def make_valid_set() -> dict[str, object]:
    # Deliberately out of catalogue order in input to verify canonical sorting too.
    candidates = [
        {
            "factor": "ROUNDING",
            "setting": {"decimals": 4, "rule": "half_even"},
            "source": "UserSelected",
            "proposer": "alice",
            "session": None,
        },
        {
            "factor": "FIT_METHOD",
            "setting": {"association_policy_id": "lsq.gaussian@1"},
            "source": "ExportStated",
            "proposer": "alice",
            "session": None,
        },
        {
            "factor": "POINT_SELECTION",
            "setting": {"selection_digest": "sha256:" + "11" * 32},
            "source": "UserSelected",
            "proposer": "alice",
            "session": None,
        },
        {
            "factor": "FILTER",
            "setting": {"filter_policy_id": "gauss.iso16610-21@1", "cutoff_mm": 0.8, "order": 2},
            "source": "ExportStated",
            "proposer": "alice",
            "session": None,
        },
        {
            "factor": "DATUM_INTERPRETATION",
            "setting": {"resolver_row_id": "dmt.asme.primary-plane@1"},
            "source": "UserSelected",
            "proposer": "alice",
            "session": None,
        },
        {
            "factor": "ALIGNMENT",
            "setting": {"alignment_ref": "align.datum-abc@1"},
            "source": "ExportStated",
            "proposer": "alice",
            "session": None,
        },
    ]
    return {"candidates": candidates}


def compute_valid_digest(valid_set: dict[str, object]) -> bytes:
    rows = []
    for c in valid_set["candidates"]:  # type: ignore[index]
        sd = sha256_canon(c["setting"])
        rows.append(
            {
                "factor": c["factor"],
                "proposer": c["proposer"],
                "session": c["session"],
                "setting": c["setting"],
                "setting_digest": sd,
                "source": c["source"],
            }
        )
    rows.sort(
        key=lambda r: (
            FACTOR_ORDER[r["factor"]],
            r["setting_digest"],
            r["source"],
            r["proposer"],
            "" if r["session"] is None else r["session"],
        )
    )
    payload = {"candidates": rows, "catalogue": "mig-factors@1"}
    return (sha256_canon(payload) + "\n").encode("utf-8")


def make_bad_factor() -> dict[str, object]:
    return {
        "candidates": [
            {
                "factor": "PROBE_RADIUS",
                "setting": {"radius_mm": 2.0},
                "source": "UserSelected",
                "proposer": "alice",
                "session": None,
            }
        ]
    }


def make_too_large() -> dict[str, object]:
    cands = []
    for i in range(65):
        cands.append(
            {
                "factor": "FIT_METHOD",
                "setting": {"association_policy_id": f"lsq.variant-{i:03d}@1"},
                "source": "UserSelected",
                "proposer": "alice",
                "session": None,
            }
        )
    return {"candidates": cands}


def dump(obj: object) -> bytes:
    return (json.dumps(obj, sort_keys=True, indent=2) + "\n").encode("utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="Verify committed fixtures match generated bytes.")
    args = ap.parse_args()

    valid = make_valid_set()
    outputs = {
        HERE / "valid-set.json": dump(valid),
        HERE / "valid-set.digest": compute_valid_digest(valid),
        HERE / "bad-factor.json": dump(make_bad_factor()),
        HERE / "too-large.json": dump(make_too_large()),
    }

    if args.check:
        ok = True
        for path, expected in outputs.items():
            if not path.exists() or path.read_bytes() != expected:
                print(f"DRIFT: {path}", file=sys.stderr)
                ok = False
        return 0 if ok else 1

    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
