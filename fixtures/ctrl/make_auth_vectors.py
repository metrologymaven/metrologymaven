#!/usr/bin/env python3
"""Independent HMAC-SHA256 reference for AUTO.CTRL.AUTH AC-6 (CC-BY-4.0 project data).

Writes fixtures/ctrl/auth-vectors.json: for each case a token, a server nonce and a client
nonce (64 lowercase hex digits each) and the two proofs

    client_proof = HMAC-SHA256(token, b"fid-ctrl-client-v1" + server_nonce + client_nonce)
    server_proof = HMAC-SHA256(token, b"fid-ctrl-server-v1" + client_nonce + server_nonce)

computed with Python's standard hmac and hashlib modules (not the Rust code under test).
Python's HMAC is first checked against RFC 4231 test case 2 for SHA-256.

Run:          python fixtures/ctrl/make_auth_vectors.py
CI (verify):  python fixtures/ctrl/make_auth_vectors.py --check
"""

import hashlib
import hmac
import json
import sys
from pathlib import Path

CLIENT_LABEL = b"fid-ctrl-client-v1"
SERVER_LABEL = b"fid-ctrl-server-v1"

# RFC 4231, test case 2 (HMAC-SHA-256).
assert hmac.new(b"Jefe", b"what do ya want for nothing?", hashlib.sha256).hexdigest() == (
    "5bdcc146bf60754e6a042426089575c75a003f089d2739839dec58b964ec3843"
)


def derived(tag):
    """32 pseudo-random bytes, reproducible from a text tag."""
    return hashlib.sha256(b"fid-ctrl-auth-vectors/" + tag.encode()).digest()


CASES = [
    ("all_zero", bytes(32), bytes(32), bytes(32)),
    ("all_ff", b"\xff" * 32, b"\xff" * 32, b"\xff" * 32),
    ("counting", bytes(range(32)), bytes(range(32, 64)), bytes(range(64, 96))),
    ("nonces_swapped", bytes(range(32)), bytes(range(64, 96)), bytes(range(32, 64))),
    ("derived_1", derived("token-1"), derived("server-1"), derived("client-1")),
    ("derived_2", derived("token-2"), derived("server-2"), derived("client-2")),
    ("same_nonces", derived("token-3"), derived("nonce-3"), derived("nonce-3")),
]


def build():
    out = []
    for name, token, sn, cn in CASES:
        assert len(token) == len(sn) == len(cn) == 32
        out.append({
            "name": name,
            "token": token.hex(),
            "server_nonce": sn.hex(),
            "client_nonce": cn.hex(),
            "client_proof": hmac.new(token, CLIENT_LABEL + sn + cn, hashlib.sha256).hexdigest(),
            "server_proof": hmac.new(token, SERVER_LABEL + cn + sn, hashlib.sha256).hexdigest(),
        })
    doc = {
        "about": "AUTO.CTRL.AUTH AC-6 proof vectors; generated by make_auth_vectors.py (Python hmac/hashlib)",
        "client_label": CLIENT_LABEL.decode(),
        "server_label": SERVER_LABEL.decode(),
        "cases": out,
    }
    return json.dumps(doc, indent=2, sort_keys=True) + "\n"


def main():
    target = Path(__file__).with_name("auth-vectors.json")
    text = build()
    if "--check" in sys.argv[1:]:
        if target.read_text(encoding="utf-8") != text:
            print(f"{target} is out of date; run {Path(__file__).name}", file=sys.stderr)
            return 1
        print(f"{target.name}: ok")
        return 0
    target.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
