#!/usr/bin/env python3
"""Independent reference for the generated clippy.toml of KRN.NUM.LINT.TYPED.

The disallowed items below are written out by hand from the KNP-1 rule table of
spec/krn/num/lint/typed/NODE.md (REQ-001): every float method, collection type and macro with
a resolvable path, each with its rule ID as the reason. This script renders them in the format
the Design pins and writes expected-clippy.toml; the Rust test compares the crate's output to
it byte for byte.

Usage: python fixtures/knp1/typed/make_expected.py [--check]
Stdlib only; it never runs the Rust code.
"""

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent

FLOAT_LIBM = [
    "acos", "acosh", "asin", "asinh", "atan", "atan2", "atanh", "cbrt", "cos", "cosh", "exp", "exp2",
    "exp_m1", "hypot", "ln", "ln_1p", "log", "log10", "log2", "sin", "sin_cos", "sinh", "sqrt", "tan", "tanh",
]

METHODS = (
    [(f"{t}::mul_add", "KNP1-FMA") for t in ("f32", "f64")]
    + [(f"{t}::{m}", "KNP1-POW") for t in ("f32", "f64") for m in ("powf", "powi")]
    + [(f"{t}::{m}", "KNP1-LIBM") for t in ("f32", "f64") for m in FLOAT_LIBM]
    + [(f"{t}::{m}", "KNP1-MINMAX") for t in ("f32", "f64") for m in ("clamp", "max", "min")]
    + [
        ("std::fs::read", "KNP1-IO-FS"),
        ("std::fs::read_to_string", "KNP1-IO-FS"),
        ("std::fs::write", "KNP1-IO-FS"),
        ("std::time::Instant::now", "KNP1-CLOCK"),
        ("std::time::SystemTime::now", "KNP1-CLOCK"),
        ("std::env::var", "KNP1-ENV"),
        ("std::env::var_os", "KNP1-ENV"),
        ("std::env::vars", "KNP1-ENV"),
        ("std::process::Command::new", "KNP1-THREAD"),
        ("std::thread::spawn", "KNP1-THREAD"),
    ]
)

TYPES = [
    ("std::collections::HashMap", "KNP1-HASH"),
    ("std::collections::HashSet", "KNP1-HASH"),
    ("std::collections::hash_map::DefaultHasher", "KNP1-HASH"),
    ("std::collections::hash_map::RandomState", "KNP1-HASH"),
    ("std::fs::File", "KNP1-IO-FS"),
    ("std::net::TcpListener", "KNP1-IO-NET"),
    ("std::net::TcpStream", "KNP1-IO-NET"),
    ("std::net::UdpSocket", "KNP1-IO-NET"),
    ("std::time::Instant", "KNP1-CLOCK"),
    ("std::time::SystemTime", "KNP1-CLOCK"),
]

MACROS = [
    ("std::arch::is_aarch64_feature_detected", "KNP1-SIMD"),
    ("std::is_x86_feature_detected", "KNP1-SIMD"),
    ("std::env", "KNP1-ENV"),
    ("std::option_env", "KNP1-ENV"),
    ("std::include_bytes", "KNP1-IO-FS"),
    ("std::include_str", "KNP1-IO-FS"),
]


def render() -> str:
    out = ["# Generated by fid-knp1-lint (KRN.NUM.LINT.TYPED). Do not edit."]
    for key, items in (("disallowed-methods", METHODS), ("disallowed-types", TYPES), ("disallowed-macros", MACROS)):
        out.append(f"{key} = [")
        out.extend(f'    {{ path = "{p}", reason = "{r}" }},' for p, r in items)
        out.append("]")
    return "\n".join(out) + "\n"


def main() -> int:
    target = HERE / "expected-clippy.toml"
    text = render().encode("utf-8")
    if "--check" in sys.argv[1:]:
        if not target.exists() or target.read_bytes() != text:
            print(f"FAIL: {target} is stale; run without --check")
            return 1
        print("typed expected-clippy.toml: ok")
        return 0
    target.write_bytes(text)
    print(f"wrote {target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
