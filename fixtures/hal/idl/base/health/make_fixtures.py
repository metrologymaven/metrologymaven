#!/usr/bin/env python3
"""Deterministic fixture generator for HAL.IDL.BASE.HEALTH (CC-BY-4.0).

Generates fixtures/hal/idl/base/health/table.json directly from the Design
transition rules of spec/hal/idl/base/health/NODE.md.
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent

STATES = [
    "OFFLINE",
    "CONNECTING",
    "INITIALIZING",
    "WARMING_UP",
    "READY",
    "BUSY",
    "FAULT",
    "SAFETY_STOPPED",
    "MAINTENANCE",
    "INTERRUPTED",
]
ACTORS = ["Device", "Runtime"]


def build_table() -> dict[str, object]:
    triples: set[tuple[str, str, str]] = set()

    def add(f: str, t: str, by: str) -> None:
        assert f in STATES and t in STATES and by in ACTORS
        triples.add((f, t, by))

    add("OFFLINE", "CONNECTING", "Runtime")
    add("CONNECTING", "INITIALIZING", "Device")
    add("CONNECTING", "OFFLINE", "Runtime")
    add("INITIALIZING", "WARMING_UP", "Device")
    add("INITIALIZING", "READY", "Device")
    add("WARMING_UP", "READY", "Device")
    add("READY", "BUSY", "Device")
    add("BUSY", "READY", "Device")

    for s in ("CONNECTING", "INITIALIZING", "WARMING_UP", "READY", "BUSY"):
        add(s, "FAULT", "Device")
        add(s, "FAULT", "Runtime")

    for s in ("INITIALIZING", "WARMING_UP", "READY", "BUSY", "FAULT", "MAINTENANCE"):
        add(s, "SAFETY_STOPPED", "Device")

    add("SAFETY_STOPPED", "INITIALIZING", "Device")

    for s in ("OFFLINE", "CONNECTING", "INITIALIZING", "WARMING_UP", "READY", "FAULT"):
        add(s, "MAINTENANCE", "Device")
    add("OFFLINE", "MAINTENANCE", "Runtime")
    add("MAINTENANCE", "OFFLINE", "Device")
    add("MAINTENANCE", "OFFLINE", "Runtime")

    for s in ("CONNECTING", "INITIALIZING", "WARMING_UP", "READY", "BUSY"):
        add(s, "INTERRUPTED", "Runtime")
    add("INTERRUPTED", "CONNECTING", "Runtime")
    add("INTERRUPTED", "OFFLINE", "Runtime")

    add("FAULT", "OFFLINE", "Runtime")
    add("READY", "OFFLINE", "Runtime")

    state_idx = {s: i for i, s in enumerate(STATES)}
    actor_idx = {a: i for i, a in enumerate(ACTORS)}
    ordered = sorted(triples, key=lambda x: (state_idx[x[0]], state_idx[x[1]], actor_idx[x[2]]))

    return {
        "schema": "hal-health-transitions/v1",
        "license": "CC-BY-4.0",
        "states": STATES,
        "actors": ACTORS,
        "allowed": [{"from": f, "to": t, "by": b} for f, t, b in ordered],
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="Verify committed fixture matches generated bytes.")
    args = ap.parse_args()

    out = (json.dumps(build_table(), indent=2) + "\n").encode("utf-8")
    target = HERE / "table.json"

    if args.check:
        if not target.exists() or target.read_bytes() != out:
            print(f"DRIFT: {target}", file=sys.stderr)
            return 1
        return 0

    target.write_bytes(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
