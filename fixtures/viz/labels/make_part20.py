#!/usr/bin/env python3
"""Generate and verify synthetic fixture fixtures/viz/labels/part20/ for VIZ.OVERLAY.LABEL.MODEL.

License: CC-BY-4.0 (synthetic project with 20 comparison points, 20 SCAN deviation labels,
2 GD&T characteristics, 2 dimensions, and 2 non-labelable geometry/mesh elements).

Usage:
    python3 fixtures/viz/labels/make_part20.py
    python3 fixtures/viz/labels/make_part20.py --check
"""

from __future__ import annotations

import json
import sys
import uuid
from pathlib import Path

ROOT = Path(__file__).resolve().parent
PART20 = ROOT / "part20"

# Fixed project namespace UUIDv5 for deterministic synthetic IDs.
PROJECT_NS = uuid.UUID("7f5b4a2c-9d61-5c0e-8b3a-4102c9e7a101")


def elem_id(tag: str) -> str:
    return str(uuid.uuid5(PROJECT_NS, tag))


def build_files() -> dict[str, str]:
    elements: list[dict[str, str]] = []
    for i in range(1, 21):
        elements.append(
            {
                "id": elem_id(f"cp-{i:02d}"),
                "name": f"cp-{i:02d}",
                "type": "scan.comparison_point",
            }
        )
        elements.append(
            {
                "id": elem_id(f"dl-{i:02d}"),
                "name": f"dl-{i:02d}",
                "type": "scan.deviation_label",
            }
        )
    for i in (1, 2):
        elements.append(
            {
                "id": elem_id(f"char-{i:02d}"),
                "name": f"char-{i:02d}",
                "type": "gdt.characteristic",
            }
        )
        elements.append(
            {
                "id": elem_id(f"dim-{i:02d}"),
                "name": f"dim-{i:02d}",
                "type": "gdt.dimension",
            }
        )
    # Non-labelable elements for AC-2 error path.
    elements.append(
        {
            "id": elem_id("mesh-part"),
            "name": "mesh-part",
            "type": "scan.mesh",
        }
    )
    elements.append(
        {
            "id": elem_id("cad-body"),
            "name": "cad-body",
            "type": "geo.brep",
        }
    )

    project = {
        "format": "viz-label-fixture-project@1",
        "license": "CC-BY-4.0",
        "namespace": str(PROJECT_NS),
        "label_set_id": elem_id("label-set-default"),
        "elements": elements,
    }

    readme = (
        "# `fixtures/viz/labels/part20`\n\n"
        "Synthetic test project for `VIZ.OVERLAY.LABEL.MODEL` (CC-BY-4.0), generated by\n"
        "`fixtures/viz/labels/make_part20.py`.\n\n"
        "Contains 20 comparison points (`cp-01`..`cp-20`, `scan.comparison_point`),\n"
        "20 SCAN deviation labels (`dl-01`..`dl-20`, `scan.deviation_label`),\n"
        "2 GD&T characteristics (`char-01`..`char-02`, `gdt.characteristic`),\n"
        "2 dimensions (`dim-01`..`dim-02`, `gdt.dimension`), and 2 non-labelable elements\n"
        "(`mesh-part` `scan.mesh` and `cad-body` `geo.brep`) for AC-1..AC-5.\n"
    )

    return {
        "project.json": json.dumps(project, indent=2, sort_keys=True, ensure_ascii=False) + "\n",
        "README.md": readme,
    }


def main() -> int:
    files = build_files()
    if "--check" in sys.argv[1:]:
        errors: list[str] = []
        for rel, want in sorted(files.items()):
            p = PART20 / rel
            if not p.is_file():
                errors.append(f"missing fixture file: part20/{rel}")
                continue
            if p.read_text(encoding="utf-8") != want:
                errors.append(f"fixture drift: part20/{rel}")
        if PART20.is_dir():
            for p in sorted(PART20.rglob("*")):
                if p.is_file():
                    rel = p.relative_to(PART20).as_posix()
                    if rel not in files:
                        errors.append(f"unexpected extra file: part20/{rel}")
        if errors:
            for e in errors:
                print(e, file=sys.stderr)
            return 1
        return 0

    PART20.mkdir(parents=True, exist_ok=True)
    for rel, content in sorted(files.items()):
        (PART20 / rel).write_text(content, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
