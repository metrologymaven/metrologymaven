#!/usr/bin/env python3
"""Generate and verify fixtures/viz/capture/policy-matrix.csv for VIZ.CAPTURE.REC.POLICY AC-1.

License: CC-BY-4.0. Synthetic matrix written from the leaf's rules, independent of the Rust code:

- REQ-002: ViewTrack, ViewportVideo and WindowVideo are refused while capture.recording is
  forbidden; WindowVideo while capture.window_capture is forbidden; Screenshot while
  capture.screenshots is forbidden; everything else is allowed.
- REQ-003: mandated is true exactly while capture.recording is mandated.
- REQ-004: retain_until(2026-11-17T10:00:00Z) is the start plus capture.retention_days days,
  or none when the value is 0.
- Fail closed (builder brief and PR): a value that cannot be used is unknown, never the
  default. Every capture that depends on an unknown key is refused with cause "unknown"; an
  unknown capture.recording is not mandated; an unknown retention has no retain_until and
  refuses the recording media. Keys are checked in the order recording, window_capture,
  retention_days (Screenshot: screenshots only); the first refusal is reported.

Each key takes the state "default" (nothing stored), one of its values, or "invalid" (a value
stored in machine scope that fails the key's schema: the string "maybe", or 36501 days).
5 x 4 x 4 x 5 key states x 4 media kinds = 1600 rows.

Usage:
    python3 fixtures/viz/capture/make_policy_matrix.py
    python3 fixtures/viz/capture/make_policy_matrix.py --check
"""

from __future__ import annotations

import sys
from datetime import datetime, timedelta, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent
CSV_PATH = ROOT / "policy-matrix.csv"

RECORDING = ("default", "allowed", "forbidden", "mandated", "invalid")
WINDOW_CAPTURE = ("default", "allowed", "forbidden", "invalid")
SCREENSHOTS = ("default", "allowed", "forbidden", "invalid")
RETENTION = ("default", "0", "30", "36500", "invalid")
KINDS = ("screenshot", "view_track", "viewport_video", "window_video")

DEFAULTS = {"recording": "allowed", "window_capture": "allowed", "screenshots": "allowed", "retention": "0"}
START = datetime(2026, 11, 17, 10, 0, 0, tzinfo=timezone.utc)


def effective(state: str, key: str) -> str | None:
    """The value the policy uses: the default when nothing is stored, None when unknown."""
    if state == "invalid":
        return None
    if state == "default":
        return DEFAULTS[key]
    return state


def decide(rec: str | None, win: str | None, shot: str | None, ret: str | None, kind: str) -> str:
    if kind == "screenshot":
        if shot is None:
            return "forbid:capture.screenshots:unknown"
        if shot == "forbidden":
            return "forbid:capture.screenshots:forbidden"
        return "allow"
    if rec is None:
        return "forbid:capture.recording:unknown"
    if rec == "forbidden":
        return "forbid:capture.recording:forbidden"
    if kind == "window_video":
        if win is None:
            return "forbid:capture.window_capture:unknown"
        if win == "forbidden":
            return "forbid:capture.window_capture:forbidden"
    if ret is None:
        return "forbid:capture.retention_days:unknown"
    return "allow"


def retain_until(ret: str | None) -> str:
    if ret is None:
        return "unknown"
    days = int(ret)
    if days == 0:
        return "none"
    return (START + timedelta(days=days)).strftime("%Y-%m-%dT%H:%M:%SZ")


def render_csv() -> str:
    n = len(RECORDING) * len(WINDOW_CAPTURE) * len(SCREENSHOTS) * len(RETENTION) * len(KINDS)
    lines = [
        "# Recording-policy matrix for VIZ.CAPTURE.REC.POLICY AC-1 (CC-BY-4.0); generated by make_policy_matrix.py.",
        "# State per key: default (nothing stored), a value, or invalid (machine value failing the schema).",
        f"# {len(RECORDING)} x {len(WINDOW_CAPTURE)} x {len(SCREENSHOTS)} x {len(RETENTION)} states x {len(KINDS)} kinds = {n} rows; retain_until for start 2026-11-17T10:00:00Z.",
        "recording,window_capture,screenshots,retention_days,kind,decision,mandated,retain_until",
    ]
    for rec in RECORDING:
        for win in WINDOW_CAPTURE:
            for shot in SCREENSHOTS:
                for ret in RETENTION:
                    r = effective(rec, "recording")
                    w = effective(win, "window_capture")
                    s = effective(shot, "screenshots")
                    t = effective(ret, "retention")
                    mandated = "true" if r == "mandated" else "false"
                    for kind in KINDS:
                        lines.append(
                            f"{rec},{win},{shot},{ret},{kind},{decide(r, w, s, t, kind)},{mandated},{retain_until(t)}"
                        )
    return "\n".join(lines) + "\n"


def main() -> int:
    want = render_csv()
    if "--check" in sys.argv[1:]:
        if not CSV_PATH.is_file():
            print(f"missing fixture: {CSV_PATH.name}", file=sys.stderr)
            return 1
        got = CSV_PATH.read_bytes().decode("utf-8")
        if got != want:
            print(f"{CSV_PATH.name} is stale; rerun make_policy_matrix.py", file=sys.stderr)
            return 1
        print(f"{CSV_PATH.name}: ok")
        return 0
    CSV_PATH.write_bytes(want.encode("utf-8"))
    print(f"wrote {CSV_PATH.name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
