#!/usr/bin/env python3
"""Generate and check RPT.OUTPUT.META fixtures (`resolved_small.json` and `resolved_small.meta.json`).

Synthetic report fixture, CC-BY-4.0, authored in-project using Python stdlib only.
Usage:
    python fixtures/rpt/output/make_meta_fixtures.py
    python fixtures/rpt/output/make_meta_fixtures.py --check
"""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path

OUT_DIR = Path(__file__).resolve().parent


def jcs(v) -> bytes:
    return json.dumps(v, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode("utf-8")


def sha256_prefixed(b: bytes) -> str:
    return "sha256:" + hashlib.sha256(b).hexdigest()


def build_fixtures() -> dict[str, bytes]:
    template_id = "019a9f00-0001-7000-8000-000000000001"
    template_digest = sha256_prefixed(b"fixture:tmpl:char-table@1")
    head_digest = sha256_prefixed(b"fixture:resolved_small:head")

    content = {
        "pages": [
            {
                "blocks": [
                    {
                        "frame": None,
                        "id": "019a9f00-0001-7000-8000-000000000101",
                        "kind": "text",
                        "kind_version": "1",
                        "payload": {
                            "key": "rpt.starter.char_table.heading",
                            "schema": "resolved_text@1",
                            "text": "Characteristic Table",
                        },
                    }
                ],
                "id": "019a9f00-0001-7000-8000-000000000011",
            }
        ],
        "provenance": {
            "formatters": [
                {"id": "fmt.angle@1", "version": "1"},
                {"id": "fmt.length@1", "version": "1"},
            ],
            "head": head_digest,
            "kernel_version": "0.1.0",
            "locale": "en",
            "locale_release": "i18n-locale@1",
            "template": {
                "builtin": True,
                "digest": template_digest,
                "id": template_id,
                "version": "1",
            },
            "units": None,
        },
        "schema": "resolved_report@1",
        "schema_version": "1",
        "warnings": [],
    }
    report_digest = sha256_prefixed(jcs(content))
    resolved = dict(content, digest=report_digest)

    meta = {
        "formatters": [
            {"id": "fmt.angle@1", "version": "1"},
            {"id": "fmt.length@1", "version": "1"},
        ],
        "kernel_version": "0.1.0",
        "renderer": {"id": "pdf", "version": "1.0.0"},
        "report_digest": report_digest,
        "schema": "export_meta@1",
        "template": {"id": template_id, "version": "1"},
    }

    return {
        "resolved_small.json": jcs(resolved),
        "resolved_small.meta.json": jcs(meta),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate or verify RPT.OUTPUT.META fixtures.")
    parser.add_argument("--check", action="store_true", help="Verify fixtures match generated bytes.")
    args = parser.parse_args()

    fixtures = build_fixtures()
    mismatches: list[str] = []
    for name, expected in sorted(fixtures.items()):
        path = OUT_DIR / name
        if args.check:
            if not path.exists() or path.read_bytes() != expected:
                mismatches.append(name)
        else:
            path.write_bytes(expected)

    if args.check:
        if mismatches:
            print("RPT.OUTPUT.META fixture mismatch:", ", ".join(mismatches), file=sys.stderr)
            return 1
        print(f"RPT.OUTPUT.META fixtures OK ({len(fixtures)} files)")
    else:
        print(f"Wrote {len(fixtures)} RPT.OUTPUT.META fixtures to {OUT_DIR}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
