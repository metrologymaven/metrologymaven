from __future__ import annotations

import argparse
import hashlib
import json
import struct
import sys
import zlib
from pathlib import Path

OUT_DIR = Path(__file__).resolve().parent


def make_png(width: int, height: int) -> bytes:
    """Minimal valid grayscale PNG with exact IHDR dimensions and zlib IDAT."""
    def chunk(ctype: bytes, data: bytes) -> bytes:
        crc = zlib.crc32(ctype + data) & 0xFFFFFFFF
        return struct.pack(">I", len(data)) + ctype + data + struct.pack(">I", crc)

    ihdr = struct.pack(">IIBBBBB", width, height, 8, 0, 0, 0, 0)
    # Scanlines: filter byte 0 + width zero bytes per row.
    raw = (b"\x00" + bytes(width)) * height
    idat = zlib.compress(raw, level=9)
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", ihdr) + chunk(b"IDAT", idat) + chunk(b"IEND", b"")


def make_jpeg(width: int, height: int) -> bytes:
    """Minimal valid JPEG header structure: SOI + APP0(JFIF) + SOF0(dimensions) + EOI."""
    soi = b"\xff\xd8"
    app0_body = b"JFIF\x00\x01\x01\x00\x00\x01\x00\x01\x00\x00"
    app0 = b"\xff\xe0" + struct.pack(">H", len(app0_body) + 2) + app0_body
    # SOF0: precision(8), height, width, 1 component (id=1, samp=0x11, qt=0).
    sof0_body = struct.pack(">BHHBBBB", 8, height, width, 1, 1, 0x11, 0)
    sof0 = b"\xff\xc0" + struct.pack(">H", len(sof0_body) + 2) + sof0_body
    eoi = b"\xff\xd9"
    return soi + app0 + sof0 + eoi


def make_gif() -> bytes:
    """Minimal valid 1x1 GIF89a image (unsupported type for AC-3)."""
    return (
        b"GIF89a"
        b"\x01\x00\x01\x00"  # 1x1
        b"\x80\x00\x00"      # global colour table (2 colours)
        b"\x00\x00\x00\xff\xff\xff"
        b"\x2c\x00\x00\x00\x00\x01\x00\x01\x00\x00"
        b"\x02\x02\x44\x01\x00"
        b"\x3b"
    )


def sha256_prefixed(data: bytes) -> str:
    return "sha256:" + hashlib.sha256(data).hexdigest()


def build_fixtures() -> dict[str, bytes]:
    png = make_png(64, 48)
    jpg = make_jpeg(32, 24)
    gif = make_gif()
    manifest = {
        "schema": "fid-rpt-images-fixture/1",
        "files": {
            "sample.png": {
                "mime": "image/png",
                "width_px": 64,
                "height_px": 48,
                "bytes": len(png),
                "sha256": sha256_prefixed(png),
            },
            "sample.jpg": {
                "mime": "image/jpeg",
                "width_px": 32,
                "height_px": 24,
                "bytes": len(jpg),
                "sha256": sha256_prefixed(jpg),
            },
            "sample.gif": {
                "mime": "image/gif",
                "bytes": len(gif),
                "sha256": sha256_prefixed(gif),
            },
        },
        "size_cases": {
            "two_mib_png_bytes": 2 * 1024 * 1024,
            "sixty_mib_png_bytes": 60 * 1024 * 1024,
        },
    }
    manifest_bytes = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode("utf-8")
    return {
        "sample.png": png,
        "sample.jpg": jpg,
        "sample.gif": gif,
        "manifest.json": manifest_bytes,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate or verify RPT.MODEL.BLOCKS.TEXT image fixtures.")
    parser.add_argument("--check", action="store_true", help="Verify fixtures match generated bytes.")
    args = parser.parse_args()

    fixtures = build_fixtures()
    mismatches: list[str] = []
    for name, expected in sorted(fixtures.items()):
        path = OUT_DIR / name
        if args.check:
            if not path.exists() or path.read_bytes() != expected:
                mismatches.append(name)
        else:
            path.write_bytes(expected)

    if args.check:
        if mismatches:
            print("RPT.MODEL.BLOCKS.TEXT image fixture mismatch:", ", ".join(mismatches), file=sys.stderr)
            return 1
        print(f"RPT.MODEL.BLOCKS.TEXT image fixtures OK ({len(fixtures)} files)")
    else:
        print(f"Wrote {len(fixtures)} RPT.MODEL.BLOCKS.TEXT image fixtures to {OUT_DIR}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
