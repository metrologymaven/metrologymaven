#!/usr/bin/env python3
"""Writes crates/fid-pkg/src/casefold_table.rs: full Unicode case folding (CaseFolding.txt
statuses C and F, as Python's str.casefold applies them), one entry per code point whose
folding differs from itself.

TRUST.PKG.MANIFEST and TRUST.PKG.READER refuse two package paths that are equal after
case folding. The table is pinned in the repository so the result never depends on the Rust
toolchain's or the running Python's Unicode version.

--check does not need the same Unicode version as the one that wrote the table: Unicode's
case-folding stability policy guarantees that the folding of an assigned character never
changes. So it checks that every code point the running Python folds is in the table with the
same folding, and that every table entry the running Python knows (assigned in its version)
folds the same way. Entries for characters newer than the running Python are skipped.

CC-BY-4.0 project data. Stdlib only.

Run:  python fixtures/pkg/make_casefold_table.py          (writes the table)
      python fixtures/pkg/make_casefold_table.py --check  (fails if the table disagrees)
"""

import re
import sys
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "crates" / "fid-pkg" / "src" / "casefold_table.rs"


def folds():
    out = {}
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        f = c.casefold()
        if f != c:
            out[cp] = f
    return out


def rust_str(s):
    return '"' + "".join("\\u{%x}" % ord(ch) for ch in s) + '"'


def render(table):
    growth = max(len(f.encode("utf-8")) / len(chr(cp).encode("utf-8")) for cp, f in table.items())
    assert growth <= 3, growth
    lines = [
        "// Generated by fixtures/pkg/make_casefold_table.py from Unicode "
        + unicodedata.unidata_version + " (Python " + sys.version.split()[0] + "). Do not edit.",
        "//! Full Unicode case folding (CaseFolding.txt statuses C and F): every code point whose",
        "//! folding differs from itself, sorted by code point.",
        "",
        "/// Unicode version the table was generated from.",
        'pub const UNICODE_VERSION: &str = "' + unicodedata.unidata_version + '";',
        "",
        "/// `(code point, folding)`, sorted by code point.",
        "#[rustfmt::skip]",
        "pub(crate) static FOLD: [(char, &str); %d] = [" % len(table),
    ]
    for cp in sorted(table):
        lines.append("    ('\\u{%x}', %s)," % (cp, rust_str(table[cp])))
    lines.append("];")
    return "\n".join(lines) + "\n"


ENTRY = re.compile(r"^    \('\\u\{([0-9a-f]+)\}', \"((?:\\u\{[0-9a-f]+\})+)\"\),$")


def parse(text):
    table = {}
    for line in text.splitlines():
        m = ENTRY.match(line)
        if m:
            table[int(m.group(1), 16)] = "".join(chr(int(h, 16)) for h in re.findall(r"[0-9a-f]+", m.group(2)))
    return table


def main():
    if "--check" not in sys.argv[1:]:
        OUT.write_text(render(folds()), encoding="utf-8", newline="\n")
        print("wrote", OUT.relative_to(ROOT).as_posix())
        return 0
    if not OUT.exists():
        print("missing", OUT)
        return 1
    committed = parse(OUT.read_text(encoding="utf-8"))
    errors = []
    if not committed:
        errors.append("no entries")
    keys = list(committed)
    if keys != sorted(keys):
        errors.append("entries not sorted")
    running = folds()
    for cp, f in running.items():
        if committed.get(cp) != f:
            errors.append("U+%04X: running Python folds to %r, table has %r" % (cp, f, committed.get(cp)))
    for cp, f in committed.items():
        if unicodedata.category(chr(cp)) == "Cn":
            continue  # newer than the running Python's Unicode version
        if chr(cp).casefold() != f:
            errors.append("U+%04X: table folds to %r, running Python to %r" % (cp, f, chr(cp).casefold()))
    if errors:
        print("\n".join(errors[:20]))
        return 1
    print("case-fold table agrees with Unicode", unicodedata.unidata_version, "(%d entries)" % len(committed))
    return 0


if __name__ == "__main__":
    sys.exit(main())
