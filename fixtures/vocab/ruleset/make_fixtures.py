#!/usr/bin/env python3
"""Deterministic fixture generator for ECO.RULES.VOCAB.RULESET (CC-BY-4.0).

Generates:
  - fixtures/vocab/ruleset/regulated-terms.txt: regulated-term list (QUAL.MATRIX fixture)
  - fixtures/vocab/ruleset/sample-units.jsonl: sample product units for AC-4 & AC-5
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent


def make_regulated_terms() -> bytes:
    lines = [
        "# Regulated claim terms and inflections (QUAL.MATRIX fixture, CC-BY-4.0).",
        "certify",
        "certifies",
        "certified",
        "certifying",
        "certification",
        "compliant",
        "conformant",
        "validate",
        "validates",
        "validated",
        "validating",
        "traceable",
        "traceability",
    ]
    return ("\n".join(lines) + "\n").encode("utf-8")


def make_sample_units() -> bytes:
    units = [
        {
            "id": "io.import_pcdmis.title",
            "file": "ui/import.ftl",
            "line": 10,
            "text": "Import PC-DMIS program format",
            "links": [],
        },
        {
            "id": "ui.home.tagline",
            "file": "ui/home.ftl",
            "line": 4,
            "text": "Open PC-DMIS files without conversion",
            "links": [],
        },
        {
            "id": "gdt.decision.conforms",
            "file": "ui/gdt.ftl",
            "line": 22,
            "text": "Conforms (rule ISO 14253-1:2017 default)",
            "links": [],
        },
    ]
    return ("\n".join(json.dumps(u, sort_keys=True) for u in units) + "\n").encode("utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="Verify committed fixtures match generated bytes.")
    args = ap.parse_args()

    outputs = {
        HERE / "regulated-terms.txt": make_regulated_terms(),
        HERE / "sample-units.jsonl": make_sample_units(),
    }

    if args.check:
        ok = True
        for path, expected in outputs.items():
            if not path.exists() or path.read_bytes() != expected:
                print(f"DRIFT: {path}", file=sys.stderr)
                ok = False
        return 0 if ok else 1

    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
