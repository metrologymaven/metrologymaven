#!/usr/bin/env python3
"""Independent reference for ECO.REL.PROC.RUNBOOK (CC-BY-4.0 project data).

Writes the hand-written fixture directories under fixtures/rel/runbook/
(ok, two-humans, orphan-job, missing-gate, drift) and renders RUNBOOK.md for each of them
and for the repository's real release/ directory, with a renderer written here from the
rendering rules below (not by running the Rust code). `cargo xtask rel runbook-check`
must accept every RUNBOOK.md this script writes (except the `drift` one, which carries one
hand edit), so the Rust renderer is checked against this one in CI.

Rendering rules (shared with crates/fid-xtask/src/rel/runbook.rs):
- line 1: the HEADER below, then one empty line;
- the preamble with CRLF turned into LF and trailing spaces, tabs, CRs and LFs removed,
  then one empty line (nothing at all if the preamble is empty);
- "## Steps", an empty line, and a table with one row per step:
  | n | `id` | title | `performer` | `job` or - | `g1`, `g2` or - | channels | status |
- an empty line, "## Step details", and per step: an empty line,
  "### n. `id`: title", an empty line, the bullets Performer, Workflow job, Gates,
  Channels, Status and (if present) Tool, then (if present) an empty line and the notes
  with CRLF turned into LF and leading/trailing spaces, tabs, CRs and LFs removed;
- every line ends in LF, and the file ends in exactly one LF.

Run:  python fixtures/rel/runbook/make_fixtures.py          (write)
      python fixtures/rel/runbook/make_fixtures.py --check  (verify, write nothing)
"""

import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
HERE = Path(__file__).resolve().parent

HEADER = (
    "<!-- Generated by `cargo xtask rel runbook-render` from runbook.toml and "
    "RUNBOOK.preamble.md. Do not edit this file: edit those two and render again. -->\n"
)
WS = " \t\r\n"


def render(steps, preamble):
    out = [HEADER, "\n"]
    pre = preamble.replace("\r\n", "\n").rstrip(WS)
    if pre:
        out += [pre, "\n\n"]
    out.append("## Steps\n\n")
    out.append("| # | Step | Title | Performer | Job | Gates | Channels | Status |\n")
    out.append("|---|---|---|---|---|---|---|---|\n")

    def job(s):
        return f"`{s['job']}`" if s.get("job") else "-"

    def gates(s):
        return ", ".join(f"`{g}`" for g in s.get("gates", [])) or "-"

    def chans(s):
        return ", ".join(s["channels"])

    for i, s in enumerate(steps, 1):
        out.append(
            f"| {i} | `{s['id']}` | {s['title']} | `{s['performer']}` | {job(s)} | "
            f"{gates(s)} | {chans(s)} | {s['status']} |\n"
        )
    out.append("\n## Step details\n")
    for i, s in enumerate(steps, 1):
        out.append(f"\n### {i}. `{s['id']}`: {s['title']}\n\n")
        out.append(f"- Performer: `{s['performer']}`\n")
        out.append(f"- Workflow job: {job(s)}\n")
        out.append(f"- Gates: {gates(s)}\n")
        out.append(f"- Channels: {chans(s)}\n")
        out.append(f"- Status: {s['status']}\n")
        if s.get("tool"):
            out.append(f"- Tool: `{s['tool']}`\n")
        notes = s.get("notes", "").replace("\r\n", "\n").strip(WS)
        if notes:
            out.append(f"\n{notes}\n")
    return "".join(out)


def toml_str(s):
    # ASCII-only fixture text: a JSON string is a valid TOML basic string.
    assert s.isascii()
    return json.dumps(s)


def runbook_toml(steps):
    lines = ["# Hand-written fixture for ECO.REL.PROC.RUNBOOK (CC-BY-4.0).", ""]
    for s in steps:
        lines.append("[[step]]")
        for key in ("id", "title", "performer", "job"):
            if key in s:
                lines.append(f"{key} = {toml_str(s[key])}")
        lines.append("gates = [" + ", ".join(toml_str(g) for g in s["gates"]) + "]")
        lines.append("channels = [" + ", ".join(toml_str(c) for c in s["channels"]) + "]")
        for key in ("status", "tool", "notes"):
            if key in s:
                lines.append(f"{key} = {toml_str(s[key])}")
        lines.append("")
    return "\n".join(lines)


def gates_toml(ids):
    lines = ["# Hand-written fixture for ECO.REL.PROC.RUNBOOK (CC-BY-4.0).", ""]
    for g in ids:
        lines += ["[[gate]]", f"id = {toml_str(g)}", f"producer = {toml_str('FIXTURE')}", ""]
    return "\n".join(lines)


def workflow_yml(jobs):
    lines = [
        "# Hand-written fixture for ECO.REL.PROC.RUNBOOK (CC-BY-4.0).",
        "name: release",
        "",
        "on:",
        "  push:",
        "    tags: ['v*']",
        "",
        "jobs:",
    ]
    for j in jobs:
        lines += [
            f"  {j}:",
            "    # a comment inside a job",
            "    runs-on: ubuntu-latest",
            "    steps:",
            "      - run: |",
            "          echo step",
            "          echo done",
        ]
    lines += ["", "permissions:", "  contents: read", ""]
    return "\n".join(lines)


ALL = ["nightly", "beta", "stable", "lts"]
REL = ["beta", "stable", "lts"]

OK_STEPS = [
    dict(id="tag-validate", title="Validate the tag", performer="ci", job="tag-validate",
         gates=[], channels=ALL, status="available", tool="cargo xtask rel version-check",
         notes="Reads the tag from its argument.\nNever creates tags.\n"),
    dict(id="vuln-gate", title="Vulnerability gate", performer="ci", job="vuln-gate",
         gates=["qual-sbom"], channels=ALL, status="planned"),
    dict(id="redteam-verdict", title="Red-team verdict", performer="ci", job="redteam-verdict",
         gates=["agent-redteam"], channels=REL, status="planned",
         notes="  Planned: AGENT.REDTEAM.  "),
    dict(id="sign-approval", title="Approve signing", performer="role:release-approver",
         gates=[], channels=REL, status="planned"),
    dict(id="sums", title="Write SHA256SUMS", performer="ci", job="sums",
         gates=[], channels=ALL, status="available", tool="cargo xtask rel sums"),
    dict(id="publish", title="Publish", performer="ci", job="publish",
         gates=[], channels=ALL, status="planned"),
]
OK_GATES = ["qual-sbom", "agent-redteam"]
OK_JOBS = ["tag-validate", "vuln-gate", "redteam-verdict", "sums", "publish"]
PREAMBLE = "# Fixture runbook\n\nA hand-written preamble that ends in extra empty lines.\n\n\n"


def two_humans():
    steps = [dict(s) for s in OK_STEPS]
    steps[-1]["performer"] = "role:maintainer"
    return steps


CASES = {
    # name: (steps, gate ids, workflow jobs, drift edit)
    "ok": (OK_STEPS, OK_GATES, OK_JOBS, False),
    "two-humans": (two_humans(), OK_GATES, OK_JOBS, False),
    "orphan-job": (OK_STEPS, OK_GATES, OK_JOBS + ["upload-extra"], False),
    "missing-gate": (OK_STEPS, ["qual-sbom"], OK_JOBS, False),
    "drift": (OK_STEPS, OK_GATES, OK_JOBS, True),
}


def outputs():
    files = {}
    for name, (steps, gate_ids, jobs, drift) in CASES.items():
        d = HERE / name
        md = render(steps, PREAMBLE)
        if drift:
            # One hand edit, as a person might make it.
            md = md.replace("| Vulnerability gate |", "| Vulnerability gate (edited) |", 1)
        files[d / "runbook.toml"] = runbook_toml(steps)
        files[d / "gates.toml"] = gates_toml(gate_ids)
        files[d / "release-workflow.yml"] = workflow_yml(jobs)
        files[d / "RUNBOOK.preamble.md"] = PREAMBLE
        files[d / "RUNBOOK.md"] = md
    rel = ROOT / "release"
    real = tomllib.loads((rel / "runbook.toml").read_text(encoding="utf-8"))
    preamble = (rel / "RUNBOOK.preamble.md").read_bytes().decode("utf-8")
    files[rel / "RUNBOOK.md"] = render(real["step"], preamble)
    return files


def main():
    check = "--check" in sys.argv[1:]
    stale = []
    for path, text in outputs().items():
        data = text.encode("utf-8")
        if check:
            if not path.exists() or path.read_bytes() != data:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if stale:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}")
        print("run: python fixtures/rel/runbook/make_fixtures.py")
        return 1
    print("runbook fixtures: ok" if check else "runbook fixtures: written")
    return 0


if __name__ == "__main__":
    sys.exit(main())
