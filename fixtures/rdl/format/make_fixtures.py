def public_view(rec):
    digest = sha(canon(rec))
    if rec["tier"] == "B" or rec["visibility"] == "blind":
        return {"aim": rec["aim"], "digest": digest, "id": rec["id"]}
    if rec["visibility"] != "public" or rec["licence"] not in REDISTRIBUTABLE:
        return {
            "aim": rec["aim"],
            "digest": digest,
            "id": rec["id"],
            "inputs": [{"digest": i["digest"]} for i in rec["inputs"]],
            "licence": rec["licence"],
            "provenance": {"source": rec["provenance"]["source"]},
            "reference_digest": sha(canon(rec["reference"])),
            "schema": rec["schema"],
            "tier": rec["tier"],
            "visibility": "reference_only",
        }
    full = dict(rec)
    full["digest"] = digest
    return full


def envelope(command, result):
    return {"command_id": command, "envelope_version": 1, "outcome": "computed", "result": result}


BASE = "g_line_0001.json"


def mutate(fn):
    rec = copy.deepcopy(VALID[BASE])
    fn(rec)
    return rec


def setp(path, value):
    def f(rec):
        cur = rec
        for k in path[:-1]:
            cur = cur[k]
        cur[path[-1]] = value

    return f


def delp(path):
    def f(rec):
        cur = rec
        for k in path[:-1]:
            cur = cur[k]
        del cur[path[-1]]

    return f


def chain(*fns):
    def f(rec):
        for g in fns:
            g(rec)

    return f


def nest(depth):
    v = []
    for _ in range(depth - 1):
        v = [v]
    return v


