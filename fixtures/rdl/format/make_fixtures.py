def canon(v):
    return json.dumps(v, sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def sha(text):
    data = text if isinstance(text, bytes) else text.encode("utf-8")
    return "sha256:" + hashlib.sha256(data).hexdigest()


def hx(x):
    return "0x" + format(struct.unpack(">Q", struct.pack(">d", x))[0], "016x")


def blob(name):
    """Digest of a synthetic blob; the blob bytes themselves are not part of the record."""
    return sha(f"synthetic rdl fixture blob: {name}\n")


def out(name, kind, value, unc, dec=None):
    o = {"name": name, "kind": kind, "value_hex": hx(value), "test_uncertainty_hex": hx(unc)}
    if dec is not None:
        o["value_dec"] = dec
    return o


