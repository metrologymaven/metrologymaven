"""Reference generator for the UNC.RDL.FORMAT fixtures (CC-BY-4.0 project data).

Every record here is small and synthetic: no third-party dataset is used or imitated
(D-038 is open). The X and B records only *declare* restricted licences
(LicenseRef-Synthetic-*) so the redaction rules have something to bite on.

Writes, next to this script:

- valid/*.json      one record per tier (two for tier G), pretty-printed (not canonical);
- invalid/*.json    variants that must fail; file name `<field>--<code>[--<note>].json`;
- digests.txt       `<file> <sha256:...>` per valid record;
- expected/*.public.json        canonical public view of each valid record;
- expected/list-tier-g.json     canonical envelope of `fid rdl list-dataset --tier G --json`;
- expected/show-tier-b.json     canonical envelope of `fid rdl show-dataset --id <B id> --json`;
- format-chars.txt  the Unicode 16.0 Cf ranges free text refuses (`<lo> <hi>` hex per line).

Expected values follow the rules pinned in spec/unc/rdl/format/NODE.md (Design), computed
here independently of the Rust code:

- canonical JSON is RFC 8785; every value is a string, a small integer, an array or an
  object with ASCII keys, so json.dumps(sort_keys, no whitespace, ensure_ascii=False) is
  exactly RFC 8785 (non-ASCII such as the micro sign stays raw UTF-8);
- the dataset digest is SHA-256 over the canonical record (which has no `digest` key);
- floats are "0x" + 16 lower-case hex digits of their IEEE 754 binary64 bits;
- public view: tier B -> {aim, digest, id}; reference_only (or a licence outside the
  redistributable list) -> {aim, digest, id, inputs:[{digest}], licence,
  provenance:{source}, reference_digest, schema, tier, visibility:"reference_only"} with
  reference_digest = SHA-256 of the canonical `reference` object; otherwise the record
  plus `digest`.

Stdlib only. Run:  python fixtures/rdl/format/make_fixtures.py [--check]
"""

