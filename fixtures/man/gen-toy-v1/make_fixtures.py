# A minimal WASI command module: _start writes fixed bytes to fd 1 with fd_write and returns
# (exit 0). Memory: iovec {ptr 16, len n} at 0, nwritten at 8, the bytes at 16.


def uleb(n):
    out = bytearray()
    while True:
        b = n & 0x7F
        n >>= 7
        if n:
            out.append(b | 0x80)
        else:
            out.append(b)
            return bytes(out)


def vec(items):
    return uleb(len(items)) + b"".join(items)


def name(s):
    b = s.encode("ascii")
    return uleb(len(b)) + b


def section(sid, body):
    return bytes([sid]) + uleb(len(body)) + body


def wasm_writer(payload):
    i32 = 0x7F
    types = vec([bytes([0x60, 4, i32, i32, i32, i32, 1, i32]), bytes([0x60, 0, 0])])
    imports = vec([name("wasi_snapshot_preview1") + name("fd_write") + bytes([0x00, 0x00])])
    funcs = vec([bytes([0x01])])
    memory = vec([bytes([0x00, 0x01])])
    exports = vec([name("memory") + bytes([0x02, 0x00]), name("_start") + bytes([0x00, 0x01])])
    code = bytes([0x00,  # no locals
                  0x41, 0x01, 0x41, 0x00, 0x41, 0x01, 0x41, 0x08,  # fd 1, iovs 0, 1 iovec, nwritten 8
                  0x10, 0x00, 0x1A, 0x0B])  # call fd_write, drop errno, end
    codes = vec([uleb(len(code)) + code])
    image = len(payload).to_bytes(4, "little")
    image = (16).to_bytes(4, "little") + image + bytes(8) + payload
    data = vec([bytes([0x00, 0x41, 0x00, 0x0B]) + uleb(len(image)) + image])
    return (b"\x00asm\x01\x00\x00\x00" + section(1, types) + section(2, imports) + section(3, funcs)
            + section(5, memory) + section(7, exports) + section(10, codes) + section(11, data))


def self_report(core_digest):
    """The canonical KernelResult envelope of the self-report query (KRN.MAN.KCI field rules)."""
    output = core_digest.encode("ascii")
    return canon({
        "algorithm": QUERY,
        "input_digests": [],
        "output": output.hex(),
        "output_digest": sha(output),
        "params_digest": sha(b""),
    })


