def facade_selftest_digest():
    rows = []
    for line in NUM_SELFTEST.read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        f = line.split(" ")
        rows.append({"inputs": f[4], "name": f[0], "outputs": f[5]})
    assert [r["name"] for r in rows] == ["sqrt", "sin", "cos", "tan", "asin", "acos", "atan", "atan2",
                                         "exp", "ln", "hypot", "cbrt"]
    return sha(canon({"functions": rows, "inputs_per_fn": "10000"}))


def build():
    out = {}
    files = dict(impl.FILES)
    files[CONSTANT] = constant(None)
    for rel, data in files.items():
        out["ws/" + rel] = data
    tracked = sorted(files, key=lambda n: n.encode("utf-8"))
    out["tracked-files.txt"] = "".join(n + "\n" for n in tracked).encode("utf-8")
    meta = impl.metadata()
    out["metadata.json"] = meta
    out.update(CARDS)
    out["wasm-runtime.toml"] = RUNTIME
    out["wasm-imports.allow"] = ALLOW
    out["native-gate.toml"] = NATIVE_GATE
    out["manifest-gen.toml"] = CONFIG
    out["artifacts.toml"] = ARTIFACTS
    out["artifacts-other-core.toml"] = ARTIFACTS_OTHER

    lock_digest = sha(files["Cargo.lock"])
    record = canon({
        "artifact": {"bin": "toy-kernel", "package": "toy-kernel", "profile": "kernel-artifact",
                     "target": "wasm32-wasip1"},
        "lockfile": lock_digest,
        "profile": {"codegen-units": "int:1", "debug": "bool:false", "debug-assertions": "bool:false",
                    "incremental": "bool:false", "inherits": "str:release", "lto": "str:fat",
                    "opt-level": "int:3", "overflow-checks": "bool:false", "panic": "str:abort",
                    "strip": "str:symbols"},
        "remap": {"cargo_home": "/fid/cargo-home", "target_dir": "/fid/target", "vendor": "/fid/vendor",
                  "workspace": "/fid/src"},
        "rustflags": ["-C", "target-cpu=generic", "-C", "target-feature=-relaxed-simd,-simd128"],
        "schema": "fid-kernel-build/1",
        "target_features": ["bulk-memory", "multivalue", "mutable-globals", "nontrapping-fptoint",
                            "reference-types", "sign-ext"],
        "toolchain": {"channel": "1.89.0", "commit_hash": "29483883eed69d5fb4db01964cdf2af4d86e9cb2",
                      "llvm_version": "20.1.7"},
    })
    out["toolchain-record.json"] = record
    limits = canon({
        "constants": {"max_iter": "200", "tol_feas": "0x3ddb7cdfd9d7bdbb", "tol_gap_abs": "0x3ddb7cdfd9d7bdbb"},
        "name": "toy.conic.limits",
        "version": "1",
    })
    out["solver-limits.json"] = limits
    suite = sha(b"toy RDL suite (gen-toy-v1)")
    results = sha(b"toy RDL results (gen-toy-v1)")
    rdl = canon({"name": "rdl-release-0.1.0", "results_digest": results, "suite_digest": suite})
    out["rdl-release.json"] = rdl

    # Source tree: every tracked file except the generated constant.
    source = canon({
        "excluded": [CONSTANT],
        "files": [{"path": p, "sha256": sha(files[p])} for p in tracked if p != CONSTANT],
    })
    inputs = json.dumps({
        "algorithms": [a for a, _, _ in ALGORITHMS],
        "registrations": [{"algorithm": a, "crate": c} for a, c, _ in ALGORITHMS],
        "allowlist": impl.ALLOWLIST,
    }).encode("utf-8")
    impl_table, closures = impl.oracle(meta, inputs, files)
    impl_by_id = {r["algorithm"]: r["impl_digest"] for r in impl_table}
    # Hand-labelled closures (the constant's directory shim/ is not a crate of any closure).
    assert closures == {"fit.plane.lsq@1.10.0": ["kfit", "kgeo", "knum"], "geo.point.dist@1.2.0": ["kgeo", "knum"]}
    algorithms = []
    for alg, _, card in sorted(ALGORITHMS, key=lambda a: impl.alg_key(a[0])):
        fields = tomllib.loads(CARDS[card].decode("ascii"))
        assert fields["id"] == alg
        algorithms.append({"card_digest": sha(canon(fields)), "id": alg, "impl_digest": impl_by_id[alg]})
    runtime = tomllib.loads(RUNTIME.decode("ascii"))

    def core(native_gate):
        return {
            "algorithms": algorithms,
            "facade_selftest_digest": facade_selftest_digest(),
            "lockfile_digest": lock_digest,
            "name": "toy-kernel",
            "native_gate": native_gate,
            "numeric_profile": "knp-1",
            "reference_results_digest": results,
            "reference_suite_digest": suite,
            "replay_runtime": {"config_digest": sha(RUNTIME), "version": runtime["wasmtime_version"]},
            "schema_version": "1",
            "semver": "0.1.0",
            "solver_limits_digest": sha(limits),
            "source_tree_digest": sha(source),
            "toolchain_digest": sha(record),
        }

    the_core = core(tomllib.loads(NATIVE_GATE.decode("ascii"))["native_gate"])
    core_digest = sha(canon(the_core))
    other_digest = sha(canon(core("gating")))
    assert other_digest != core_digest
    out["expected-core.json"] = canon({"artifacts": [], "core": the_core, "core_digest": core_digest})
    out["expected-core-digest.txt"] = (core_digest + "\n").encode("ascii")
    out["expected-constant.rs"] = constant(core_digest)
    answer = self_report(core_digest)
    out["expected-self-report.json"] = answer
    toy = wasm_writer(answer)
    out["artifacts/toy-kernel.wasm"] = toy
    out["artifacts/other-core.wasm"] = wasm_writer(self_report(other_digest))
    manifest = canon({
        "artifacts": [{"role": "wasm", "sha256": sha(toy), "target": "wasm32-wasip1"}],
        "core": the_core,
        "core_digest": core_digest,
    })
    out["expected-manifest.json"] = manifest
    out["expected-manifest-digest.txt"] = (sha(manifest) + "\n").encode("ascii")
    return out


def main():
    check = "--check" in sys.argv[1:]
    out = build()
    on_disk = set()
    for p in HERE.rglob("*"):
        if p.is_file() and p.name != "make_fixtures.py" and "__pycache__" not in p.parts:
            on_disk.add(p.relative_to(HERE).as_posix())
    stale = sorted(on_disk - set(out))
    bad = []
    for rel, data in sorted(out.items()):
        path = HERE / rel
        if check:
            if not path.is_file() or path.read_bytes() != data:
                bad.append(rel)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if check:
        if bad or stale:
            for rel in bad:
                print("stale or missing: " + rel)
            for rel in stale:
                print("unexpected file: " + rel)
            sys.exit(1)
        print("gen-toy-v1: %d files up to date" % len(out))
    elif stale:
        for rel in stale:
            print("unexpected file (remove by hand): " + rel)
        sys.exit(1)


if __name__ == "__main__":
    main()
