#!/usr/bin/env python3
"""Generate the KRN.MAN.XART fixtures (CC-BY-4.0 project data) independently of the Rust code.

Every expected value comes from Python's standard library (hashlib, json) or is hand-labelled
from the rules in spec/krn/man/xart/NODE.md and the result envelope pinned by KRN.MAN.KCI and
KRN.MAN.WASM, never from the Rust implementation.

- calls.txt                     the synthetic call set (stand-in for the frozen UNC.RDL set)
- reference-table.json          the digest table the stand-in test algorithms must produce
- reference-reversed-table.json the table of the deliberately divergent native test artifact
                                (echo concatenates its inputs in reverse order)
- scenarios/<name>/             matrix, digest tables (and failed-<host>.txt markers), optional
                                previous table, release kind,
                                and the expected report bytes and exit code of `fid-xart compare`

Run:          python fixtures/man/xart-calls-v1/make_fixtures.py
Check (CI):   python fixtures/man/xart-calls-v1/make_fixtures.py --check
"""

import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).parent
OUT = {}  # path -> bytes

ECHO = "test.echo.identity@1.0.0"
RECURSE = "test.stack.recurse@1.0.0"
UNKNOWN = "test.none.missing@1.0.0"


def put(path, data):
    assert path not in OUT, path
    OUT[path] = data


def sha(b):
    return "sha256:" + hashlib.sha256(b).hexdigest()


def canon(value):
    # Every value is a string, array or object of ASCII text, so sorted keys (byte order equals
    # UTF-16 order for ASCII) and compact separators are RFC 8785 canonical.
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode("ascii")


# --- the call set ---------------------------------------------------------------------------
# (name, algorithm, params, seed or None, inputs, claimed digests or None)
CALLS = [
    ("echo-empty", ECHO, b"", None, [], None),
    ("echo-one-input", ECHO, b"a", 1, [b"abc"], None),
    ("echo-two-inputs", ECHO, b"two", 42, [b"abc", b"def"], None),
    ("echo-same-inputs", ECHO, b"same", None, [b"x", b"x"], None),
    ("echo-three-inputs", ECHO, b"three", 7, [b"1", b"22", b"333"], None),
    ("echo-fail", ECHO, b"fail", None, [], None),
    ("echo-empty-and-z", ECHO, b"empty-pair", 18446744073709551615, [b"", b"z"], None),
    ("recurse-0", RECURSE, b"0", None, [], None),
    ("recurse-1", RECURSE, b"1", None, [], None),
    ("recurse-100", RECURSE, b"100", 5, [], None),
    ("recurse-1000", RECURSE, b"1000", None, [], None),
    ("recurse-leading-zero", RECURSE, b"01", None, [], None),
    ("unknown-algorithm", UNKNOWN, b"", None, [], None),
    ("echo-digest-mismatch", ECHO, b"m", None, [b"abc"], [sha(b"abd")]),
]


def call_json(alg, params, seed, inputs, claimed):
    claimed = claimed or [sha(x) for x in inputs]
    v = {
        "algorithm": alg,
        "inputs": [{"bytes": x.hex(), "sha256": c} for x, c in zip(inputs, claimed)],
        "params": params.hex(),
    }
    if seed is not None:
        v["seed"] = str(seed)
    return canon(v)


def err(code):
    return canon({"error": code})


def envelope(alg, params, seed, inputs, output):
    v = {
        "algorithm": alg,
        "input_digests": [sha(x) for x in inputs],
        "output": output.hex(),
        "output_digest": sha(output),
        "params_digest": sha(params),
    }
    if seed is not None:
        v["seed"] = str(seed)
    return canon(v)


def decimal_ok(p):
    # KRN.MAN.WASM stand-in rule: a decimal u64 without leading zeros.
    return 0 < len(p) <= 20 and p.isdigit() and not (len(p) > 1 and p[:1] == b"0") and int(p) < 2**64


def answer(alg, params, seed, inputs, claimed, reversed_echo):
    """(exit, stdout) of the stand-in kernel for one call, in KCI evaluation order."""
    if alg not in (ECHO, RECURSE):
        return 1, err("unknown_algorithm")
    if claimed is not None and any(sha(x) != c for x, c in zip(inputs, claimed)):
        return 1, err("digest_mismatch")
    if alg == ECHO:
        if not all(0x20 <= b <= 0x7E for b in params):
            return 1, err("invalid_params")
        if params == b"fail":
            return 1, err("algorithm_failed")
        out = params + b"|" + (str(seed).encode() if seed is not None else b"-")
        for x in reversed(inputs) if reversed_echo else inputs:
            out += b"|" + x
        return 0, envelope(alg, params, seed, inputs, out)
    if not decimal_ok(params):
        return 1, err("invalid_params")
    return 0, envelope(alg, params, seed, inputs, str(int(params)).encode())


lines = [
    b"# KRN.MAN.XART AC-1..AC-4: synthetic call set over the KRN.MAN.WASM stand-in test algorithms,",
    b"# standing in for the frozen UNC.RDL reference set. Generated by make_fixtures.py. CC-BY-4.0.",
    b"# Format: <name><TAB><canonical KernelCall JSON>.",
]
for name, alg, params, seed, inputs, claimed in CALLS:
    lines.append(name.encode() + b"\t" + call_json(alg, params, seed, inputs, claimed))
calls_bytes = b"\n".join(lines) + b"\n"
CALL_SET = sha(calls_bytes)
put(HERE / "calls.txt", calls_bytes)


def rows(reversed_echo=False):
    out = []
    for i, (name, alg, params, seed, inputs, claimed) in enumerate(CALLS):
        code, stdout = answer(alg, params, seed, inputs, claimed, reversed_echo)
        out.append({"algorithm": alg, "call": str(i), "exit": str(code), "name": name, "result_digest": sha(stdout)})
    return out


def table(artifact, host, kind, rs, call_set=CALL_SET):
    return {
        "artifact": artifact,
        "artifact_sha256": sha(artifact.encode()),
        "call_set_digest": call_set,
        "host": host,
        "kind": kind,
        "rows": rs,
        "schema": "fid-xart-table@1",
    }


REF_ROWS = rows()
REV_ROWS = rows(reversed_echo=True)
# Reference tables: the artifact hash is a placeholder (SHA-256 of the label); only rows matter.
put(HERE / "reference-table.json", canon(table("python-reference", "reference", "wasm", REF_ROWS)))
put(HERE / "reference-reversed-table.json", canon(table("python-reversed", "reference", "native", REV_ROWS)))


# --- the comparison oracle (spec Design: run, tabulate, compare) ----------------------------
def compare(hosts, tables, release, previous, failed=()):
    """hosts: [(name, runner, optional)] sorted by name; failed: hosts that left a
    failed-<host> marker. Returns (exit, report bytes)."""
    wasm = {t["host"]: t for t in tables if t["kind"] == "wasm"}
    natives = sorted((t for t in tables if t["kind"] == "native"), key=lambda t: (t["host"], t["artifact"]))
    ref_host = next((h for h, _, _ in hosts if h in wasm), None)
    ref = wasm.get(ref_host)
    failures = []
    if ref is None:
        failures.append("no_wasm_table")
    host_entries = []
    for h, runner, optional in hosts:
        t = wasm.get(h)
        e = {"host": h, "optional": "true" if optional else "false", "runner": runner}
        if t is None:
            e["status"] = "not_run"
            if not optional:
                failures.append(f"host_not_run: {h}")
            host_entries.append(e)
            continue
        e["status"] = "run"
        e["artifact_sha256"] = t["artifact_sha256"]
        host_entries.append(e)
        if h == ref_host:
            continue
        if t["artifact_sha256"] != ref["artifact_sha256"]:
            failures.append(
                f"wasm_artifact_mismatch: host {h} ran {t['artifact_sha256']}, host {ref_host} ran {ref['artifact_sha256']}"
            )
        for r, q in zip(t["rows"], ref["rows"]):
            if r["result_digest"] != q["result_digest"]:
                failures.append(
                    f"wasm_digest_mismatch: host {h} call {r['call']} ({r['name']}) algorithm {r['algorithm']} differs from host {ref_host}"
                )
    # A host whose job failed is a failure, optional or not (defence in depth).
    for h, _, _ in hosts:
        if h in failed:
            failures.append(f"host_failed: {h}")
    native_entries = []
    for t in natives:
        algs = {}
        if ref is not None:
            for r, q in zip(t["rows"], ref["rows"]):
                a = algs.setdefault(r["algorithm"], [0, 0])
                a[0] += 1
                a[1] += r["result_digest"] == q["result_digest"]
        native_entries.append(
            {
                "algorithms": [
                    {"algorithm": k, "calls": str(v[0]), "matches": str(v[1])} for k, v in sorted(algs.items())
                ],
                "artifact": t["artifact"],
                "artifact_sha256": t["artifact_sha256"],
                "host": t["host"],
            }
        )
    rel = {"kind": release, "status": "not_checked"}
    if release == "patch":
        rel["previous_artifact_sha256"] = previous["artifact_sha256"]
        ok = ref is not None
        if ref is not None and previous["call_set_digest"] != ref["call_set_digest"]:
            failures.append(f"patch_call_set_mismatch: previous {previous['call_set_digest']}")
            ok = False
        elif ref is not None:
            for r, q in zip(ref["rows"], previous["rows"]):
                if r["result_digest"] != q["result_digest"]:
                    failures.append(
                        f"patch_digest_mismatch: call {r['call']} ({r['name']}) algorithm {r['algorithm']}"
                    )
                    ok = False
        rel["status"] = "pass" if ok else "fail"
    report = {
        "call_set_digest": tables[0]["call_set_digest"],
        "failures": failures,
        "gate": "fail" if failures else "pass",
        "hosts": host_entries,
        "native": native_entries,
        "native_gate": "measured-only",
        "release": rel,
        "schema": "fid-xart-report@1",
    }
    if ref is not None:
        report["wasm_artifact_sha256"] = ref["artifact_sha256"]
    return (1 if failures else 0), canon(report)


def matrix_toml(hosts):
    out = ["# Scenario matrix (generated by make_fixtures.py).", 'schema = "1"']
    for h, runner, optional in hosts:
        out += ["", "[[host]]", f'name = "{h}"', f'runner = "{runner}"', f"optional = {'true' if optional else 'false'}"]
    return ("\n".join(out) + "\n").encode()


HOSTS3 = [("linux-x86_64", "ubuntu-latest", False), ("macos-arm64", "macos-latest", False), ("windows-arm64", "windows-11-arm", True)]
WASM = "kernel-wasm-test"


def wasm_tables(names, rows_for=lambda h: REF_ROWS):
    return [table(WASM, h, "wasm", rows_for(h)) for h in names]


def tweak(rs, index):
    rs = [dict(r) for r in rs]
    rs[index]["result_digest"] = sha(b"tampered")
    return rs


NATIVES = [
    table("native-faithful", "linux-x86_64", "native", REF_ROWS),
    table("native-reversed", "linux-x86_64", "native", REV_ROWS),
]
ALL3 = ["linux-x86_64", "macos-arm64", "windows-arm64"]
PREV = table("previous-release", "reference", "wasm", REF_ROWS)
SCENARIOS = {
    # AC-1 (identical WASM digests on every host, exit 0) and AC-2 (divergent native reported).
    "ac1-ac2-identical": (HOSTS3, wasm_tables(ALL3) + NATIVES, "none", None),
    # AC-3: a patch release whose previous table differs in one entry.
    "ac3-patch-differs": (HOSTS3, wasm_tables(ALL3), "patch", dict(PREV, rows=tweak(REF_ROWS, 9))),
    "patch-identical": (HOSTS3, wasm_tables(ALL3), "patch", PREV),
    "patch-call-set-differs": (HOSTS3, wasm_tables(ALL3), "patch", dict(PREV, call_set_digest=sha(b"other"))),
    # REQ-001: one host differs.
    "host-differs": (
        HOSTS3,
        wasm_tables(ALL3, lambda h: tweak(REF_ROWS, 2) if h == "macos-arm64" else REF_ROWS),
        "none",
        None,
    ),
    "artifact-differs": (
        HOSTS3,
        wasm_tables(ALL3[:2]) + [table("kernel-wasm-other", "windows-arm64", "wasm", REF_ROWS)],
        "none",
        None,
    ),
    # REQ-005: an unavailable host is `not_run`; it fails the gate unless optional.
    "optional-not-run": (HOSTS3, wasm_tables(ALL3[:2]), "none", None),
    "required-not-run": (HOSTS3, wasm_tables(["linux-x86_64", "windows-arm64"]), "none", None),
    "no-wasm-table": (HOSTS3, NATIVES, "none", None),
    # A host job that failed leaves a failed-<host> marker: a failure even for an optional host.
    "host-failed": (HOSTS3, wasm_tables(ALL3[:2]), "none", None, ["windows-arm64"]),
}

for name, (hosts, tables, release, previous, *rest) in SCENARIOS.items():
    failed = rest[0] if rest else []
    d = HERE / "scenarios" / name
    put(d / "matrix.toml", matrix_toml(hosts))
    for t in tables:
        put(d / "tables" / f"{t['kind']}-{t['host']}-{t['artifact']}.json", canon(t))
    if previous is not None:
        put(d / "previous.json", canon(previous))
    for h in failed:
        put(d / "tables" / f"failed-{h}.txt", b"failed\n")
    put(d / "release.txt", (release + "\n").encode())
    code, report = compare(hosts, tables, release, previous, failed)
    put(d / "expected-exit.txt", f"{code}\n".encode())
    put(d / "expected-report.json", report)


def main():
    check = sys.argv[1:] == ["--check"]
    if sys.argv[1:] not in ([], ["--check"]):
        print(__doc__)
        return 2
    bad = 0
    for path, data in sorted(OUT.items()):
        if check:
            if not path.exists() or path.read_bytes() != data:
                print(f"stale: {path.relative_to(HERE)}")
                bad += 1
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    if check:
        # No file in the scenario folders that this script does not write.
        for p in sorted((HERE / "scenarios").rglob("*")):
            if p.is_file() and p not in OUT:
                print(f"unexpected: {p.relative_to(HERE)}")
                bad += 1
        print(f"{len(OUT)} files, {bad} stale or unexpected")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
