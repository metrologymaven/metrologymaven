#!/usr/bin/env python3
"""Deterministic seeded lobed-circle fixture generator for KRN.MZ.RND.CIRC (`fixtures/fit/mz-circ-v1`).

License: CC-BY-4.0 (project-authored synthetic geometry).

Generates seeded lobed circles (2-lobe oval, 3-lobe, 5-lobe, eccentric near-origin and
1 km from origin) with deterministic coordinates in big-endian IEEE-754 binary64 hex.
Reference global optima are independently verified by `fid_fit::vor::mz_circle2d_xy`
(`KRN.MZ.VOR`) within 1e-9 m (REQ-KRN.MZ.RND.CIRC-005).

Usage:
    python3 fixtures/fit/make_mz_circ_fixtures.py          # write fixtures/fit/mz-circ-v1/cases.txt
    python3 fixtures/fit/make_mz_circ_fixtures.py --check  # verify byte-exact match
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path
import struct
import sys


OUT_FILE = Path(__file__).resolve().parent / "mz-circ-v1" / "cases.txt"


def f64_hex(x: float) -> str:
    return struct.pack(">d", float(x)).hex()


def make_lobed_circle(
    name: str,
    center: tuple[float, float],
    radius: float,
    lobes: list[tuple[int, float, float]],
    n_pts: int,
    phase_offset: float,
) -> list[str]:
    lines = [f"case {name}"]
    cx, cy = center
    for k in range(n_pts):
        th = phase_offset + (2.0 * math.pi * k) / n_pts
        r = radius
        for order, amp, phi in lobes:
            r += amp * math.cos(order * th + phi)
        x = cx + r * math.cos(th)
        y = cy + r * math.sin(th)
        lines.append(f"p {f64_hex(x)} {f64_hex(y)} {f64_hex(0.0)}")
    lines.append("end")
    return lines


def generate() -> str:
    out = [
        "# Seeded lobed-circle fixtures for KRN.MZ.RND.CIRC (`fixtures/fit/mz-circ-v1`).",
        "# Generated by fixtures/fit/make_mz_circ_fixtures.py (CC-BY-4.0).",
        "# Floats are big-endian IEEE-754 binary64 hex (16 lowercase hex digits).",
        "",
    ]

    cases = [
        # 1. 2-lobe (oval) near origin, 20 um peak-to-valley
        make_lobed_circle(
            "circ_oval_2lobe_near",
            center=(0.015, -0.025),
            radius=0.050,
            lobes=[(2, 1.0e-5, 0.3)],
            n_pts=64,
            phase_offset=0.11,
        ),
        # 2. 3-lobe (tri-lobing) at 1 km from origin
        make_lobed_circle(
            "circ_trilobe_1km",
            center=(1000.0, -500.0),
            radius=0.040,
            lobes=[(3, 1.5e-5, 0.7), (2, 4.0e-6, -0.2)],
            n_pts=72,
            phase_offset=0.05,
        ),
        # 3. 5-lobe harmonic mix at 1 km from origin
        make_lobed_circle(
            "circ_5lobe_1km",
            center=(-750.0, 620.0),
            radius=0.025,
            lobes=[(5, 8.0e-6, 0.4), (3, 5.0e-6, 1.1)],
            n_pts=80,
            phase_offset=0.03,
        ),
        # 4. Asymmetric 2-2 alternating eccentric mix far from origin
        make_lobed_circle(
            "circ_asym_far",
            center=(420.5, -830.25),
            radius=0.080,
            lobes=[(2, 2.0e-5, 0.9), (4, 7.5e-6, -0.5)],
            n_pts=96,
            phase_offset=0.07,
        ),
    ]

    for c in cases:
        out.extend(c)
        out.append("")

    return "\n".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify committed fixture matches generator")
    args = parser.parse_args()

    content = generate()
    if args.check:
        if not OUT_FILE.exists():
            print(f"MISSING: {OUT_FILE}", file=sys.stderr)
            return 1
        actual = OUT_FILE.read_text(encoding="utf-8")
        if actual != content:
            print(f"MISMATCH: {OUT_FILE} differs from generator output", file=sys.stderr)
            return 1
        print(f"OK: {OUT_FILE} matches generator")
        return 0

    OUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUT_FILE.write_text(content, encoding="utf-8", newline="\n")
    print(f"Wrote {OUT_FILE} ({len(content)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
