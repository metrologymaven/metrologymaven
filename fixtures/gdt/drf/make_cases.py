#!/usr/bin/env python3
"""Independent reference for the GDT.DRF.DATUM tests (stdlib only; CC0; synthetic data).

Writes, next to this script:

- block_plan.fidproj: a synthetic block plan with three measured planes (f1, f2, f3, one
  nominal face each) and a few target geometries, no datums declared;
- datum_profile.json: a synthetic defaults profile that sets gdt.datum.label_pattern;
- expected.json: the canonical event, result and MCP parameter bytes the acceptance criteria
  expect, derived here from the leaf's written rules (not by running the Rust code).

Canonical JSON (RFC 8785) for this data: keys sorted, no whitespace, strings only (the
files hold no numbers), ASCII only, so json.dumps with sort_keys and compact separators is
exact.
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PATTERN = "[A-Z]{1,3}"  # synthetic; not taken from any standard


def canon(v):
    return json.dumps(v, sort_keys=True, separators=(",", ":"), ensure_ascii=True)


PLAN = {
    "schema": "fid.gdt-datum-plan/1",
    "plan": "block-1",
    "faces": ["face:12", "face:13", "face:14"],
    "features": {
        "f1": {"type": "plane", "faces": ["face:12"]},
        "f2": {"type": "plane", "faces": ["face:13"]},
        "f3": {"type": "plane", "faces": ["face:14"]},
    },
    "geometry": {
        "pt:1": {"kind": "point", "face": "face:12"},
        "pt:2": {"kind": "point", "face": "face:12"},
        "pt:3": {"kind": "point", "face": "face:13"},
        "ln:1": {"kind": "line", "face": "face:12"},
        "ar:1": {"kind": "area", "face": "face:12"},
    },
    "datums": {"working": {}, "agent": {}},
}


def definition(label, feature, faces, ftype, targets):
    # Faces ascending, targets ascending by id (the canonical order of the leaf's Design).
    return {
        "label": label,
        "feature": feature,
        "faces": sorted(faces),
        "feature_type": ftype,
        "targets": sorted(
            [{"id": i, "kind": k, "geometry": g} for (i, k, g) in targets], key=lambda t: t["id"]
        ),
    }


def event(principal, replace, old, new):
    return {
        "command": "gdt.define_datum@1",
        "principal": principal,
        "branch": "working" if principal == "human" else "agent",
        "plan": "block-1",
        "label_pattern": PATTERN,
        "replace": replace,
        "old": old,
        "new": new,
    }


def main():
    # AC-1: define-datum --label A --feature f1 --faces face:12 --type plane (human).
    a1 = definition("A", "f1", ["face:12"], "plane", [])
    ac1_event = event("human", False, None, a1)
    ac1_result = {"branch": "working", "datum": a1, "dry_run": False, "plan": "block-1", "replaced": None}

    # AC-3: the same label again with --replace and three point/area targets given out of order.
    a3 = definition(
        "A", "f1", ["face:12"], "plane", [("A2", "point", "pt:2"), ("A1", "point", "pt:1"), ("A3", "area", "ar:1")]
    )
    ac3_event = event("human", True, a1, a3)
    ac3_result = {"branch": "working", "datum": a3, "dry_run": False, "plan": "block-1", "replaced": a1}

    # The same calls as MCP parameter objects. The parameter keys equal the definition keys
    # (label, feature, faces, feature_type, targets), as pinned in the leaf's Design.
    ac1_params = {"label": "A", "feature": "f1", "faces": ["face:12"], "feature_type": "plane"}
    ac3_params = {
        "label": "A",
        "feature": "f1",
        "faces": ["face:12"],
        "feature_type": "plane",
        "targets": [
            {"id": "A2", "kind": "point", "geometry": "pt:2"},
            {"id": "A1", "kind": "point", "geometry": "pt:1"},
            {"id": "A3", "kind": "area", "geometry": "ar:1"},
        ],
        "replace": True,
    }

    # An agent declaring B on f2 with a point target: agent branch.
    b = definition("B", "f2", ["face:13"], "plane", [("B1", "point", "pt:3")])
    agent_event = event("agent", False, None, b)

    # The plan after AC-1 and AC-3.
    after = json.loads(json.dumps(PLAN))
    after["datums"]["working"]["A"] = a3

    profile = {
        "schema": "fid.defaults-profile/1",
        "dialect": "asme",
        "edition": "y14.5-2018",
        "version": "1.0.0",
        "keys": {"gdt.datum.label_pattern": "[A-H]{1,2}", "placeholder.synthetic": True},
    }

    expected = {
        "note": "Generated by make_cases.py from the GDT.DRF.DATUM rules; synthetic data; CC0.",
        "label_pattern": PATTERN,
        "ac1_event": canon(ac1_event),
        "ac1_result": canon(ac1_result),
        "ac3_event": canon(ac3_event),
        "ac3_result": canon(ac3_result),
        "ac1_params": canon(ac1_params),
        "ac3_params": canon(ac3_params),
        "agent_event": canon(agent_event),
        "plan_after_ac3": canon(after),
        "plan_canonical": canon(PLAN),
    }

    with open(os.path.join(HERE, "block_plan.fidproj"), "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(PLAN, indent=2) + "\n")
    with open(os.path.join(HERE, "datum_profile.json"), "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(profile, indent=2) + "\n")
    with open(os.path.join(HERE, "expected.json"), "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(expected, indent=2, sort_keys=True) + "\n")


if __name__ == "__main__":
    main()
