#!/usr/bin/env python3
"""Generate the ECO.DATA.FETCH fixtures (MIT OR Apache-2.0, like the spec node says).

Writes seeded binary files fixtures/fetch/*.bin and the catalogue template
fixtures/fetch/catalogue.toml whose entries the tests serve from an in-process
HTTP server on 127.0.0.1 (placeholder @BASE@) or read through file:// (placeholder
@FILEBASE@). The tests substitute the placeholders at run time. No external network.

Every digest and size in the catalogue is computed here with Python's hashlib, sharing
no code with the Rust crate. All files are synthetic bytes, not datasets.

Run:  python fixtures/fetch/make_fixtures.py          (writes the files)
      python fixtures/fetch/make_fixtures.py --check  (fails if the files are stale)
"""

import hashlib
import sys
from pathlib import Path

HERE = Path(__file__).parent


def seeded(seed: str, n: int) -> bytes:
    """n bytes: SHA-256 of "<seed>:<counter>" for counter = 0, 1, 2, ... concatenated."""
    out = bytearray()
    i = 0
    while len(out) < n:
        out += hashlib.sha256(f"{seed}:{i}".encode()).digest()
        i += 1
    return bytes(out[:n])


TINY = seeded("tiny", 1024)
CORRUPT = bytes([TINY[0] ^ 0xFF]) + TINY[1:]  # same size, one byte flipped
MIRRORED = seeded("mirrored", 2048)
OVERSIZE = seeded("oversize", 4096)
OVERSIZE_LIMIT = 512  # the catalogue says 512 bytes; the server streams 4096

FILES = {"tiny.bin": TINY, "corrupt.bin": CORRUPT, "mirrored.bin": MIRRORED, "oversize.bin": OVERSIZE}


def sha(b: bytes) -> str:
    return hashlib.sha256(b).hexdigest()


def entry(id_: str, data: bytes, urls: list[str], size: int | None = None) -> str:
    size = len(data) if size is None else size
    url_list = ", ".join(f'"{u}"' for u in urls)
    return (
        "\n[[dataset]]\n"
        f'id = "{id_}"\n'
        f'title = "Synthetic test file {id_} (ECO.DATA.FETCH)"\n'
        'source = "https://github.com/metrologymaven/metrologymaven/tree/main/fixtures/fetch"\n'
        'licence = "CC0-1.0"\n'
        f"size_bytes = {size}\n"
        f'sha256 = "{sha(data[:size])}"\n'
        'owner = "ECO"\n'
        'redistribution = "mirror"\n'
        f"urls = [{url_list}]\n"
    )


CATALOGUE = (
    "# ECO.DATA.FETCH test catalogue, generated by make_fixtures.py. @BASE@ and @FILEBASE@ are\n"
    "# replaced by the tests (in-process HTTP server on 127.0.0.1, and file:// of this folder).\n"
    "\n[policy]\nredistributable = [\"CC0-1.0\"]\n"
    + entry("tiny", TINY, ["@BASE@/tiny.bin"])
    # Served bytes differ from the catalogue digest (AC-3).
    + entry("corrupt", TINY, ["@BASE@/corrupt.bin"])
    # First URL is a 404, second serves the right bytes (AC-4).
    + entry("mirrored", MIRRORED, ["@BASE@/missing/mirrored.bin", "@BASE@/mirrored.bin"])
    # The server streams 4096 bytes; the catalogue allows 512 (AC-6).
    + entry("oversize", OVERSIZE, ["@BASE@/oversize.bin"], size=OVERSIZE_LIMIT)
    # The server answers 302 to /tiny.bin; redirects are refused.
    + entry("redirect", TINY, ["@BASE@/redirect/tiny.bin"])
    # Local mirror through file://.
    + entry("local", TINY, ["@FILEBASE@/tiny.bin"])
)

OUTPUTS = {**FILES, "catalogue.toml": CATALOGUE.encode()}


def main() -> int:
    check = "--check" in sys.argv[1:]
    stale = []
    for name, data in OUTPUTS.items():
        path = HERE / name
        if check:
            if not path.is_file() or path.read_bytes() != data:
                stale.append(name)
        else:
            path.write_bytes(data)
    for name, data in FILES.items():
        print(f"{name}\t{len(data)}\t{sha(data)}")
    print(f"oversize[:{OVERSIZE_LIMIT}]\t{OVERSIZE_LIMIT}\t{sha(OVERSIZE[:OVERSIZE_LIMIT])}")
    if stale:
        print("stale: " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
