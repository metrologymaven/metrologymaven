#!/usr/bin/env python3
"""Generate the CORE.STO.LAYOUT fixtures (AC-3, AC-5). CC-BY-4.0 project data.

stale_lock/lock             lock record naming a dead PID; host is the placeholder @THIS_HOST@,
                            which the test replaces with the machine's host name (AC-3, take over).
stale_lock/lock_other_host  same record from another host (AC-3, never taken over).
session_100/session.txt     100 writes into the project areas, with a write reopen every 10.
session_100/expected_listing.txt
                            every path the project folder must hold after the session, computed
                            here from the spec's layout rules (REQ-001, REQ-007), not by the store.

PID 4294967294 cannot be a live process: Linux pid_max is at most 4194304, macOS PIDs stay
below 100000, and Windows PIDs are multiples of 4.
Run:  python fixtures/core/sto/layout/make_fixtures.py
"""

import hashlib
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEAD_PID = 4294967294


def lock_record(host):
    return f"fid-lock@1\npid={DEAD_PID}\nhost={host}\nstarted=1700000000\n"


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_bytes(text.encode("ascii"))


write(HERE / "stale_lock" / "lock", lock_record("@THIS_HOST@"))
write(HERE / "stale_lock" / "lock_other_host", lock_record("other-host.invalid"))

# Session: item i goes to blobs/<d[:2]>/<d>, kernels/<d> or tmp/<d> by i mod 3, where d is
# the SHA-256 of the item's content. Every 10th item is followed by a write reopen.
AREAS = ["blobs", "kernels", "tmp"]
ops = []
paths = {"format", "project.db", "lock", "blobs", "kernels", "tmp"}
for i in range(100):
    content = f"session-100 item {i}".encode("ascii")
    d = hashlib.sha256(content).hexdigest()
    area = AREAS[i % 3]
    if area == "blobs":
        ops.append(f"put {area} {d[:2]} {d} {content.hex()}")
        paths.add(f"blobs/{d[:2]}")
        paths.add(f"blobs/{d[:2]}/{d}")
    else:
        ops.append(f"put {area} - {d} {content.hex()}")
        paths.add(f"{area}/{d}")
    if i % 10 == 9:
        ops.append("reopen")

NAME = re.compile(r"^[a-z0-9_.-]+$")
for p in paths:
    assert all(NAME.match(part) for part in p.split("/")), p
folded = {p.casefold() for p in paths}
assert len(folded) == len(paths)

header = ("# CORE.STO.LAYOUT AC-5 session, generated by make_fixtures.py. CC-BY-4.0.\n"
          "# put <area> <subdir or -> <name> <content as hex> | reopen\n")
write(HERE / "session_100" / "session.txt", header + "\n".join(ops) + "\n")
write(HERE / "session_100" / "expected_listing.txt", "\n".join(sorted(paths)) + "\n")
print(f"{len(ops)} ops, {len(paths)} paths")
