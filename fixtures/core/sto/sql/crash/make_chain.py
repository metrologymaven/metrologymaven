#!/usr/bin/env python3
"""Independent oracle for CORE.STO.SQL.CRASH: the synthetic chain and the expected recovery.

Written from the rules of spec/core/sto/sql/crash/NODE.md and spec/core/sto/sql/txn/NODE.md
with Python's hashlib and json only; nothing here is produced by running the Rust code.

Synthetic chain (format "fid-crash-row@1"), for seq = 1, 2, ...:
  payload bytes  b"fid-crash payload <seq>"
  blob bytes     present when seq % 3 != 0: (b"fid-crash blob <seq>\\n") * (32 * (1 + seq % 5))
  row            {"blob": sha256 of the blob bytes or null, "format": "fid-crash-row@1",
                  "payload": sha256 of the payload bytes, "prev": hash of row seq-1 or null
                  for seq 1, "seq": decimal string of seq}
  canonical      RFC 8785 form of the row: keys sorted, no white space; every value is an
                 ASCII string or null, so json.dumps(sort_keys, compact separators) is exact
  hash           "sha256:" + SHA-256 of the canonical bytes, lowercase hex

Steps (kill and fault at every commit step): a commit of row c reports, in order,
  BlobDurable (only when row c has a blob), Begin, BeforeCommit, Committed
(CORE.STO.SQL.TXN: blobs durable first, then BEGIN, the rows, COMMIT). For a writer that
commits rows 1..M and is stopped at the n-th reported step (counting from 1 over the whole
run), the expected recovered row count is
  kill  (process killed at that step):  c if the step is Committed, else c - 1
  fault (the step returns an error):    the commit of c fails and writes nothing unless the
                                        step is Committed, which comes after COMMIT and can no
                                        longer fail it; the writer then retries c and goes on,
                                        so all M rows are present at the end.
  failed  whether the commit of c returned an error.

Kill plan: the delay before kill k of seed s is splitmix64(splitmix64(s) XOR k) modulo
(max_delay_us + 1), with SplitMix64 as published by Steele, Lea and Flood (2014); the vectors
below are for seed 1 and max_delay_us 30000, kills 0..15.

Output: chain.json (CC-BY-4.0 project data).

Run:   python fixtures/core/sto/sql/crash/make_chain.py
Check: python fixtures/core/sto/sql/crash/make_chain.py --check
"""

import hashlib
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "chain.json"
ROWS = 40
STEP_COMMITS = 6
FORMAT = "fid-crash-row@1"


def sha(b: bytes) -> str:
    return "sha256:" + hashlib.sha256(b).hexdigest()


def payload(seq: int) -> bytes:
    return b"fid-crash payload %d" % seq


def blob(seq: int):
    if seq % 3 == 0:
        return None
    return (b"fid-crash blob %d\n" % seq) * (32 * (1 + seq % 5))


def canonical(obj) -> str:
    text = json.dumps(obj, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    assert text.isascii()
    return text


def chain(n: int):
    rows = []
    prev = None
    for seq in range(1, n + 1):
        b = blob(seq)
        row = {
            "blob": None if b is None else sha(b),
            "format": FORMAT,
            "payload": sha(payload(seq)),
            "prev": prev,
            "seq": str(seq),
        }
        text = canonical(row)
        h = sha(text.encode("ascii"))
        rows.append(
            {
                "seq": seq,
                "canonical": text,
                "hash": h,
                "blob_len": 0 if b is None else len(b),
            }
        )
        prev = h
    return rows


def steps(m: int):
    out = []
    n = 0
    for c in range(1, m + 1):
        names = (["BlobDurable"] if blob(c) is not None else []) + ["Begin", "BeforeCommit", "Committed"]
        for name in names:
            n += 1
            committed = name == "Committed"
            out.append(
                {
                    "step": n,
                    "commit": c,
                    "event": name,
                    "kill_rows": c if committed else c - 1,
                    "fault_failed": not committed,
                    "fault_rows": m,
                }
            )
    return out


MASK = (1 << 64) - 1
PLAN_SEED = 1
PLAN_MAX_DELAY_US = 30000
PLAN_KILLS = 16


def splitmix64(x: int) -> int:
    z = (x + 0x9E3779B97F4A7C15) & MASK
    z = ((z ^ (z >> 30)) * 0xBF58476D1CE4E5B9) & MASK
    z = ((z ^ (z >> 27)) * 0x94D049BB133111EB) & MASK
    return z ^ (z >> 31)


def kill_plan():
    base = splitmix64(PLAN_SEED)
    delays = [splitmix64(base ^ k) % (PLAN_MAX_DELAY_US + 1) for k in range(PLAN_KILLS)]
    return {"seed": PLAN_SEED, "max_delay_us": PLAN_MAX_DELAY_US, "delays_us": delays}


def build() -> str:
    doc = {
        "about": "Independent oracle for CORE.STO.SQL.CRASH, generated by make_chain.py from "
        "the spec rules with Python hashlib and json; never produced by the Rust code. "
        "CC-BY-4.0.",
        "format": FORMAT,
        "kill_plan": kill_plan(),
        "rows": chain(ROWS),
        "step_commits": STEP_COMMITS,
        "steps": steps(STEP_COMMITS),
    }
    return json.dumps(doc, indent=1, sort_keys=True) + "\n"


def main() -> int:
    text = build()
    if "--check" in sys.argv[1:]:
        have = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if have != text:
            print(f"{OUT} is stale; run {Path(__file__).name}", file=sys.stderr)
            return 1
        print(f"{OUT.name} up to date")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
