#!/usr/bin/env python3
"""Reference generator for the pinned Unicode 16.0 tables of CORE.BUS.PRIN.

Writes crates/fid-bus/src/unicode16.rs, independently of the Rust code:

  FORMAT_RANGES             general category Cf
  UNASSIGNED_RANGES         general category Cn (unassigned code points, noncharacters included)
  DEFAULT_IGNORABLE_RANGES  derived property Default_Ignorable_Code_Point

Cf and Cn come from Python's `unicodedata`, which must report Unicode 16.0.0 (Python 3.14);
the script refuses any other version, so the tables stay pinned.

`unicodedata` has no Default_Ignorable_Code_Point. It is derived here with the formula of
DerivedCoreProperties.txt (Unicode 16.0):
  Other_Default_Ignorable_Code_Point + Cf + Variation_Selector
  - White_Space - FFF9..FFFB - 13430..1343F - Prepended_Concatenation_Mark
The PropList.txt 16.0 inputs that `unicodedata` lacks are hand-copied below as code point
ranges (Other_Default_Ignorable_Code_Point, Variation_Selector, Prepended_Concatenation_Mark,
White_Space).
The result is compared with the hand-copied DerivedCoreProperties.txt 16.0 list as a check.

  python fixtures/core/bus/principal/make_unicode_tables.py          # write
  python fixtures/core/bus/principal/make_unicode_tables.py --check  # compare, exit 1 on drift

CC-BY-4.0 project data.
"""

import argparse
import pathlib
import sys
import unicodedata

UNICODE = "16.0.0"
ROOT = pathlib.Path(__file__).resolve().parents[4]
OUT = ROOT / "crates" / "fid-bus" / "src" / "unicode16.rs"

# PropList.txt 16.0, Other_Default_Ignorable_Code_Point.
OTHER_DI = [
    (0x034F, 0x034F), (0x115F, 0x1160), (0x17B4, 0x17B5), (0x2065, 0x2065), (0x3164, 0x3164),
    (0xFFA0, 0xFFA0), (0xFFF0, 0xFFF8), (0xE0000, 0xE0000), (0xE0002, 0xE001F),
    (0xE0080, 0xE00FF), (0xE01F0, 0xE0FFF),
]
# PropList.txt 16.0, Variation_Selector.
VARIATION_SELECTOR = [(0x180B, 0x180D), (0x180F, 0x180F), (0xFE00, 0xFE0F), (0xE0100, 0xE01EF)]
# PropList.txt 16.0, Prepended_Concatenation_Mark.
PCM = [(0x0600, 0x0605), (0x06DD, 0x06DD), (0x070F, 0x070F), (0x0890, 0x0891), (0x08E2, 0x08E2),
       (0x110BD, 0x110BD), (0x110CD, 0x110CD)]
# DerivedCoreProperties.txt 16.0, Default_Ignorable_Code_Point (merged ranges), for the check.
DI_EXPECTED = [
    (0x00AD, 0x00AD), (0x034F, 0x034F), (0x061C, 0x061C), (0x115F, 0x1160), (0x17B4, 0x17B5),
    (0x180B, 0x180F), (0x200B, 0x200F), (0x202A, 0x202E), (0x2060, 0x206F), (0x3164, 0x3164),
    (0xFE00, 0xFE0F), (0xFEFF, 0xFEFF), (0xFFA0, 0xFFA0), (0xFFF0, 0xFFF8), (0x1BCA0, 0x1BCA3),
    (0x1D173, 0x1D17A), (0xE0000, 0xE0FFF),
]


def expand(ranges):
    out = set()
    for lo, hi in ranges:
        out.update(range(lo, hi + 1))
    return out


def merge(points):
    out = []
    for cp in sorted(points):
        if out and out[-1][1] + 1 == cp:
            out[-1][1] = cp
        else:
            out.append([cp, cp])
    return [tuple(r) for r in out]


def category(cat):
    return {cp for cp in range(0x110000) if unicodedata.category(chr(cp)) == cat}


def white_space():
    # Unicode White_Space (PropList.txt 16.0); none is Cf, listed for the formula only.
    return expand([(0x0009, 0x000D), (0x0020, 0x0020), (0x0085, 0x0085), (0x00A0, 0x00A0),
                   (0x1680, 0x1680), (0x2000, 0x200A), (0x2028, 0x2029), (0x202F, 0x202F),
                   (0x205F, 0x205F), (0x3000, 0x3000)])


def rust_table(name, doc, ranges):
    lines = [f"/// {doc}", "#[rustfmt::skip]", f"pub const {name}: &[(u32, u32)] = &["]
    row = []
    for lo, hi in ranges:
        row.append(f"(0x{lo:04X}, 0x{hi:04X}),")
        if len(row) == 6:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines.append("];")
    return "\n".join(lines)


def render():
    if unicodedata.unidata_version != UNICODE:
        sys.exit(f"need unicodedata {UNICODE}, have {unicodedata.unidata_version} (use Python 3.14)")
    cf = category("Cf")
    cn = category("Cn")
    di = (expand(OTHER_DI) | cf | expand(VARIATION_SELECTOR)) - white_space()
    di -= expand([(0xFFF9, 0xFFFB), (0x13430, 0x1343F)]) | expand(PCM)
    if merge(di) != DI_EXPECTED:
        sys.exit("derived Default_Ignorable_Code_Point differs from DerivedCoreProperties.txt 16.0")
    parts = [
        "//! Pinned Unicode 16.0 tables for identifier checks (CORE.BUS.PRIN). Generated by",
        "//! `fixtures/core/bus/principal/make_unicode_tables.py` from Python's `unicodedata`",
        "//! 16.0.0 and the PropList.txt / DerivedCoreProperties.txt 16.0 lists it quotes; do not",
        "//! edit by hand. Each table is sorted, inclusive and non-overlapping.",
        "",
        rust_table("FORMAT_RANGES", "Code points of general category Cf (format), Unicode 16.0.", merge(cf)),
        "",
        rust_table("UNASSIGNED_RANGES",
                   "Code points of general category Cn (unassigned, noncharacters included), Unicode 16.0.",
                   merge(cn)),
        "",
        rust_table("DEFAULT_IGNORABLE_RANGES",
                   "Code points with the derived property Default_Ignorable_Code_Point, Unicode 16.0.",
                   merge(di)),
        "",
    ]
    return "\n".join(parts)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = render().encode("utf-8")
    if args.check:
        if OUT.read_bytes() != text:
            sys.exit(f"{OUT} differs from the generator output")
        print("ok")
        return
    OUT.write_bytes(text)
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
