"""Generate fixtures/core/prj/cont/id/v7.json and v5.json (CORE.PRJ.CONT.ID AC-1, AC-3).

Independent reference: expected UUIDs are built here from the RFC 9562 layouts with
Python integers and the standard `uuid` module (SHA-1 for v5), never by running the
Rust code. Two vectors are hand-labelled from RFC 9562 Appendix A (A.4 for v5, A.6 for v7).
CC-BY-4.0 project data.
Run:  python fixtures/core/prj/cont/id/make_fixtures.py

Convention for the 74 random bits of a UUIDv7 (CORE.PRJ.CONT.ID): the source draws one
74-bit value R; rand_a = the top 12 bits of R (R >> 62), rand_b = the low 62 bits.
"""

import json
import uuid
from pathlib import Path

HERE = Path(__file__).resolve().parent


# ------------------------------------------------------------------ UUIDv7

def v7(ts_ms: int, r74: int) -> str:
    assert 0 <= ts_ms < (1 << 48) and 0 <= r74 < (1 << 74)
    rand_a = r74 >> 62
    rand_b = r74 & ((1 << 62) - 1)
    n = (ts_ms << 80) | (0x7 << 76) | (rand_a << 64) | (0b10 << 62) | rand_b
    u = uuid.UUID(int=n)
    assert u.variant == uuid.RFC_4122
    assert (n >> 76) & 0xF == 7
    return str(u)


# RFC 9562 Appendix A.6 example, hand-labelled: unix_ts_ms 0x017F22E279B0,
# rand_a 0xCC3, rand_b 0x18C4DC0C0C07398F -> 017f22e2-79b0-7cc3-98c4-dc0c0c07398f.
RFC_TS = 0x017F22E279B0
RFC_R = (0xCC3 << 62) | 0x18C4DC0C0C07398F
assert v7(RFC_TS, RFC_R) == "017f22e2-79b0-7cc3-98c4-dc0c0c07398f"

steps = [
    ("rfc9562 A.6", RFC_TS, RFC_R),
    ("all zero", 0, 0),
    ("max time, all ones", (1 << 48) - 1, (1 << 74) - 1),
    ("rand_a only", 1731801600000, 0xFFF << 62),
    ("rand_b only", 1731801600000, (1 << 62) - 1),
    ("same ms as previous", 1731801600000, 0x2A5A5A5A5A5A5A5A5A5),
    ("alternating bits", 0xAAAAAAAAAAAA, 0x2AAAAAAAAAAAAAAAAAA),
    ("2026-11-17", 1795392000123, 0x1234567890ABCDEF012),
]
v7_doc = {
    "comment": "CORE.PRJ.CONT.ID AC-1/AC-2. Observations are drawn in order: now_ms then random_bits(74) per ID. "
               "random74 = rand_a (12 bits) << 62 | rand_b (62 bits). Generated by make_fixtures.py. CC-BY-4.0.",
    "steps": [
        {"name": name, "now_ms": str(ts), "random74": "0x%019x" % r, "expected": v7(ts, r)}
        for name, ts, r in steps
    ],
}


# ------------------------------------------------------------------ UUIDv5 over RFC 8785 canonical JSON

def jcs_str(s: str) -> str:
    out = ['"']
    short = {'"': '\\"', '\\': '\\\\', '\b': '\\b', '\t': '\\t', '\n': '\\n', '\f': '\\f', '\r': '\\r'}
    for c in s:
        if c in short:
            out.append(short[c])
        elif ord(c) < 0x20:
            out.append('\\u%04x' % ord(c))
        else:
            out.append(c)
    out.append('"')
    return ''.join(out)


def jcs_num(x) -> str:
    # Only values whose ECMAScript and Python spellings agree are used in the fixture.
    if isinstance(x, bool):
        raise TypeError
    if isinstance(x, int) or (isinstance(x, float) and x.is_integer()):
        assert abs(x) < 1e21
        return str(int(x))
    r = repr(x)
    assert 'e' not in r and 'inf' not in r and 'nan' not in r
    return r


def jcs(v) -> str:
    if v is None:
        return "null"
    if v is True:
        return "true"
    if v is False:
        return "false"
    if isinstance(v, str):
        return jcs_str(v)
    if isinstance(v, (int, float)):
        return jcs_num(v)
    if isinstance(v, list):
        return "[" + ",".join(jcs(i) for i in v) + "]"
    if isinstance(v, dict):
        keys = sorted(v, key=lambda k: k.encode("utf-16-be"))  # RFC 8785 3.2.3: UTF-16 code units
        return "{" + ",".join(jcs_str(k) + ":" + jcs(v[k]) for k in keys) + "}"
    raise TypeError(type(v))


DNS = "6ba7b810-9dad-11d1-80b4-00c04fd430c8"
PROJECT_NS = "0193a6f2-7c3e-7b2a-9d41-5e2f8c1a0b77"

# RFC 9562 Appendix A.4 example, hand-labelled: DNS namespace, name "www.example.com".
assert str(uuid.uuid5(uuid.UUID(DNS), "www.example.com")) == "2ed6657d-e927-568b-95e1-2665a8aea6a2"

inputs = [
    ("template instance", PROJECT_NS,
     {"kind": "template_instance", "template": "017f22e2-79b0-7cc3-98c4-dc0c0c07398f", "index": 3}),
    ("same inputs, other key order", PROJECT_NS,
     {"index": 3, "template": "017f22e2-79b0-7cc3-98c4-dc0c0c07398f", "kind": "template_instance"}),
    ("other namespace", DNS,
     {"kind": "template_instance", "template": "017f22e2-79b0-7cc3-98c4-dc0c0c07398f", "index": 3}),
    ("plain string", PROJECT_NS, "plain string"),
    ("array", PROJECT_NS, ["a", "b", 1, None, True, False]),
    ("nested and non-ASCII", PROJECT_NS, {"é": "x", "z": [1, 2, {"b": None, "a": True}]}),
    ("UTF-16 key order", PROJECT_NS, {"": 1, "\U0001F600": 2, "a": 0}),
    ("control characters", PROJECT_NS, {"s": "tab\tnewline\n\u0001quote\"back\\"}),
    ("numbers", PROJECT_NS, {"half": 0.5, "neg": -7, "hundred": 100.0}),
    ("empty object", PROJECT_NS, {}),
]
v5_doc = {
    "comment": "CORE.PRJ.CONT.ID AC-3. expected = uuid5(namespace, RFC 8785 canonical JSON of inputs). "
               "raw: plain-name vectors (RFC 9562 A.4). Generated by make_fixtures.py. CC-BY-4.0.",
    "cases": [
        {"name": name, "namespace": ns, "inputs": inp, "canonical": jcs(inp),
         "expected": str(uuid.uuid5(uuid.UUID(ns), jcs(inp)))}
        for name, ns, inp in inputs
    ],
    "raw": [
        {"namespace": DNS, "name": "www.example.com", "expected": "2ed6657d-e927-568b-95e1-2665a8aea6a2"},
    ],
}
for c in v5_doc["cases"]:
    assert uuid.UUID(c["expected"]).version == 5

for fname, doc in (("v7.json", v7_doc), ("v5.json", v5_doc)):
    (HERE / fname).write_text(json.dumps(doc, indent=2, ensure_ascii=True) + "\n", encoding="utf-8", newline="\n")
    print("wrote", fname)
