def dump(obj: dict[str, object]) -> bytes:
    return (json.dumps(obj, sort_keys=True, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="Verify committed fixtures match generated bytes.")
    args = ap.parse_args()

    outputs = {
        HERE / "branch-basic" / "project.json": dump(make_branch_basic()),
        HERE / "brief-valid.json": dump(make_brief_valid()),
        HERE / "brief-valid-2.json": dump(make_brief_valid_2()),
        HERE / "brief-bad.json": dump(make_brief_bad()),
    }

    if args.check:
        ok = True
        for path, expected in outputs.items():
            if not path.exists():
                print(f"MISSING: {path}", file=sys.stderr)
                ok = False
                continue
            if path.read_bytes() != expected:
                print(f"DRIFT: {path}", file=sys.stderr)
                ok = False
        return 0 if ok else 1

    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
